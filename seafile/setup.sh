#!/usr/bin/env bash
#
# setup.sh — one-shot deploy of Seafile CE (self-hosted Drive) behind Tailscale.
#
# End state:
#   - Seafile CE 13 + MariaDB + Redis via Docker Compose (restart: unless-stopped
#     => boot-persistent through dockerd, no systemd unit needed)
#   - web listens on 127.0.0.1:LOCAL_PORT only
#   - published tailnet-only at https://<host>.<tailnet>.ts.net:HTTPS_PORT
#   - data under ~/seafile/ (documents/photos live INSIDE Seafile's chunked
#     store — see SETUP.md for the backup story)
#
# Usage:
#   ./setup.sh                              # defaults: local 8081, HTTPS 8443
#   LOCAL_PORT=9081 HTTPS_PORT=10000 ./setup.sh
#
# Requirements: Linux, curl, Docker Engine + Compose v2, Tailscale logged in,
# user in the `docker` group (sudo usermod -aG docker $USER, then re-login).
#
# Idempotent: safe to re-run; an existing .env (holds all secrets) is never
# overwritten. Tailscale HTTPS serve ports must be 443, 8443, or 10000.

set -euo pipefail

LOCAL_PORT="${LOCAL_PORT:-8081}"
HTTPS_PORT="${HTTPS_PORT:-8443}"
SERVICE_DIR="$(cd "$(dirname "$0")" && pwd)"
ENV_FILE="$SERVICE_DIR/.env"
ADMIN_EMAIL="${ADMIN_EMAIL:-admin@localhost}"

info()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
ok()    { printf '\033[1;32m ✓ \033[0m %s\n' "$*"; }
die()   { printf '\033[1;31m ✗ \033[0m %s\n' "$*" >&2; exit 1; }

# ---------------------------------------------------------------- preflight
info "Preflight checks"
[ "$(uname -s)" = "Linux" ] || die "This script targets Linux."
[ "$(id -u)" -ne 0 ] || die "Run as a regular user, not root."
command -v curl >/dev/null || die "curl is required."
command -v docker >/dev/null || die "Docker is not installed. On Ubuntu: sudo apt-get install -y docker.io docker-compose-v2"
command -v tailscale >/dev/null || die "Tailscale is not installed: https://tailscale.com/download"

docker ps >/dev/null 2>&1 || die "Cannot talk to the Docker daemon. Fix: sudo usermod -aG docker $USER, then log out/in (or run this script via: sg docker -c ./setup.sh)"
docker compose version >/dev/null 2>&1 || die "Docker Compose v2 is required (docker compose)."

state="$(tailscale status --json 2>/dev/null | grep -o '"BackendState": *"[^"]*"' | head -1 | cut -d'"' -f4 || true)"
[ "$state" = "Running" ] || die "Tailscale is not up (state: ${state:-unknown}). Run: sudo tailscale up"

case "$HTTPS_PORT" in 443|8443|10000) ;; *) die "Tailscale Serve only supports HTTPS on 443, 8443, or 10000 (got: $HTTPS_PORT)";; esac
ok "Linux + curl + Docker (daemon reachable) + Compose v2 + Tailscale (running)"

host="$(tailscale status --json | grep -o '"DNSName": *"[^"]*"' | head -1 | cut -d'"' -f4 | sed 's/\.$//')"
[ -n "$host" ] || die "Could not determine tailnet DNS name (is MagicDNS enabled?)"

# ---------------------------------------------------------------- .env
if [ -f "$ENV_FILE" ]; then
  ok "Config already exists, leaving untouched: $ENV_FILE"
else
  info "Generating .env (secrets + host config)"
  admin_pw="$(openssl rand -base64 15)"
  cat > "$ENV_FILE" <<EOF
# Generated by setup.sh $(hostname). Holds ALL secrets — never commit, mode 600.
SEAFILE_IMAGE=seafileltd/seafile-mc:13.0-latest
SEAFILE_DB_IMAGE=mariadb:10.11
SEAFILE_REDIS_IMAGE=redis:7-alpine

SEAFILE_VOLUME=$HOME/seafile/data
SEAFILE_MYSQL_VOLUME=$HOME/seafile/mysql

LOCAL_PORT=$LOCAL_PORT
SEAFILE_SERVER_HOSTNAME=$host:$HTTPS_PORT
SEAFILE_SERVER_PROTOCOL=https
TIME_ZONE=$(cat /etc/timezone 2>/dev/null || echo Etc/UTC)

JWT_PRIVATE_KEY=$(openssl rand -hex 32)
SEAFILE_MYSQL_DB_PASSWORD=$(openssl rand -hex 16)
INIT_SEAFILE_MYSQL_ROOT_PASSWORD=$(openssl rand -hex 16)
REDIS_PASSWORD=$(openssl rand -hex 16)

INIT_SEAFILE_ADMIN_EMAIL=$ADMIN_EMAIL
INIT_SEAFILE_ADMIN_PASSWORD=$admin_pw
EOF
  chmod 600 "$ENV_FILE"
  ok "Wrote $ENV_FILE (mode 600)"
fi

mkdir -p "$HOME/seafile/data" "$HOME/seafile/mysql"

# ---------------------------------------------------------------- deploy
info "Starting containers (docker compose up -d) — first run pulls ~1 GB of images"
docker compose --project-directory "$SERVICE_DIR" up -d

info "Waiting for Seafile web UI on 127.0.0.1:$LOCAL_PORT (first init can take a few minutes)"
for i in $(seq 1 60); do
  code="$(curl -s -o /dev/null -w '%{http_code}' "http://127.0.0.1:$LOCAL_PORT/" 2>/dev/null || true)"
  case "$code" in
    2*|3*) ok "Seafile is answering locally (HTTP $code)"; break ;;
  esac
  [ "$i" -eq 60 ] && die "Seafile did not come up. Logs: docker compose --project-directory $SERVICE_DIR logs seafile"
  sleep 5
done

# ------------------------------------------------------- tailscale serve
info "Publishing via Tailscale Serve (HTTPS :$HTTPS_PORT, tailnet only)"
if ! tailscale serve --bg --https="$HTTPS_PORT" "http://127.0.0.1:$LOCAL_PORT" >/dev/null 2>&1; then
  info "Direct serve failed — trying operator grant (needs sudo, one time)"
  sudo tailscale set --operator="$USER"
  until tailscale serve --bg --https="$HTTPS_PORT" "http://127.0.0.1:$LOCAL_PORT"; do
    echo
    info "If Tailscale printed an approval URL above, open it, approve, then press Enter to retry."
    read -r
  done
fi
ok "Tailscale Serve: HTTPS :$HTTPS_PORT -> http://127.0.0.1:$LOCAL_PORT"

# ------------------------------------------------------------ final check
url="https://$host:$HTTPS_PORT"
info "Verifying $url (first request can take ~60s while the TLS cert is minted)"
if curl -fsS -o /dev/null --max-time 90 "$url"; then
  ok "End-to-end check passed"
else
  echo "    Cert may still be minting — try again in a minute: curl -I $url"
fi

echo
printf '\033[1;32mDone.\033[0m Seafile is at \033[1m%s\033[0m (tailnet only).\n' "$url"
echo
echo "Admin login (also in $ENV_FILE):"
grep -E '^INIT_SEAFILE_ADMIN_(EMAIL|PASSWORD)=' "$ENV_FILE" | sed 's/^INIT_SEAFILE_/  /'
echo
echo "Clients: https://www.seafile.com/en/download/  (server URL: $url)"
echo "Manage:  docker compose --project-directory $SERVICE_DIR ps|logs|restart|down"
