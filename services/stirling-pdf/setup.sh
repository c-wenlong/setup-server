#!/usr/bin/env bash
#
# setup.sh — one-shot deploy of Stirling PDF (self-hosted PDF toolbox)
# behind Tailscale. Linux + macOS.
#
# End state:
#   - a single `stirling-pdf` container
#   - published on 127.0.0.1:LOCAL_PORT only (default 8103 — code-server
#     already owns host :8080, Stirling's upstream default)
#   - reachable tailnet-only at https://<host>.<tailnet>.ts.net:HTTPS_PORT
#   - login OFF (upstream defaults to admin/stirling; the tailnet is the
#     access boundary)
#   - boot-persistent via Docker's restart policy (no systemd/launchd)
#
# Usage:
#   ./setup.sh
#   LOCAL_PORT=8104 ./setup.sh            # HTTPS follows LOCAL_PORT
#   LOCAL_PORT=8104 HTTPS_PORT=8104 ./setup.sh
#
# Version: pinned to 2.14.3. Bump STIRLING_PDF_VERSION in .env, then re-run.
#
# Requirements: Linux or macOS, curl, Docker + Compose v2, Tailscale logged in.
#
# Idempotent: safe to re-run; it upgrades the image and repairs the publish.
# An existing .env is never overwritten.

set -euo pipefail

LOCAL_PORT="${LOCAL_PORT:-8103}"
HTTPS_PORT_EXPLICIT="${HTTPS_PORT:+yes}"
HTTPS_PORT="${HTTPS_PORT:-$LOCAL_PORT}"

SERVICE_DIR="$(cd "$(dirname "$0")" && pwd)"
ENV_FILE="$SERVICE_DIR/.env"
STATE="$HOME/services/stirling-pdf"

info()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
ok()    { printf '\033[1;32m ✓ \033[0m %s\n' "$*"; }
warn()  { printf '\033[1;33m ! \033[0m %s\n' "$*"; }
die()   { printf '\033[1;31m ✗ \033[0m %s\n' "$*" >&2; exit 1; }

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# ---------------------------------------------------------------- preflight
OS="$(uname -s)"
info "Preflight checks ($OS)"
case "$OS" in Linux|Darwin) ;; *) die "Unsupported OS: $OS (Linux and macOS only)";; esac
[ "$(id -u)" -ne 0 ] || die "Run as a regular user, not root."
command -v curl >/dev/null || die "curl is required."
if ! command -v docker >/dev/null; then
  [ "$OS" = "Linux" ] && die "Docker is not installed. On Ubuntu: sudo apt-get install -y docker.io docker-compose-v2"
  die "Docker is not installed. On macOS install Docker Desktop or OrbStack."
fi

if command -v tailscale >/dev/null; then
  TAILSCALE="tailscale"
elif [ "$OS" = "Darwin" ] && [ -x "/Applications/Tailscale.app/Contents/MacOS/Tailscale" ]; then
  TAILSCALE="/Applications/Tailscale.app/Contents/MacOS/Tailscale"
else
  die "Tailscale is not installed: https://tailscale.com/download"
fi

if ! docker ps >/dev/null 2>&1; then
  [ "$OS" = "Linux" ] && die "Cannot talk to the Docker daemon. Fix: sudo usermod -aG docker $USER, then log out/in (or run via: sg docker -c ./setup.sh)"
  die "Cannot talk to the Docker daemon. Is Docker Desktop/OrbStack running?"
fi
docker compose version >/dev/null 2>&1 || die "Docker Compose v2 is required (docker compose)."

state="$("$TAILSCALE" status --json 2>/dev/null | grep -o '"BackendState": *"[^"]*"' | head -1 | cut -d'"' -f4 || true)"
[ "$state" = "Running" ] || die "Tailscale is not up (state: ${state:-unknown}). Run: sudo tailscale up (or open the Tailscale app)"

case "$LOCAL_PORT" in ''|*[!0-9]*) die "LOCAL_PORT must be numeric (got: $LOCAL_PORT)";; esac
case "$HTTPS_PORT" in ''|*[!0-9]*) die "HTTPS_PORT must be numeric (got: $HTTPS_PORT)";; esac

ok "$OS + curl + Docker (daemon reachable) + Compose v2 + Tailscale (running)"

TS_HOST="$("$TAILSCALE" status --json 2>/dev/null | grep -o '"DNSName": *"[^"]*"' | head -1 | cut -d'"' -f4 | sed 's/\.$//')"
[ -n "$TS_HOST" ] || die "Could not determine tailnet DNS name (is MagicDNS enabled?)"
ok "Tailnet name: $TS_HOST"

avail_mb=""
if [ -r /proc/meminfo ]; then
  avail_mb="$(sed -n 's/^MemAvailable: *\([0-9]*\) kB/\1/p' /proc/meminfo)"
  avail_mb="$(( avail_mb / 1024 ))"
fi
if [ -n "${avail_mb:-}" ] && [ "$avail_mb" -lt 600 ]; then
  warn "Only ~${avail_mb} MB RAM available. Stirling PDF is Java + LibreOffice (cap ${STIRLING_MEM_LIMIT:-1536m}); unload ollama if it gets OOM-killed."
fi

# ---------------------------------------------------------------- .env
if [ -f "$ENV_FILE" ]; then
  ok "Config already exists, leaving untouched: $ENV_FILE"
else
  info "Writing .env"
  tz="Etc/UTC"
  if [ -L /etc/localtime ]; then
    tz="$(readlink /etc/localtime | sed 's#.*/zoneinfo/##')"
  elif [ -f /etc/timezone ]; then
    tz="$(cat /etc/timezone)"
  fi
  cat > "$ENV_FILE" <<EOF
# Generated by setup.sh. Gitignored; mode 600.
# Docker Compose interpolates this file from the project directory.

# Pinned. Official floats \`latest\`. To upgrade: bump, then ./setup.sh.
STIRLING_PDF_VERSION=2.14.3

LOCAL_PORT=$LOCAL_PORT
TZ=$tz

# Runtime state. Moving a path means moving the directory too.
STIRLING_DATA=$STATE
STIRLING_UID=$(id -u)
STIRLING_GID=$(id -g)

# Public identity. SYSTEM_FRONTENDURL is the tailnet HTTPS URL, no trailing
# slash. If the machine is renamed or the HTTPS port moves, edit it and
# re-run — setup.sh warns when it drifts.
SYSTEM_FRONTENDURL=https://$TS_HOST:$HTTPS_PORT

# Login is OFF. Upstream defaults to admin/stirling — a well-known pair.
# The tailnet is the access boundary. To turn login on: set
# SECURITY_ENABLELOGIN=true and SECURITY_INITIALLOGIN_USERNAME /
# SECURITY_INITIALLOGIN_PASSWORD, then ./setup.sh.
SECURITY_ENABLELOGIN=false

STIRLING_MEM_LIMIT=1536m
SYSTEM_MAXFILESIZE=100
SYSTEM_DEFAULTLOCALE=en-US
EOF
  chmod 600 "$ENV_FILE"
  ok "Wrote $ENV_FILE"
fi

# Read back: an existing .env is the source of truth for ports, paths and
# credentials, so a re-run can never silently move a live deployment.
REQUESTED_PORT="$LOCAL_PORT"
set -a; . "$ENV_FILE"; set +a
DATA_DIR="${STIRLING_DATA:?STIRLING_DATA missing from $ENV_FILE}"
SYSTEM_FRONTENDURL="${SYSTEM_FRONTENDURL:?SYSTEM_FRONTENDURL missing from $ENV_FILE}"
SECURITY_ENABLELOGIN="${SECURITY_ENABLELOGIN:-false}"
if [ "$LOCAL_PORT" != "$REQUESTED_PORT" ]; then
  warn "LOCAL_PORT=$REQUESTED_PORT ignored — the existing $ENV_FILE says $LOCAL_PORT. Edit .env and re-run to move the port."
fi
[ -n "$HTTPS_PORT_EXPLICIT" ] || HTTPS_PORT="$LOCAL_PORT"

WANT_URL="https://$TS_HOST:$HTTPS_PORT"
if [ "$SYSTEM_FRONTENDURL" != "$WANT_URL" ]; then
  warn "SYSTEM_FRONTENDURL in .env is $SYSTEM_FRONTENDURL but this box now answers to $WANT_URL."
  warn "  Asset URLs and CORS will point at the old address. Fix: set SYSTEM_FRONTENDURL=$WANT_URL in $ENV_FILE, then re-run."
fi

case "$SECURITY_ENABLELOGIN" in
  true|TRUE|yes|YES|1)
    warn "SECURITY_ENABLELOGIN is on. If you left the upstream default password (stirling), change it now. Anyone on the tailnet can log in as that admin."
    ;;
esac

mkdir -p "$DATA_DIR/configs" "$DATA_DIR/logs" "$DATA_DIR/tessdata" \
  "$DATA_DIR/pipeline" "$DATA_DIR/customFiles"

avail_kb="$(df -Pk "$DATA_DIR" | awk 'NR==2{print $4}')"
if [ "${avail_kb:-0}" -lt 1048576 ]; then
  warn "$(( avail_kb / 1048576 )) GB free at $DATA_DIR — PDF conversions write temp files."
else
  ok "$(( avail_kb / 1048576 )) GB free at $DATA_DIR"
fi

# ---------------------------------------------------------------- deploy
COMPOSE=(docker compose --project-directory "$SERVICE_DIR")

info "Starting Stirling PDF (docker compose up -d) — first run pulls the image"
"${COMPOSE[@]}" up -d

info "Waiting for Stirling PDF on 127.0.0.1:$LOCAL_PORT (first boot can take a minute)"
for i in $(seq 1 90); do
  if curl -fsS -o /dev/null "http://127.0.0.1:$LOCAL_PORT/api/v1/info/status" 2>/dev/null; then
    ok "Stirling PDF is answering locally"
    break
  fi
  [ "$i" -eq 90 ] && die "Stirling PDF did not come up. Logs: docker compose --project-directory $SERVICE_DIR logs stirling-pdf"
  sleep 3
done

# ------------------------------------------------------- tailscale serve
info "Publishing via Tailscale Serve (HTTPS :$HTTPS_PORT -> 127.0.0.1:$LOCAL_PORT)"
if ! "$TAILSCALE" serve --bg --https="$HTTPS_PORT" "http://127.0.0.1:$LOCAL_PORT" >/dev/null 2>&1; then
  if [ "$OS" = "Linux" ]; then
    info "Direct serve failed — trying operator grant (needs sudo, one time)"
    sudo tailscale set --operator="$USER"
  fi
  until "$TAILSCALE" serve --bg --https="$HTTPS_PORT" "http://127.0.0.1:$LOCAL_PORT"; do
    echo
    info "If Tailscale printed an approval URL above, open it, approve, then press Enter to retry."
    read -r
  done
fi
ok "Tailscale Serve: HTTPS :$HTTPS_PORT -> http://127.0.0.1:$LOCAL_PORT"

# ------------------------------------------------------------ final check
url="https://$TS_HOST:$HTTPS_PORT"
info "Verifying $url/api/v1/info/status (first request can take ~60s while the TLS cert is minted)"
if curl -fsS -o /dev/null --max-time 90 "$url/api/v1/info/status"; then
  ok "End-to-end HTTPS check passed"
else
  warn "No answer on $url/api/v1/info/status yet — the cert may still be minting. Retry in a minute: curl $url/api/v1/info/status"
fi

# A 200 on /api/v1/info/status does not prove login is off. Upstream's
# default admin/stirling is a well-known pair. If / still bounces to a
# login form, say so loudly.
login_code="$(curl -sS -o "$WORK/login.html" -w '%{http_code}' --max-time 30 \
  -L "$url/login" 2>/dev/null || echo 000)"
login_body="$(cat "$WORK/login.html" 2>/dev/null || true)"
home_hdr="$(curl -sS -o /dev/null -D - --max-time 15 "$url/" 2>/dev/null || true)"
case "$home_hdr" in
  *[Ll]ocation:*/login*)
    warn "GET / redirects to /login. SECURITY_ENABLELOGIN is not off. If the password is still the upstream default (stirling), change it immediately."
    ;;
esac
case "$login_code" in
  200)
    case "$login_body" in
      *[Pp]assword*[Uu]sername*|*[Uu]sername*[Pp]assword*|*"Sign in"*|*"sign in"*)
        warn "GET /login still looks like a login form (HTTP $login_code). SECURITY_ENABLELOGIN in $ENV_FILE is not taking effect, or login was turned on in the UI."
        ;;
      *)
        ok "No login form on /login"
        ;;
    esac
    ;;
  404|302|301|303|307|308)
    ok "Login is not an open form (HTTP $login_code)"
    ;;
  *)
    warn "Could not check /login (HTTP $login_code). Confirm the UI yourself: $url"
    ;;
esac

echo
printf '\033[1;32mDone.\033[0m Stirling PDF is at \033[1m%s\033[0m (tailnet only).\n' "$url"
echo
echo "  Login is off — the tailnet is the access boundary."
echo "  Upgrade: bump STIRLING_PDF_VERSION in $ENV_FILE then ./setup.sh"
echo
echo "Backups: nothing backs this box up. Keep $ENV_FILE off-box with:"
echo "    $DATA_DIR/configs"
echo
echo "Manage:  docker compose --project-directory $SERVICE_DIR ps|logs|restart|down"
echo "Upgrade: edit STIRLING_PDF_VERSION in .env, then ./setup.sh"
exit 0
