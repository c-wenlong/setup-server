#!/usr/bin/env bash
#
# setup.sh — one-shot deploy of ntfy-control: start/stop server services from
# the ntfy phone app. Linux + macOS.
#
# End state:
#   - control_listener.py running as a systemd user unit (launchd on macOS),
#     subscribed to the local ntfy server's CONTROL_TOPIC
#   - send `stop seafile` / `start seafile` / `status` etc. from the ntfy app
#     to the control topic; replies arrive on the alerts topic
#   - stopping a service auto-pauses its Uptime Kuma monitor (best-effort)
#
# No new ports, nothing published: the listener talks to ntfy over loopback
# and the tailnet-only ntfy server is the (only) way in.
#
# Usage:
#   ./setup.sh
#   CONTROL_TOPIC=ops ./setup.sh
#
# Idempotent: re-running refreshes the listener code + unit; an existing
# .env is never overwritten.

set -euo pipefail

NTFY_PORT="${NTFY_PORT:-3003}"
CONTROL_TOPIC="${CONTROL_TOPIC:-control}"
REPLY_TOPIC="${REPLY_TOPIC:-alerts}"
SERVICE_DIR="$(cd "$(dirname "$0")" && pwd)"
ENV_FILE="$SERVICE_DIR/.env"

# shellcheck source=../../lib/common.sh
. "$SERVICE_DIR/../../lib/common.sh"

# ---------------------------------------------------------------- preflight
detect_os
info "Preflight checks ($OS)"
refuse_root
command -v curl >/dev/null || die "curl is required."
command -v python3 >/dev/null || die "python3 is required (runs the listener)."
[ "$OS" = "Linux" ] && { command -v systemctl >/dev/null || die "systemd is required on Linux."; }

if ! command -v docker >/dev/null; then
  die "Docker is required (the listener starts/stops containers)."
fi
docker ps >/dev/null 2>&1 || die "Cannot talk to the Docker daemon."

curl -fsS -o /dev/null "http://127.0.0.1:$NTFY_PORT/v1/health" 2>/dev/null \
  || die "ntfy is not reachable on 127.0.0.1:$NTFY_PORT — deploy services/monitoring/ first."

command -v uv >/dev/null || warn "uv not found — Kuma monitor auto-pause will be skipped (everything else works)."
ok "$OS + curl + python3 + Docker + ntfy (healthy)"

# Tailnet hostname for notification action buttons (tapped on the phone, so
# they must carry the tailnet URL, not loopback). Best-effort.
TS_HOST=""
if command -v tailscale >/dev/null; then
  TAILSCALE="tailscale"
elif [ "$OS" = "Darwin" ] && [ -x "/Applications/Tailscale.app/Contents/MacOS/Tailscale" ]; then
  TAILSCALE="/Applications/Tailscale.app/Contents/MacOS/Tailscale"
fi
if [ -n "${TAILSCALE:-}" ]; then
  TS_HOST="$(tailnet_host)"
fi
if [ -n "$TS_HOST" ]; then
  PUBLIC_NTFY_URL="https://$TS_HOST:$NTFY_PORT"
else
  warn "Could not determine tailnet hostname — notification buttons will only work on the box itself."
  PUBLIC_NTFY_URL="http://127.0.0.1:$NTFY_PORT"
fi

# ---------------------------------------------------------------- .env
# The listener's ntfy credentials live in monitoring/.env (the auth db is
# created there) and are copied in here as NTFY_USER/NTFY_PASS.
MON_ENV="$(cd "$SERVICE_DIR/.." && pwd)/monitoring/.env"
env_val() { sed -n "s/^$1=//p" "$2" 2>/dev/null | head -1; }

if [ -f "$ENV_FILE" ]; then
  ok "Config already exists, leaving untouched: $ENV_FILE"
else
  info "Writing .env (topics + paths + ntfy credentials)"
  cat > "$ENV_FILE" <<EOF
# Generated by setup.sh. Gitignored; mode 600 (holds the ntfy login). Edit +
# re-run setup.sh to apply.
NTFY_BASE_URL=http://127.0.0.1:$NTFY_PORT
PUBLIC_NTFY_URL=$PUBLIC_NTFY_URL
CONTROL_TOPIC=$CONTROL_TOPIC
REPLY_TOPIC=$REPLY_TOPIC
KUMA_ENV_FILE=$MON_ENV
SERVICE_HOME=$HOME/services/ntfy-control
TOOL_DIR=$(dirname "$(command -v uv 2>/dev/null || echo "$HOME/.local/bin/uv")")
# The ntfy account this listener authenticates as (read on CONTROL_TOPIC,
# write on REPLY_TOPIC). Copied from NTFY_CONTROL_* in monitoring/.env —
# change it there (and re-run monitoring/setup.sh), not here.
NTFY_USER=$(env_val NTFY_CONTROL_USER "$MON_ENV")
NTFY_PASS=$(env_val NTFY_CONTROL_PASS "$MON_ENV")
EOF
  chmod 600 "$ENV_FILE"
  ok "Wrote $ENV_FILE"
fi

# Migration: add PUBLIC_NTFY_URL to .envs generated before action buttons.
if ! grep -q '^PUBLIC_NTFY_URL=' "$ENV_FILE"; then
  echo "PUBLIC_NTFY_URL=$PUBLIC_NTFY_URL" >> "$ENV_FILE"
  ok "Added PUBLIC_NTFY_URL to existing .env"
fi

# Migration: add the ntfy credentials to .envs generated before ntfy auth.
# Empty values mean monitoring is older still — the probe below dies with
# instructions if the server actually requires auth.
if ! grep -q '^NTFY_USER=' "$ENV_FILE"; then
  {
    echo "NTFY_USER=$(env_val NTFY_CONTROL_USER "$MON_ENV")"
    echo "NTFY_PASS=$(env_val NTFY_CONTROL_PASS "$MON_ENV")"
  } >> "$ENV_FILE"
  ok "Added NTFY_USER/NTFY_PASS to existing .env (from monitoring/.env)"
fi
# Credentials live here now — lock down even a pre-auth .env we just migrated.
chmod 600 "$ENV_FILE"

CONTROL_TOPIC="$(env_val CONTROL_TOPIC "$ENV_FILE")"
REPLY_TOPIC="$(env_val REPLY_TOPIC "$ENV_FILE")"
SERVICE_HOME="$(env_val SERVICE_HOME "$ENV_FILE")"
TOOL_DIR="$(env_val TOOL_DIR "$ENV_FILE")"
NTFY_USER="$(env_val NTFY_USER "$ENV_FILE")"
NTFY_PASS="$(env_val NTFY_PASS "$ENV_FILE")"

# ------------------------------------------------------------- ntfy auth
# The listener needs credentials iff the ntfy server denies anonymous
# access. A poll on the control topic proves which: 200 means open, 401/403
# means auth — in which case the stored credentials must also work, or the
# subscribe loop would sit there being refused forever.
PROBE="http://127.0.0.1:$NTFY_PORT/$CONTROL_TOPIC/json?poll=1"
code="$(curl -s -o /dev/null -w '%{http_code}' "$PROBE" || true)"
case "$code" in
  200)
    [ -n "$NTFY_USER" ] \
      || ok "ntfy accepts anonymous access — no credentials needed"
    ;;
  401|403)
    if [ -z "$NTFY_USER" ] || [ -z "$NTFY_PASS" ]; then
      die "ntfy on :$NTFY_PORT requires auth, but $ENV_FILE has no NTFY_USER/NTFY_PASS — re-run services/monitoring/setup.sh first (it creates the 'control' account and writes it to .env), then re-run this."
    fi
    check="$(curl -s -o /dev/null -w '%{http_code}' -u "$NTFY_USER:$NTFY_PASS" "$PROBE" || true)"
    [ "$check" = "200" ] \
      || die "ntfy rejected the NTFY_USER/NTFY_PASS in $ENV_FILE (HTTP $check). The account is created by services/monitoring/setup.sh — fix NTFY_CONTROL_* there, mirror it into .env, then re-run."
    ok "ntfy auth verified for user '$NTFY_USER'"
    ;;
  *)
    warn "Could not probe ntfy auth on the control topic (HTTP ${code:-000}) — continuing; the listener retries anyway."
    ;;
esac

# ------------------------------------------------------------ install code
info "Installing listener -> $SERVICE_HOME/bin/"
mkdir -p "$SERVICE_HOME/bin"
cp "$SERVICE_DIR/control_listener.py" "$SERVICE_DIR/kuma_toggle.py" "$SERVICE_HOME/bin/"
chmod +x "$SERVICE_HOME/bin/control_listener.py"
ok "Listener installed"

# ------------------------------------------------------------ service
if [ "$OS" = "Linux" ]; then
  UNIT="$HOME/.config/systemd/user/ntfy-control.service"
  info "Installing systemd user service"
  mkdir -p "$(dirname "$UNIT")"
  # The user-level systemd manager bakes in supplementary groups at its own
  # start — if the docker-group grant is newer, services it spawns can't use
  # the socket. sg re-acquires the group from /etc/group at exec time.
  EXEC="/usr/bin/env python3 $SERVICE_HOME/bin/control_listener.py"
  if id -nG | grep -qw docker && command -v sg >/dev/null; then
    EXEC="$(command -v sg) docker -c '/usr/bin/env python3 $SERVICE_HOME/bin/control_listener.py'"
  fi
  cat > "$UNIT" <<EOF
[Unit]
Description=ntfy-control (start/stop services via ntfy messages)
After=network.target

[Service]
Type=exec
EnvironmentFile=$ENV_FILE
Environment=PATH=$TOOL_DIR:/usr/local/bin:/usr/bin:/bin
ExecStart=$EXEC
Restart=always
RestartSec=5

[Install]
WantedBy=default.target
EOF
  systemctl --user daemon-reload
  systemctl --user enable ntfy-control >/dev/null 2>&1
  systemctl --user restart ntfy-control
  ok "Service enabled and (re)started"

  if [ "$(loginctl show-user "$USER" -p Linger --value 2>/dev/null)" = "yes" ]; then
    ok "Lingering already enabled"
  else
    info "Enabling lingering (needs sudo, one time)"
    sudo loginctl enable-linger "$USER"
    ok "Lingering enabled"
  fi
else
  PLIST="$HOME/Library/LaunchAgents/com.ntfy-control.listener.plist"
  info "Installing launchd LaunchAgent"
  mkdir -p "$(dirname "$PLIST")" "$HOME/Library/Logs"
  # .env values go into XML verbatim — escape & < > so a value containing
  # one (a password, a URL query) can't produce a malformed plist. python3
  # is already a hard dependency (it runs the listener).
  ENV_XML="$(python3 - "$ENV_FILE" <<'PY'
import re, sys
from xml.sax.saxutils import escape
with open(sys.argv[1], encoding="utf-8") as fh:
    for line in fh:
        m = re.match(r"^([A-Z_]+)=(.*)$", line.rstrip("\n"))
        if m:
            print("    <key>%s</key><string>%s</string>" % (m.group(1), escape(m.group(2))))
PY
)"
  cat > "$PLIST" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>com.ntfy-control.listener</string>
  <key>ProgramArguments</key>
  <array><string>/usr/bin/env</string><string>python3</string><string>$SERVICE_HOME/bin/control_listener.py</string></array>
  <key>EnvironmentVariables</key>
  <dict>
$ENV_XML
    <key>PATH</key><string>$TOOL_DIR:/usr/local/bin:/usr/bin:/bin</string>
  </dict>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>StandardOutPath</key><string>$HOME/Library/Logs/ntfy-control.log</string>
  <key>StandardErrorPath</key><string>$HOME/Library/Logs/ntfy-control.log</string>
</dict>
</plist>
EOF
  launchctl bootout "gui/$(id -u)/com.ntfy-control.listener" 2>/dev/null || true
  launchctl bootstrap "gui/$(id -u)" "$PLIST"
  ok "LaunchAgent loaded (logs: ~/Library/Logs/ntfy-control.log)"
fi

# ------------------------------------------------------------ final check
if [ "$OS" = "Linux" ]; then
  sleep 1
  systemctl --user is-active ntfy-control >/dev/null 2>&1 \
    || die "Listener is not running. Logs: journalctl --user -u ntfy-control"
  ok "Listener is running"
fi

# ------------------------------------------------------- phone bootstrap
# Publish the button menu so a subscribed phone lands on the control panel
# immediately (the iOS app can't compose messages, so this is its entry).
# The publish authenticates as the listener's own account — the same ACL
# (read-write on the control topic) covers it.
panel_url="http://127.0.0.1:$NTFY_PORT/$CONTROL_TOPIC"
publish_panel() {
  if [ -n "$NTFY_USER" ]; then
    curl -fsS -o /dev/null -u "$NTFY_USER:$NTFY_PASS" -d "panel" "$panel_url"
  else
    curl -fsS -o /dev/null -d "panel" "$panel_url"
  fi
}
if publish_panel 2>/dev/null; then
  ok "Control panel published to topic '$REPLY_TOPIC' — check your phone"
else
  warn "Could not publish the control panel — send it later: curl -u $NTFY_USER:<NTFY_PASS from .env> -d panel $panel_url"
fi

# ntfy has no subscriber-listing API, and iOS delivery rides the ntfy.sh
# push relay (no persistent connection) — so the best available "is a phone
# even able to connect?" signal is whether one exists on the tailnet.
phone_peer=""
if [ -n "${TAILSCALE:-}" ]; then
  phone_peer="$("$TAILSCALE" status --json 2>/dev/null | grep -oE '"OS": *"(iOS|android)"' | head -1 || true)"
fi

echo
printf '\033[1;32mDone.\033[0m Control the server from the ntfy app.\n'
echo
if [ -z "$phone_peer" ]; then
  warn "No phone detected on your tailnet — to receive alerts and the control panel:"
  echo "     1. Install Tailscale on the phone and log in to this tailnet"
  echo "     2. Install the ntfy app"
  echo "     3. Add subscription: topic '$REPLY_TOPIC', tap 'Use another server',"
  echo "        server URL https://${TS_HOST:-<tailnet-host>}:$NTFY_PORT, and enter"
  echo "        username/password — NTFY_PHONE_USER / NTFY_PHONE_PASS in"
  echo "        $(cd "$SERVICE_DIR/.." && pwd)/monitoring/.env (auth is deny-all now;"
  echo "        anonymous subscriptions get nothing)"
  echo "     4. Re-run ./setup.sh (or open https://${TS_HOST:-<tailnet-host>}:$NTFY_PORT/$CONTROL_TOPIC/publish?message=panel"
  echo "        and log in) to repost the control panel"
else
  ok "Phone found on the tailnet ($phone_peer) — if no notification arrived, subscribe to"
  echo "     topic '$REPLY_TOPIC' in the ntfy app with server https://${TS_HOST:-<tailnet-host>}:$NTFY_PORT"
  echo "     using NTFY_PHONE_USER / NTFY_PHONE_PASS from monitoring/.env"
fi
echo
echo "From the panel: tap [start]/[stop]/[restart] to pick a service; typed"
echo "commands (Android/web app) work too: status | panel | stop seafile | ..."
# Derived from the shared registry rather than hard-coded: app/web/services.json
# is the single source of truth for what is controllable, read by both this
# listener and the launcher's web UI. A hard-coded list here went stale the
# moment services were added.
echo "  (services: $(python3 - <<'PY' 2>/dev/null || echo 'see app/web/services.json'
import json, os, sys
p = os.path.join(os.path.dirname(os.path.abspath("$0")), "..", "..", "app", "web", "services.json")
try:
    d = json.load(open(p))
except Exception:
    sys.exit(1)
svcs = d["services"] if isinstance(d, dict) and "services" in d else d
names = [s["key"] for s in svcs
         if isinstance(s.get("control"), dict) and not s["control"].get("locked")]
print(", ".join(sorted(names)) if names else "none found")
PY
))"
echo
if [ "$OS" = "Linux" ]; then
  echo "Manage: systemctl --user status|restart ntfy-control"
  echo "Logs:   journalctl --user -u ntfy-control -f"
else
  echo "Logs: tail -f ~/Library/Logs/ntfy-control.log"
fi
