#!/usr/bin/env bash
#
# setup.sh — one-shot deploy of Hermes Agent (Nous Research's self-improving
# AI agent) behind Tailscale. Linux + macOS.
#
# End state:
#   - a single `hermes-agent` container (official nousresearch/hermes-agent
#     image) running `gateway run` under s6 supervision
#   - the web dashboard on 127.0.0.1:LOCAL_PORT behind basic auth, published
#     tailnet-only at https://<host>.<tailnet>.ts.net:HTTPS_PORT
#   - the OpenAI-compatible API server on 127.0.0.1:API_PORT (key-gated,
#     loopback only — for other services on this box, not Serve-published)
#   - all agent state (config, keys, sessions, skills, memories) in
#     ~/services/hermes-agent/data
#   - boot-persistent via Docker's restart policy (no systemd/launchd)
#
# Usage:
#   ./setup.sh                            # dashboard 9119, API 8642
#   LOCAL_PORT=9120 ./setup.sh            # HTTPS follows LOCAL_PORT
#   API_PORT=8643 LOCAL_PORT=9120 ./setup.sh
#
# Requirements: Linux or macOS, curl, Docker + Compose v2, Tailscale
# logged in. Sudo is needed at most once on Linux (tailscale operator).
#
# Idempotent: safe to re-run; it upgrades the image and repairs the publish.
# An existing .env is never overwritten, and the data dir is never touched
# beyond being created.
#
# This deploy is independent of a native Hermes install: a `hermes` CLI,
# ~/.hermes, or a hermes-gateway systemd unit found on the box are reported
# and left exactly as they are. The two share nothing — separate config,
# sessions and skills — and channels must be configured in each.

set -euo pipefail

LOCAL_PORT="${LOCAL_PORT:-9119}"
API_PORT="${API_PORT:-8642}"
# The HTTPS port follows the local port unless set explicitly (the forgejo
# convention), so overriding only LOCAL_PORT cannot split the two. Whether it
# was explicit is remembered for the .env read-back below.
HTTPS_PORT_EXPLICIT="${HTTPS_PORT:+yes}"
HTTPS_PORT="${HTTPS_PORT:-$LOCAL_PORT}"

SERVICE_DIR="$(cd "$(dirname "$0")" && pwd)"
ENV_FILE="$SERVICE_DIR/.env"
STATE="$HOME/services/hermes-agent"

# shellcheck source=../../lib/common.sh
. "$SERVICE_DIR/../../lib/common.sh"

# 32 hex chars: [A-Za-z0-9]-safe, so it survives .env, shell quoting and
# HTTP basic auth without escaping.
randhex() {
  if command -v python3 >/dev/null 2>&1; then
    python3 -c 'import secrets; print(secrets.token_hex(16))'
  else
    od -An -tx1 -N16 /dev/urandom | tr -d ' \n'
    echo
  fi
}

# ---------------------------------------------------------------- preflight
detect_os
info "Preflight checks ($OS)"
refuse_root
command -v curl >/dev/null || die "curl is required."
resolve_tailscale
require_docker_compose
require_tailscale_up
require_numeric LOCAL_PORT API_PORT HTTPS_PORT

ok "$OS + curl + Docker (daemon reachable) + Compose v2 + Tailscale (running)"

TS_HOST="$(tailnet_host)"
[ -n "$TS_HOST" ] || die "Could not determine tailnet DNS name (is MagicDNS enabled?)"
ok "Tailnet name: $TS_HOST"

# --------------------------------------- inspect an existing native install
# Report only. This deploy mounts ~/services/hermes-agent/data, never
# ~/.hermes, and runs no systemd unit, so the two cannot fight over config
# or the gateway unit file.
if [ -d "$HOME/.hermes" ] || command -v hermes >/dev/null 2>&1; then
  warn "A native Hermes install was found (${HOME}/.hermes or a hermes on PATH)."
  warn "  This container is independent: own data dir, own config, own channels."
fi
if [ "$OS" = "Linux" ] && [ -f "$HOME/.config/systemd/user/hermes-gateway.service" ]; then
  warn "hermes-gateway.service exists and is left alone — this deploy is the"
  warn "  Docker container 'hermes-agent', a separate gateway on separate ports."
fi

# ---------------------------------------------------------------- .env
if [ -f "$ENV_FILE" ]; then
  ok "Config already exists, leaving untouched: $ENV_FILE"
else
  info "Writing .env (generated dashboard password + API key)"
  tz="Etc/UTC"
  if [ -L /etc/localtime ]; then
    tz="$(readlink /etc/localtime | sed 's#.*/zoneinfo/##')"
  fi
  # umask 077 so the file is private the moment it exists — a chmod after the
  # write would leave a window where another local account could read it.
  ( umask 077; cat > "$ENV_FILE" <<EOF
# Generated by setup.sh. Gitignored; mode 600.
# Docker Compose reads this file from the project directory for interpolation.
# It is NOT passed to the container as env_file.

# Official image. 'latest'/'stable' track the stable release gate; v* tags
# pin a release.
HERMES_VERSION=v0.22.5

LOCAL_PORT=$LOCAL_PORT
API_PORT=$API_PORT
TZ=$tz

# All agent state: config, API keys, sessions, skills, memories. The only
# thing here worth backing up; moving it means moving the directory too.
# Double quotes keep a path with spaces valid for both `set -a; .` and Compose.
HERMES_DATA="$STATE/data"
HERMES_UID=$(id -u)
HERMES_GID=$(id -g)

# Web dashboard login. The tailnet is the real boundary; this is the second
# gate Hermes requires on a non-loopback bind. Changing the password here and
# re-running setup.sh rotates it (the secret invalidates old sessions).
HERMES_DASHBOARD_USERNAME=admin
HERMES_DASHBOARD_PASSWORD=$(randhex)
HERMES_DASHBOARD_SECRET=$(randhex)

# OpenAI-compatible API server on 127.0.0.1:$API_PORT, for other services on
# this box (Open WebUI, n8n). Not published on the tailnet.
API_SERVER_KEY=$(randhex)
EOF
  )
  if [ -n "$HTTPS_PORT_EXPLICIT" ]; then
    # An explicit publish port stops following LOCAL_PORT, so it must be
    # recorded — the launcher tile reads this file for the tile URL.
    printf '\n# Explicitly set at install: the tailnet publish port, which no longer\n# follows LOCAL_PORT. Delete this line to resume following it.\nHTTPS_PORT=%s\n' \
      "$HTTPS_PORT" >> "$ENV_FILE"
  fi
  chmod 600 "$ENV_FILE"
  ok "Wrote $ENV_FILE"
fi

# Read back: an existing .env is the source of truth for ports and paths, so
# a re-run can never silently move a live deployment.
REQUESTED_PORT="$LOCAL_PORT"
REQUESTED_API_PORT="$API_PORT"
REQUESTED_HTTPS_PORT="${HTTPS_PORT_EXPLICIT:+$HTTPS_PORT}"
# Unset first, so a post-source value can only have come from .env — then
# every assignment form the shell accepts (export, leading whitespace)
# counts as recorded, not just a literal `HTTPS_PORT=` at column 0.
unset HTTPS_PORT
set -a; . "$ENV_FILE"; set +a
DATA_DIR="${HERMES_DATA:?HERMES_DATA missing from $ENV_FILE}"
if [ "$LOCAL_PORT" != "$REQUESTED_PORT" ]; then
  warn "LOCAL_PORT=$REQUESTED_PORT ignored — the existing $ENV_FILE says $LOCAL_PORT. Edit .env and re-run to move the port."
fi
if [ "$API_PORT" != "$REQUESTED_API_PORT" ]; then
  warn "API_PORT=$REQUESTED_API_PORT ignored — the existing $ENV_FILE says $API_PORT. Edit .env and re-run to move the port."
fi
if [ -n "${HTTPS_PORT+x}" ]; then
  # .env already decided the publish port (an earlier explicit override);
  # an explicit value on this re-run is as ignored as LOCAL_PORT is.
  if [ -n "$HTTPS_PORT_EXPLICIT" ] && [ "$HTTPS_PORT" != "$REQUESTED_HTTPS_PORT" ]; then
    warn "HTTPS_PORT=$REQUESTED_HTTPS_PORT ignored — the existing $ENV_FILE says $HTTPS_PORT. Edit .env and re-run to move the publish port."
  fi
elif [ -n "$HTTPS_PORT_EXPLICIT" ]; then
  # First explicit override on a re-run: apply it and record it so the
  # launcher tile and teardown see the real publish port. The leading
  # newline keeps a .env with no trailing newline parseable.
  HTTPS_PORT="$REQUESTED_HTTPS_PORT"
  printf '\n# Explicitly set on re-run: the tailnet publish port, which no longer\n# follows LOCAL_PORT. Delete this line to resume following it.\nHTTPS_PORT=%s\n' \
    "$HTTPS_PORT" >> "$ENV_FILE"
  ok "Recorded HTTPS_PORT=$HTTPS_PORT in $ENV_FILE"
else
  # No recorded publish port: HTTPS keeps following the local port .env settled on.
  HTTPS_PORT="$LOCAL_PORT"
fi
require_numeric HTTPS_PORT

mkdir -p "$STATE" "$DATA_DIR"
ok "Data dir ready: $DATA_DIR"

# ---------------------------------------------------------------- deploy
COMPOSE=(docker compose --project-directory "$SERVICE_DIR")

info "Starting Hermes Agent (docker compose up -d) — first run pulls the image"
"${COMPOSE[@]}" up -d

info "Waiting for the dashboard on 127.0.0.1:$LOCAL_PORT (first boot writes the initial config)"
# The basic-auth gate sits in front of every page once the container binds
# non-loopback, so probe with the .env credentials: anonymous curl sees a 401
# (or a login redirect, which also passes). Either way an authed 2xx/3xx is
# the real "the dashboard is serving" signal.
dash_up=""
for _i in $(seq 1 60); do
  if curl -fsS -o /dev/null \
      -u "$HERMES_DASHBOARD_USERNAME:$HERMES_DASHBOARD_PASSWORD" \
      "http://127.0.0.1:$LOCAL_PORT/" 2>/dev/null; then
    dash_up=1
    break
  fi
  sleep 3
done
[ -n "$dash_up" ] \
  || die "Hermes did not come up. Logs: docker compose --project-directory $SERVICE_DIR logs gateway"
ok "Dashboard is answering locally"

info "Waiting for the API server on 127.0.0.1:$API_PORT"
if wait_http "http://127.0.0.1:$API_PORT/health" 20 3; then
  ok "API server is answering locally"
else
  warn "No answer on 127.0.0.1:$API_PORT/health yet — the API may still be starting (the dashboard is up). Logs: docker compose --project-directory $SERVICE_DIR logs gateway"
fi

# ------------------------------------------------------- tailscale serve
info "Publishing the dashboard via Tailscale Serve (HTTPS :$HTTPS_PORT, tailnet only)"
ts_serve_publish "$HTTPS_PORT" "http://127.0.0.1:$LOCAL_PORT"

# ------------------------------------------------------------ final check
url="https://$TS_HOST:$HTTPS_PORT"
info "Verifying $url (first request can take ~60s while the TLS cert is minted)"
if curl -fsS -o /dev/null --max-time 90 \
    -u "$HERMES_DASHBOARD_USERNAME:$HERMES_DASHBOARD_PASSWORD" "$url/"; then
  ok "End-to-end HTTPS check passed"
else
  warn "No answer on $url yet — the cert may still be minting. Retry in a minute: curl $url/"
fi

echo
printf '\033[1;32mDone.\033[0m Hermes Agent is at \033[1m%s\033[0m (tailnet only).\n' "$url"
echo
echo "  Dashboard:  $url"
echo "  Login:      HERMES_DASHBOARD_USERNAME / HERMES_DASHBOARD_PASSWORD in $ENV_FILE"
echo "  Local API:  http://127.0.0.1:$API_PORT  (OpenAI-compatible, key in .env)"
echo
echo "First run has no model or channels configured. In the dashboard or via:"
echo "  docker exec -it hermes-agent hermes model      # pick a provider + model"
echo "  docker exec -it hermes-agent hermes setup      # full wizard (keys, channels)"
echo
echo "State lives in $DATA_DIR — that directory is the backup target."
echo "A native install at ~/.hermes, if present, was not touched and shares"
echo "nothing with this container."
echo
echo "Manage:  docker compose --project-directory $SERVICE_DIR ps|logs|restart|down"
echo "Upgrade: docker compose --project-directory $SERVICE_DIR pull && ./setup.sh"
exit 0
