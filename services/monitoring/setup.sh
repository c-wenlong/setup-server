#!/usr/bin/env bash
#
# setup.sh — one-shot deploy of Uptime Kuma + ntfy behind Tailscale.
# Linux + macOS.
#
# End state:
#   - Uptime Kuma at https://<host>:KUMA_HTTPS_PORT (status dashboard)
#   - ntfy       at https://<host>:NTFY_HTTPS_PORT (push notifications)
#   - both host-networked, bound to 127.0.0.1 only, tailnet-only via Serve
#   - ntfy auth on: deny-all to anonymous, one user per role (phone, Kuma,
#     ntfy-control) with per-topic ACLs — credentials in .env (mode 600)
#   - Kuma auto-seeded: admin account, monitors for the other services
#     (code-server, seafile, open-webui, ollama), ntfy alert channel
#
# Usage:
#   ./setup.sh
#   KUMA_PORT=3012 NTFY_TOPIC=my-alerts ./setup.sh
#
# Requirements: Linux or macOS, curl, openssl (passwords), Docker + Compose
# v2, Tailscale >= 1.90 (arbitrary HTTPS serve ports), uv (for the Kuma
# seeding step; optional).
#
# Idempotent: safe to re-run; existing .env (holds admin + ntfy credentials)
# is never overwritten; ntfy users are created once, then kept in sync —
# passwords re-aligned to .env, ACLs re-applied (ntfy access is an upsert);
# seeding skips anything that already exists.

set -euo pipefail

KUMA_PORT="${KUMA_PORT:-3002}"
NTFY_PORT="${NTFY_PORT:-3003}"
KUMA_HTTPS_PORT="${KUMA_HTTPS_PORT:-$KUMA_PORT}"
NTFY_HTTPS_PORT="${NTFY_HTTPS_PORT:-$NTFY_PORT}"
NTFY_TOPIC="${NTFY_TOPIC:-alerts}"
# The topic ntfy-control listens on for commands. It is ACL'd here because
# the users live in this service's auth db; services/ntfy-control/.env must
# carry the same CONTROL_TOPIC or the listener will be denied.
CONTROL_TOPIC="${CONTROL_TOPIC:-control}"
SERVICE_DIR="$(cd "$(dirname "$0")" && pwd)"
ENV_FILE="$SERVICE_DIR/.env"

# shellcheck source=../../lib/common.sh
. "$SERVICE_DIR/../../lib/common.sh"

# ---------------------------------------------------------------- preflight
detect_os
info "Preflight checks ($OS)"
refuse_root
command -v curl >/dev/null || die "curl is required."
command -v openssl >/dev/null || die "openssl is required (generates the Kuma admin + ntfy account passwords). Install it first: sudo apt install openssl (macOS: it ships with the OS)."
resolve_tailscale
require_docker_compose
require_tailscale_up
ok "$OS + curl + Docker (daemon reachable) + Compose v2 + Tailscale (running)"

host="$(tailnet_host)"
[ -n "$host" ] || die "Could not determine tailnet DNS name (is MagicDNS enabled?)"

# ---------------------------------------------------------------- .env
if [ -f "$ENV_FILE" ]; then
  ok "Config already exists, leaving untouched: $ENV_FILE"
else
  info "Generating .env (Kuma admin + ntfy account credentials, ports)"
  cat > "$ENV_FILE" <<EOF
# Generated by setup.sh. Holds the Kuma admin + ntfy account passwords —
# gitignored, mode 600.
KUMA_IMAGE=louislam/uptime-kuma:1.23.16
# Pinned, not \`latest\`: a surprise major bump can migrate auth.db forward
# and leave downgrade impossible. Bump deliberately, re-run setup.sh.
NTFY_IMAGE=binwiederhier/ntfy:v2.14.0
KUMA_VOLUME=$HOME/services/monitoring/kuma
NTFY_VOLUME=$HOME/services/monitoring/ntfy
KUMA_PORT=$KUMA_PORT
NTFY_PORT=$NTFY_PORT
NTFY_BASE_URL=https://$host:$NTFY_HTTPS_PORT
NTFY_TOPIC=$NTFY_TOPIC
# Topic the ntfy-control listener reads commands from. Must match
# CONTROL_TOPIC in services/ntfy-control/.env — the ACL below grants on it.
CONTROL_TOPIC=$CONTROL_TOPIC
KUMA_ADMIN_USER=admin
KUMA_ADMIN_PASSWORD=$(openssl rand -base64 15)
# ntfy accounts, one per role (hex only, so they survive .env, JSON bodies
# and a phone keyboard). ACLs, applied by setup.sh:
#   phone   — read on NTFY_TOPIC, read-write on CONTROL_TOPIC
#   kuma    — write-only on NTFY_TOPIC (publishes alerts, cannot read)
#   control — read-write on CONTROL_TOPIC, write-only on NTFY_TOPIC (replies)
# Anything else is denied outright (auth-default-access=deny-all).
NTFY_PHONE_USER=phone
NTFY_PHONE_PASS=$(openssl rand -hex 16)
NTFY_KUMA_USER=kuma
NTFY_KUMA_PASS=$(openssl rand -hex 16)
NTFY_CONTROL_USER=control
NTFY_CONTROL_PASS=$(openssl rand -hex 16)
EOF
  chmod 600 "$ENV_FILE"
  ok "Wrote $ENV_FILE"
fi

# Migration: a .env from before ntfy auth has no account block, and deny-all
# in the compose file would lock every client out. Append it, then fall
# through to the same read-back a fresh .env gets.
if ! grep -qE '^[[:space:]]*(export[[:space:]]+)?NTFY_CONTROL_USER=' "$ENV_FILE"; then
  info "Adding the ntfy account block to the existing .env (new in this version)"
  cat >> "$ENV_FILE" <<EOF
# ntfy accounts, one per role (hex only, so they survive .env, JSON bodies
# and a phone keyboard). ACLs, applied by setup.sh:
#   phone   — read on NTFY_TOPIC, read-write on CONTROL_TOPIC
#   kuma    — write-only on NTFY_TOPIC (publishes alerts, cannot read)
#   control — read-write on CONTROL_TOPIC, write-only on NTFY_TOPIC (replies)
# Anything else is denied outright (auth-default-access=deny-all).
NTFY_PHONE_USER=phone
NTFY_PHONE_PASS=$(openssl rand -hex 16)
NTFY_KUMA_USER=kuma
NTFY_KUMA_PASS=$(openssl rand -hex 16)
NTFY_CONTROL_USER=control
NTFY_CONTROL_PASS=$(openssl rand -hex 16)
EOF
  # Only when the key is absent entirely: .env is last-assignment-wins when
  # sourced, so appending CONTROL_TOPIC unconditionally would shadow one the
  # user already pinned further up the file.
  grep -qE '^[[:space:]]*(export[[:space:]]+)?CONTROL_TOPIC=' "$ENV_FILE" \
    || echo "CONTROL_TOPIC=${CONTROL_TOPIC:-control}" >> "$ENV_FILE"
  ok ".env now carries the ntfy accounts"
fi
# The block above holds passwords — enforce 600 even on a .env created
# before it existed.
chmod 600 "$ENV_FILE"

# env_val KEY: KEY's value in .env, read the way Docker Compose (and the
# seeding step's `set -a; . .env`) sees it — an optional `export ` prefix,
# one pair of surrounding quotes stripped, an unquoted trailing ` #`
# comment dropped, $HOME/${HOME} interpolated outside single quotes, last
# assignment wins. The ACL grants and the credential checks below consume
# these values directly, so this reader must agree with the source or a
# quoted `NTFY_TOPIC="alerts"` grants on `"alerts"` while Kuma publishes to
# `alerts`. Same parser teardown.sh uses for the same reason.
env_val() {
  local line value tail quote=""
  line="$(grep -E "^[[:space:]]*(export[[:space:]]+)?$1=" "$ENV_FILE" | tail -1 || true)"
  [ -n "$line" ] || return 0
  value="${line#*=}"
  tail="${value##*[![:space:]]}"; value="${value%"$tail"}"
  case "$value" in
    \"*) quote='"'; value="${value#\"}"; value="${value%%\"*}" ;;
    \'*) quote="'"; value="${value#\'}"; value="${value%%\'*}" ;;
    *) value="${value%%[[:space:]]#*}"
       tail="${value##*[![:space:]]}"; value="${value%"$tail"}" ;;
  esac
  if [ "$quote" != "'" ]; then
    value="${value//\$\{HOME\}/$HOME}"
    value="${value//\$HOME/$HOME}"
  fi
  printf '%s' "$value"
}

NTFY_PHONE_USER="$(env_val NTFY_PHONE_USER)";     NTFY_PHONE_PASS="$(env_val NTFY_PHONE_PASS)"
NTFY_KUMA_USER="$(env_val NTFY_KUMA_USER)";       NTFY_KUMA_PASS="$(env_val NTFY_KUMA_PASS)"
NTFY_CONTROL_USER="$(env_val NTFY_CONTROL_USER)"; NTFY_CONTROL_PASS="$(env_val NTFY_CONTROL_PASS)"
CONTROL_TOPIC="$(env_val CONTROL_TOPIC)";         CONTROL_TOPIC="${CONTROL_TOPIC:-control}"
NTFY_TOPIC="$(env_val NTFY_TOPIC)";               NTFY_TOPIC="${NTFY_TOPIC:-alerts}"
for v in NTFY_PHONE_USER NTFY_PHONE_PASS NTFY_KUMA_USER NTFY_KUMA_PASS \
         NTFY_CONTROL_USER NTFY_CONTROL_PASS; do
  [ -n "${!v}" ] || die "$v is empty or missing from $ENV_FILE — fix that line, or delete .env and re-run to regenerate the accounts."
done

mkdir -p "$HOME/services/monitoring/kuma" "$HOME/services/monitoring/ntfy"

# ---------------------------------------------------------------- deploy
info "Starting containers (docker compose up -d)"
docker compose --project-directory "$SERVICE_DIR" up -d

info "Waiting for Kuma (:$KUMA_PORT) and ntfy (:$NTFY_PORT)"
for i in $(seq 1 40); do
  if curl -fsS -o /dev/null "http://127.0.0.1:$KUMA_PORT/" 2>/dev/null \
     && curl -fsS -o /dev/null "http://127.0.0.1:$NTFY_PORT/v1/health" 2>/dev/null; then
    ok "Both answering locally"
    break
  fi
  [ "$i" -eq 40 ] && die "Not healthy. Logs: docker compose --project-directory $SERVICE_DIR logs"
  sleep 3
done

# ---------------------------------------------------------------- ntfy auth
# One user per role in the auth db (the ntfy-auth named volume), deny-all to
# everything else. `ntfy user list` prints "user <name> (role: ...)" blocks;
# a user is added only when absent, and an existing one gets `change-pass`
# back to the .env password — .env is the authority for credentials (it is
# what ntfy-control and the seeder read), which also self-heals the reset
# where .env was regenerated but the auth volume survived. To rotate a
# password, edit .env and re-run; changing it inside ntfy is reverted here.
# `ntfy access` is an upsert, so the grants run every time and repair drift.
info "Configuring ntfy auth (one user per role; anonymous denied)"
ntfy_user_exists() {
  docker exec ntfy ntfy user list 2>/dev/null \
    | awk -v u="$1" '$1 == "user" && $2 == u { found=1 } END { exit !found }'
}
new_users=""
for pair in "$NTFY_PHONE_USER $NTFY_PHONE_PASS" "$NTFY_KUMA_USER $NTFY_KUMA_PASS" "$NTFY_CONTROL_USER $NTFY_CONTROL_PASS"; do
  set -- $pair
  if ntfy_user_exists "$1"; then
    docker exec -e "NTFY_PASSWORD=$2" ntfy ntfy user change-pass "$1" >/dev/null
  else
    docker exec -e "NTFY_PASSWORD=$2" ntfy ntfy user add "$1" >/dev/null
    new_users="$new_users $1"
  fi
done
#   phone   — the app subscription: reads alerts, sends commands on control
#   kuma    — the alert channel: publishes to alerts, reads nothing
#   control — the ntfy-control listener: reads commands on control (setup.sh
#             also posts `panel` to it under this account), writes replies to
#             alerts
ntfy_grant() { docker exec ntfy ntfy access "$1" "$2" "$3" >/dev/null; }
ntfy_grant "$NTFY_PHONE_USER" "$NTFY_TOPIC" read-only
ntfy_grant "$NTFY_PHONE_USER" "$CONTROL_TOPIC" read-write
ntfy_grant "$NTFY_KUMA_USER" "$NTFY_TOPIC" write-only
ntfy_grant "$NTFY_CONTROL_USER" "$CONTROL_TOPIC" read-write
ntfy_grant "$NTFY_CONTROL_USER" "$NTFY_TOPIC" write-only
if [ -n "$new_users" ]; then
  ok "ntfy users created:$new_users (anonymous: deny-all)"
else
  ok "ntfy users + ACLs verified (passwords synced from .env)"
fi

# ---------------------------------------------------------------- seed
if command -v uv >/dev/null; then
  info "Seeding Kuma (admin account, monitors, ntfy alert channel)"
  # TAILNET_HOST: monitors probe the tailnet HTTPS URLs, so the seeder needs
  # this node's MagicDNS name. ADGUARD_DNS_IP: the adguard-dns monitor asks
  # this node's resolver a question — the tailnet v4, resolved the same way.
  dns_ip="$("$TAILSCALE" ip -4 2>/dev/null || true)"
  if (set -a; . "$ENV_FILE"; TAILNET_HOST="$host" ADGUARD_DNS_IP="$dns_ip"; set +a; \
      uv run --with uptime-kuma-api python3 "$SERVICE_DIR/seed_kuma.py"); then
    ok "Kuma seeded"
  else
    warn "Seeding failed — Kuma still works, configure via the web UI (see SETUP.md)."
  fi
else
  warn "uv not found — skipping auto-seed. Configure Kuma via the web UI (see SETUP.md)."
fi

# ------------------------------------------------------- tailscale serve
publish() { # publish <https_port> <local_port>
  ts_serve_publish "$1" "http://127.0.0.1:$2"
}
info "Publishing via Tailscale Serve (tailnet only)"
publish "$KUMA_HTTPS_PORT" "$KUMA_PORT"
publish "$NTFY_HTTPS_PORT" "$NTFY_PORT"

# ------------------------------------------------------------ final check
kuma_url="https://$host:$KUMA_HTTPS_PORT"
ntfy_url="https://$host:$NTFY_HTTPS_PORT"
info "Verifying end-to-end (first request can take ~60s while certs mint)"
curl -fsS -o /dev/null --max-time 90 "$kuma_url/" && ok "Kuma reachable at $kuma_url" \
  || echo "    Kuma cert may still be minting: curl -I $kuma_url"
curl -fsS -o /dev/null --max-time 90 "$ntfy_url/v1/health" && ok "ntfy reachable at $ntfy_url" \
  || echo "    ntfy cert may still be minting: curl -I $ntfy_url"

echo
printf '\033[1;32mDone.\033[0m\n'
echo "  Dashboard:  $kuma_url  (login: see KUMA_ADMIN_* in $ENV_FILE)"
echo "  Alerts:     $ntfy_url  — subscribe to topic '$NTFY_TOPIC'"
echo
echo "Phone setup: install the ntfy app, add server $ntfy_url, subscribe to"
echo "  '$NTFY_TOPIC' WITH a username/password — NTFY_PHONE_USER / NTFY_PHONE_PASS"
echo "  in $ENV_FILE. Anonymous reads/writes are denied now; without the login"
echo "  the phone silently gets nothing."
echo "Test alert:  curl -u $NTFY_KUMA_USER:<NTFY_KUMA_PASS from .env> -d 'hello' $ntfy_url/$NTFY_TOPIC"
echo "Manage:      docker compose --project-directory $SERVICE_DIR ps|logs|restart|down"
