#!/usr/bin/env bash
#
# setup.sh — one-shot deploy of Umami (self-hosted web analytics) behind
# Tailscale. Linux + macOS.
#
# End state:
#   - umami + postgres containers
#   - published on 127.0.0.1:LOCAL_PORT only (default 8106 — forgejo
#     already owns host :3000, Umami's upstream default)
#   - reachable tailnet-only at https://<host>.<tailnet>.ts.net:HTTPS_PORT
#   - default admin/umami password rotated to UMAMI_ADMIN_PASSWORD
#   - boot-persistent via Docker's restart policy (no systemd/launchd)
#
# Usage:
#   ./setup.sh
#   LOCAL_PORT=8108 ./setup.sh            # HTTPS follows LOCAL_PORT
#   LOCAL_PORT=8108 HTTPS_PORT=8108 ./setup.sh
#
# Version: pinned to 3.3.1. Bump UMAMI_VERSION in .env, then re-run.
#
# Requirements: Linux or macOS, curl, Docker + Compose v2, Tailscale logged in.
#
# Idempotent: safe to re-run; it upgrades the image and repairs the publish.
# An existing .env is never overwritten.

set -euo pipefail

LOCAL_PORT="${LOCAL_PORT:-8106}"
HTTPS_PORT_EXPLICIT="${HTTPS_PORT:+yes}"
HTTPS_PORT="${HTTPS_PORT:-$LOCAL_PORT}"

SERVICE_DIR="$(cd "$(dirname "$0")" && pwd)"
ENV_FILE="$SERVICE_DIR/.env"
STATE="$HOME/services/umami"

# shellcheck source=../../lib/common.sh
. "$SERVICE_DIR/../../lib/common.sh"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

randhex() {
  local n="${1:-16}"
  if command -v python3 >/dev/null 2>&1; then
    python3 -c "import secrets; print(secrets.token_hex($n))"
  else
    od -An -tx1 -N"$n" /dev/urandom | tr -d ' \n'
    echo
  fi
}

randpass() {
  printf '%sAa1' "$(randhex 12)"
}

# ---------------------------------------------------------------- preflight
detect_os
info "Preflight checks ($OS)"
refuse_root
command -v curl >/dev/null || die "curl is required."
resolve_tailscale
require_docker_compose
require_tailscale_up
require_numeric LOCAL_PORT HTTPS_PORT

ok "$OS + curl + Docker (daemon reachable) + Compose v2 + Tailscale (running)"

TS_HOST="$(tailnet_host)"
[ -n "$TS_HOST" ] || die "Could not determine tailnet DNS name (is MagicDNS enabled?)"
ok "Tailnet name: $TS_HOST"

avail_mb=""
if [ -r /proc/meminfo ]; then
  avail_mb="$(sed -n 's/^MemAvailable: *\([0-9]*\) kB/\1/p' /proc/meminfo)"
  avail_mb="$(( avail_mb / 1024 ))"
fi
if [ -n "${avail_mb:-}" ] && [ "$avail_mb" -lt 400 ]; then
  warn "Only ~${avail_mb} MB RAM available. Umami is light, but Postgres still needs a floor."
fi

# ---------------------------------------------------------------- .env
if [ -f "$ENV_FILE" ]; then
  ok "Config already exists, leaving untouched: $ENV_FILE"
else
  info "Writing .env"
  tz="Etc/UTC"
  if [ -L /etc/localtime ]; then
    tz="$(readlink /etc/localtime | sed 's#.*/zoneinfo/##')"
  elif [ -f /etc/timezone ]; then
    tz="$(cat /etc/timezone)"
  fi
  db_pass="$(randhex 16)"
  admin_pass="$(randpass)"
  app_secret="$(randhex 32)"
  two_factor="$(randhex 32)"
  cat > "$ENV_FILE" <<EOF
# Generated by setup.sh. Gitignored; mode 600.
# Docker Compose interpolates this file from the project directory.

# Pinned. Official floats \`postgresql-latest\`. To upgrade: bump, then ./setup.sh.
UMAMI_VERSION=3.3.1
POSTGRES_VERSION=16-alpine

LOCAL_PORT=$LOCAL_PORT
TZ=$tz

# Marker dir (launcher "installed"). Live Postgres is the named volume
# umami-postgres — Postgres cannot write a host-owned bind mount.
UMAMI_DATA=$STATE

UMAMI_PUBLIC_URL=https://$TS_HOST:$HTTPS_PORT

UMAMI_DB_NAME=umami
UMAMI_DB_USER=umami
UMAMI_DB_PASSWORD=$db_pass

UMAMI_APP_SECRET=$app_secret
# 64 hex chars. Required for 2FA; generate with: python3 -c "import secrets; print(secrets.token_hex(32))"
UMAMI_TWO_FACTOR_KEY=$two_factor

# Upstream seeds username admin / password umami on first boot. setup.sh
# rotates that password via the API. Changing this after first boot does
# not rotate the live password — do that in the UI.
UMAMI_ADMIN_USER=admin
UMAMI_ADMIN_PASSWORD=$admin_pass

UMAMI_MEM_LIMIT=512m
UMAMI_DB_MEM_LIMIT=256m
EOF
  chmod 600 "$ENV_FILE"
  ok "Wrote $ENV_FILE"
fi

REQUESTED_PORT="$LOCAL_PORT"
set -a; . "$ENV_FILE"; set +a
DATA_DIR="${UMAMI_DATA:?UMAMI_DATA missing from $ENV_FILE}"
UMAMI_PUBLIC_URL="${UMAMI_PUBLIC_URL:?UMAMI_PUBLIC_URL missing from $ENV_FILE}"
UMAMI_ADMIN_USER="${UMAMI_ADMIN_USER:-admin}"
UMAMI_ADMIN_PASSWORD="${UMAMI_ADMIN_PASSWORD:?UMAMI_ADMIN_PASSWORD missing from $ENV_FILE}"
if [ "$LOCAL_PORT" != "$REQUESTED_PORT" ]; then
  warn "LOCAL_PORT=$REQUESTED_PORT ignored — the existing $ENV_FILE says $LOCAL_PORT. Edit .env and re-run to move the port."
fi
[ -n "$HTTPS_PORT_EXPLICIT" ] || HTTPS_PORT="$LOCAL_PORT"

WANT_URL="https://$TS_HOST:$HTTPS_PORT"
if [ "$UMAMI_PUBLIC_URL" != "$WANT_URL" ]; then
  warn "UMAMI_PUBLIC_URL in .env is $UMAMI_PUBLIC_URL but this box now answers to $WANT_URL."
  warn "  Tracker snippets copied from the UI will still work (they use the page origin). Fix: set UMAMI_PUBLIC_URL=$WANT_URL in $ENV_FILE, then re-run."
fi

mkdir -p "$DATA_DIR"

avail_kb="$(df -Pk "$DATA_DIR" | awk 'NR==2{print $4}')"
if [ "${avail_kb:-0}" -lt 524288 ]; then
  warn "$(( avail_kb / 1048576 )) GB free at $DATA_DIR — analytics events accumulate."
else
  ok "$(( avail_kb / 1048576 )) GB free at $DATA_DIR"
fi

# ---------------------------------------------------------------- deploy
COMPOSE=(docker compose --project-directory "$SERVICE_DIR")

info "Starting Umami (docker compose up -d) — first run pulls the image and runs migrations"
"${COMPOSE[@]}" up -d

info "Waiting for Umami on 127.0.0.1:$LOCAL_PORT (first boot runs Prisma migrations)"
wait_http "http://127.0.0.1:$LOCAL_PORT/api/heartbeat" 90 3 || die "Umami did not come up. Logs: docker compose --project-directory $SERVICE_DIR logs umami"
ok "Umami is answering locally"

# Upstream seeds admin/umami. Rotate it so the well-known pair is not
# sitting on the tailnet. Re-runs: if the generated password already
# works, skip; if the default still works, rotate.
rotate_admin() {
  local login_body token user_id payload code
  if ! command -v python3 >/dev/null; then
    die "python3 is required to rotate the default admin/umami password. Not publishing while that well-known pair may still work."
  fi
  login_json() {
    UMAMI_USER="$1" UMAMI_PASS="$2" python3 -c 'import json,os; print(json.dumps({"username":os.environ["UMAMI_USER"],"password":os.environ["UMAMI_PASS"]}))'
  }
  # Already rotated?
  code="$(curl -sS -o "$WORK/login.json" -w '%{http_code}' --max-time 30 \
    -X POST -H 'Content-Type: application/json' --data-binary "$(login_json "$UMAMI_ADMIN_USER" "$UMAMI_ADMIN_PASSWORD")" \
    "http://127.0.0.1:$LOCAL_PORT/api/auth/login" 2>/dev/null || echo 000)"
  if [ "$code" = "200" ]; then
    ok "Admin password already matches .env"
    return 0
  fi
  code="$(curl -sS -o "$WORK/login.json" -w '%{http_code}' --max-time 30 \
    -X POST -H 'Content-Type: application/json' --data-binary "$(login_json "$UMAMI_ADMIN_USER" umami)" \
    "http://127.0.0.1:$LOCAL_PORT/api/auth/login" 2>/dev/null || echo 000)"
  if [ "$code" != "200" ]; then
    warn "Could not log in as $UMAMI_ADMIN_USER with either the generated password or the upstream default (umami). Set the password in the UI."
    return 0
  fi
  login_body="$(cat "$WORK/login.json" 2>/dev/null || true)"
  token="$(printf '%s' "$login_body" | sed -n 's/.*"token": *"\([^"]*\)".*/\1/p')"
  user_id="$(printf '%s' "$login_body" | sed -n 's/.*"id": *"\([^"]*\)".*/\1/p')"
  if [ -z "$token" ] || [ -z "$user_id" ]; then
    die "Login succeeded but the response had no token/id. The default admin/umami password may still be live. Not publishing."
  fi
  payload="$(UMAMI_PASS="$UMAMI_ADMIN_PASSWORD" python3 -c 'import json,os; print(json.dumps({"currentPassword":"umami","newPassword":os.environ["UMAMI_PASS"]}))')"
  code="$(curl -sS -o "$WORK/pw.json" -w '%{http_code}' --max-time 30 \
    -X POST -H 'Content-Type: application/json' -H "Authorization: Bearer $token" \
    --data-binary "$payload" \
    "http://127.0.0.1:$LOCAL_PORT/api/users/$user_id/password" 2>/dev/null || echo 000)"
  case "$code" in
    200)
      ok "Rotated the default admin/umami password"
      ;;
    *)
      die "POST /api/users/$user_id/password returned HTTP $code. The upstream default (admin/umami) is still live. Not publishing."
      ;;
  esac
}
rotate_admin

# ------------------------------------------------------- tailscale serve
info "Publishing via Tailscale Serve (HTTPS :$HTTPS_PORT -> 127.0.0.1:$LOCAL_PORT)"
ts_serve_publish "$HTTPS_PORT" "http://127.0.0.1:$LOCAL_PORT"

url="https://$TS_HOST:$HTTPS_PORT"
info "Verifying $url/api/heartbeat (first request can take ~60s while the TLS cert is minted)"
if curl -fsS -o /dev/null --max-time 90 "$url/api/heartbeat"; then
  ok "End-to-end HTTPS check passed"
else
  warn "No answer on $url/api/heartbeat yet — the cert may still be minting. Retry in a minute: curl $url/api/heartbeat"
fi

echo
printf '\033[1;32mDone.\033[0m Umami is at \033[1m%s\033[0m (tailnet only).\n' "$url"
echo
echo "  Sign in as $UMAMI_ADMIN_USER (password in $ENV_FILE)."
echo "  Upgrade: bump UMAMI_VERSION in $ENV_FILE then ./setup.sh"
echo
echo "Backups: nothing backs this box up. Dump Postgres with:"
echo "    docker compose --project-directory $SERVICE_DIR exec -T db pg_dump -U umami umami"
echo
echo "Manage:  docker compose --project-directory $SERVICE_DIR ps|logs|restart|down"
echo "Upgrade: edit UMAMI_VERSION in .env, then ./setup.sh"
exit 0
