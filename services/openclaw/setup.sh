#!/usr/bin/env bash
#
# setup.sh — one-shot deploy of OpenClaw (self-hosted AI assistant gateway)
# behind Tailscale. Linux + macOS.
#
# End state:
#   - an `openclaw-gateway` container (pre-built GHCR image) listening on
#     127.0.0.1:LOCAL_PORT, token-gated, reachable tailnet-only at
#     https://<host>.<tailnet>.ts.net:HTTPS_PORT
#   - state, config and workspace under ~/services/openclaw/
#   - existing ~/.claude / ~/.codex mounted in read-write so onboarding can
#     reuse their logins — never created or overwritten by this script
#   - boot-persistent via Docker's restart policy (no systemd/launchd)
#
# Usage:
#   ./setup.sh                            # local 18789, HTTPS 18789
#   LOCAL_PORT=18790 ./setup.sh           # HTTPS follows LOCAL_PORT
#   LOCAL_PORT=18790 HTTPS_PORT=8443 ./setup.sh
#
# Requirements: Linux or macOS, curl, Docker + Compose v2, Tailscale
# logged in. Sudo is needed at most once on Linux (tailscale operator).
#
# Idempotent: safe to re-run; it upgrades the image and repairs the publish.
# An existing .env and docker-compose.creds.yml are never overwritten. A
# controlUi.allowedOrigins already set in the Gateway config is left alone.

set -euo pipefail

LOCAL_PORT="${LOCAL_PORT:-18789}"
# The HTTPS port follows the local port unless set explicitly (the forgejo
# convention), so overriding only LOCAL_PORT cannot split the two. Whether it
# was explicit is remembered for the .env read-back below.
HTTPS_PORT_EXPLICIT="${HTTPS_PORT:+yes}"
HTTPS_PORT="${HTTPS_PORT:-$LOCAL_PORT}"

SERVICE_DIR="$(cd "$(dirname "$0")" && pwd)"
ENV_FILE="$SERVICE_DIR/.env"
STATE="$HOME/services/openclaw"

# shellcheck source=../../lib/common.sh
. "$SERVICE_DIR/../../lib/common.sh"

# 32 hex chars: [A-Za-z0-9]-safe, so it survives .env, shell quoting and the
# Control UI token field without escaping.
randhex() {
  if command -v python3 >/dev/null 2>&1; then
    python3 -c 'import secrets; print(secrets.token_hex(16))'
  else
    od -An -tx1 -N16 /dev/urandom | tr -d ' \n'
    echo
  fi
}

# ---------------------------------------------------------------- preflight
detect_os
info "Preflight checks ($OS)"
refuse_root
command -v curl >/dev/null || die "curl is required."
resolve_tailscale
require_docker_compose
require_tailscale_up
require_numeric LOCAL_PORT HTTPS_PORT

ok "$OS + curl + Docker (daemon reachable) + Compose v2 + Tailscale (running)"

# The tailnet name goes into controlUi.allowedOrigins before the container
# ever starts, so resolve it up front like forgejo's ROOT_URL.
TS_HOST="$(tailnet_host)"
[ -n "$TS_HOST" ] || die "Could not determine tailnet DNS name (is MagicDNS enabled?)"
ok "Tailnet name: $TS_HOST"

# ---------------------------------------------------------------- .env
if [ -f "$ENV_FILE" ]; then
  ok "Config already exists, leaving untouched: $ENV_FILE"
else
  info "Writing .env (generated gateway token + ports + paths)"
  tz="Etc/UTC"
  if [ -L /etc/localtime ]; then
    tz="$(readlink /etc/localtime | sed 's#.*/zoneinfo/##')"
  fi
  # umask 077 so the file is private the moment it exists — a chmod after the
  # write would leave a window where another local account could read it.
  ( umask 077; cat > "$ENV_FILE" <<EOF
# Generated by setup.sh. Gitignored; mode 600.
# Docker Compose reads this file from the project directory for interpolation.
# It is NOT passed to the container as env_file — the token below must not end
# up readable by every process in the container.

# Pre-built GHCR image. Release tags look like 2026.10.7; 'latest' tracks the
# moving stable channel, 'extended-stable' the trailing-month line.
OPENCLAW_VERSION=2026.10.7

LOCAL_PORT=$LOCAL_PORT
TZ=$tz

# State, config, workspace and auth-profile secrets — the only things here
# worth backing up. Moving them means moving the directories too. Double
# quotes keep a path with spaces valid for both `set -a; .` and Compose.
OPENCLAW_CONFIG_DIR="$STATE/config"
OPENCLAW_WORKSPACE_DIR="$STATE/workspace"
OPENCLAW_AUTH_PROFILE_SECRET_DIR="$STATE/auth-secrets"

# Shared-secret auth for the Gateway and the Control UI login. Anyone who has
# this token can drive the assistant; Tailscale is still the network boundary.
OPENCLAW_GATEWAY_TOKEN=$(randhex)
EOF
  )
  if [ -n "$HTTPS_PORT_EXPLICIT" ]; then
    # An explicit publish port stops following LOCAL_PORT, so it must be
    # recorded — the launcher tile reads this file for the tile URL.
    printf '\n# Explicitly set at install: the tailnet publish port, which no longer\n# follows LOCAL_PORT. Delete this line to resume following it.\nHTTPS_PORT=%s\n' \
      "$HTTPS_PORT" >> "$ENV_FILE"
  fi
  chmod 600 "$ENV_FILE"
  ok "Wrote $ENV_FILE"
fi

# Read back: an existing .env is the source of truth for ports and paths, so
# a re-run can never silently move a live deployment.
REQUESTED_PORT="$LOCAL_PORT"
REQUESTED_HTTPS_PORT="${HTTPS_PORT_EXPLICIT:+$HTTPS_PORT}"
# Unset first, so a post-source value can only have come from .env — then
# every assignment form the shell accepts (export, leading whitespace)
# counts as recorded, not just a literal `HTTPS_PORT=` at column 0.
unset HTTPS_PORT
set -a; . "$ENV_FILE"; set +a
CONFIG_DIR="${OPENCLAW_CONFIG_DIR:?OPENCLAW_CONFIG_DIR missing from $ENV_FILE}"
WORKSPACE_DIR="${OPENCLAW_WORKSPACE_DIR:?OPENCLAW_WORKSPACE_DIR missing from $ENV_FILE}"
SECRET_DIR="${OPENCLAW_AUTH_PROFILE_SECRET_DIR:?OPENCLAW_AUTH_PROFILE_SECRET_DIR missing from $ENV_FILE}"
if [ "$LOCAL_PORT" != "$REQUESTED_PORT" ]; then
  warn "LOCAL_PORT=$REQUESTED_PORT ignored — the existing $ENV_FILE says $LOCAL_PORT. Edit .env and re-run to move the port."
fi
if [ -n "${HTTPS_PORT+x}" ]; then
  # .env already decided the publish port (an earlier explicit override);
  # an explicit value on this re-run is as ignored as LOCAL_PORT is.
  if [ -n "$HTTPS_PORT_EXPLICIT" ] && [ "$HTTPS_PORT" != "$REQUESTED_HTTPS_PORT" ]; then
    warn "HTTPS_PORT=$REQUESTED_HTTPS_PORT ignored — the existing $ENV_FILE says $HTTPS_PORT. Edit .env and re-run to move the publish port."
  fi
elif [ -n "$HTTPS_PORT_EXPLICIT" ]; then
  # First explicit override on a re-run: apply it and record it so the
  # launcher tile and teardown see the real publish port. The leading
  # newline keeps a .env with no trailing newline parseable.
  HTTPS_PORT="$REQUESTED_HTTPS_PORT"
  printf '\n# Explicitly set on re-run: the tailnet publish port, which no longer\n# follows LOCAL_PORT. Delete this line to resume following it.\nHTTPS_PORT=%s\n' \
    "$HTTPS_PORT" >> "$ENV_FILE"
  ok "Recorded HTTPS_PORT=$HTTPS_PORT in $ENV_FILE"
else
  # No recorded publish port: HTTPS keeps following the local port .env settled on.
  HTTPS_PORT="$LOCAL_PORT"
fi
require_numeric HTTPS_PORT

mkdir -p "$STATE" "$CONFIG_DIR" "$WORKSPACE_DIR" "$SECRET_DIR"
ok "State dirs ready under $STATE"

# ------------------------------------------------- optional creds overlay
# Generated once, never overwritten. Read-write so token refresh inside the
# container persists; setup.sh itself never writes inside ~/.claude or
# ~/.codex. Same trade-off as services/openhands.
CREDS_FILE="$SERVICE_DIR/docker-compose.creds.yml"
if [ -f "$CREDS_FILE" ]; then
  ok "Compose creds overlay already exists, leaving untouched: $CREDS_FILE"
elif [ -d "$HOME/.claude" ] || [ -d "$HOME/.codex" ]; then
  info "Writing compose overlay to mount existing Claude/Codex dirs (not created, not copied)"
  {
    echo "services:"
    echo "  openclaw-gateway:"
    echo "    volumes:"
    [ -d "$HOME/.claude" ] && echo "      - $HOME/.claude:/home/node/.claude"
    [ -d "$HOME/.codex" ] && echo "      - $HOME/.codex:/home/node/.codex"
  } > "$CREDS_FILE"
  ok "Wrote $CREDS_FILE"
else
  warn "No ~/.claude or ~/.codex to mount — configure a model provider in the Control UI after first boot."
fi

COMPOSE=(docker compose --project-directory "$SERVICE_DIR" -f docker-compose.yml)
if [ -f "$CREDS_FILE" ]; then
  COMPOSE+=(-f docker-compose.creds.yml)
fi

# ------------------------------------------------- gateway config (once)
# Pre-start config writes go through a throwaway gateway container (the
# upstream scripts/docker/setup.sh pattern): the running gateway cannot
# rewrite its own openclaw.json, and openclaw-cli needs the gateway's network
# namespace, which does not exist yet. `run` pulls the image on first use.
prestart_cli() {
  "${COMPOSE[@]}" run --rm --no-deps \
    --entrypoint node openclaw-gateway dist/index.js "$@"
}

info "Syncing Gateway config (mode, bind, Control UI origins, trusted proxies)"
current="$(prestart_cli config get gateway.controlUi.allowedOrigins 2>/dev/null || true)"
current="${current//$'\r'/}"
proxies="$(prestart_cli config get gateway.trustedProxies 2>/dev/null || true)"
proxies="${proxies//$'\r'/}"

# mode/bind are deployment invariants and always pinned. allowedOrigins and
# trustedProxies are seeded only when unset — a user who configured them by
# hand knows better than the defaults.
batch='[{"path":"gateway.mode","value":"local"},{"path":"gateway.bind","value":"lan"}'
msg="Pinned gateway.mode=local, gateway.bind=lan"
if [ -z "$current" ] || [ "$current" = "null" ] || [ "$current" = "[]" ]; then
  # loopback for local clients, the tailnet URL for browsers behind Serve.
  origins="$(printf '["http://localhost:%s","http://127.0.0.1:%s","https://%s:%s"]' \
    "$LOCAL_PORT" "$LOCAL_PORT" "$TS_HOST" "$HTTPS_PORT")"
  batch="$batch,{\"path\":\"gateway.controlUi.allowedOrigins\",\"value\":$origins}"
  msg="$msg and Control UI origins"
else
  # Origins exist but may predate this publish: an explicit HTTPS_PORT on a
  # re-run can move the URL while the seeded origin still names the old port.
  # Health checks all pass in that state — only the browser is refused.
  need="https://$TS_HOST:$HTTPS_PORT"
  if printf '%s' "$current" | grep -qF "\"$need\"" || printf '%s' "$current" | grep -qxF "$need"; then
    ok "Control UI origins already configured, leaving allowedOrigins alone"
  else
    warn "allowedOrigins is already configured but lacks $need — browsers on the published URL will be refused."
    warn "  Add it (keeping the entries already there): docker exec openclaw-gateway node dist/index.js config set --batch-json '[{\"path\":\"gateway.controlUi.allowedOrigins\",\"value\":[\"$need\",...]}]'"
  fi
fi
if [ -z "$proxies" ] || [ "$proxies" = "null" ] || [ "$proxies" = "[]" ]; then
  # docker-proxy is how both Serve traffic and local curl reach the
  # container; the gateway 403s forwarded headers from a proxy outside
  # trustedProxies. Must match the subnet pinned in docker-compose.yml.
  batch="$batch,{\"path\":\"gateway.trustedProxies\",\"value\":[\"192.168.144.0/24\"]}"
  msg="$msg and trusted proxies"
else
  ok "trustedProxies already configured, leaving them alone"
fi
batch="$batch]"

if prestart_cli config set --batch-json "$batch" >/dev/null; then
  ok "$msg"
else
  warn "Could not write Gateway config — first boot may need: docker compose run --rm --no-deps --entrypoint node openclaw-gateway dist/index.js onboard"
fi

# ---------------------------------------------------------------- deploy
info "Starting OpenClaw Gateway (docker compose up -d) — first run pulls the image"
"${COMPOSE[@]}" up -d openclaw-gateway

info "Waiting for the Gateway on 127.0.0.1:$LOCAL_PORT"
# /healthz, not /: with trustedProxies set, / demands forwarded client
# headers even locally and a bare curl 403s — the health endpoint is the
# unauthenticated "the gateway is serving" signal.
wait_http "http://127.0.0.1:$LOCAL_PORT/healthz" 60 3 \
  || die "Gateway did not come up. Logs: docker compose --project-directory $SERVICE_DIR logs openclaw-gateway"
ok "Gateway is answering locally"

# ------------------------------------------------------- tailscale serve
info "Publishing via Tailscale Serve (HTTPS :$HTTPS_PORT, tailnet only)"
ts_serve_publish "$HTTPS_PORT" "http://127.0.0.1:$LOCAL_PORT"

# ------------------------------------------------------------ final check
url="https://$TS_HOST:$HTTPS_PORT"
info "Verifying $url (first request can take ~60s while the TLS cert is minted)"
if curl -fsS -o /dev/null --max-time 90 "$url/healthz"; then
  ok "End-to-end HTTPS check passed"
else
  warn "No answer on $url yet — the cert may still be minting. Retry in a minute: curl $url/"
fi

echo
printf '\033[1;32mDone.\033[0m OpenClaw Gateway is at \033[1m%s\033[0m (tailnet only).\n' "$url"
echo
echo "  Control UI: $url"
echo "  Token:      OPENCLAW_GATEWAY_TOKEN in $ENV_FILE"
echo "              (paste it into the Control UI when it asks)"
echo
echo "State, config and the agent workspace live under $STATE —"
echo "that directory is the backup target."
echo
echo "Next steps, from the Control UI or the CLI:"
echo "  - connect a model provider (mounted ~/.claude / ~/.codex are reused)"
echo "  - add a chat channel, e.g. Telegram:"
echo "      cd $SERVICE_DIR"
echo "      docker compose run --rm openclaw-cli channels add --channel telegram --token \"<bot token>\""
echo
echo "Manage:  docker compose --project-directory $SERVICE_DIR ps|logs|restart|down"
echo "Upgrade: docker compose --project-directory $SERVICE_DIR pull && ./setup.sh"
exit 0
