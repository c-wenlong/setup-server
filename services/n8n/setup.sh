#!/usr/bin/env bash
#
# setup.sh — one-shot deploy of n8n (workflow automation) behind Tailscale.
# Linux + macOS.
#
# End state:
#   - n8n container (host network, binds 127.0.0.1:LOCAL_PORT only)
#   - published tailnet-only at https://<host>.<tailnet>.ts.net:HTTPS_PORT
#   - owner account seeded via n8n's setup API (idempotent)
#   - boot-persistent via Docker's restart policy
#
# Usage:
#   ./setup.sh
#   OWNER_EMAIL=me@x.com OWNER_PASSWORD='MyPass123' ./setup.sh
#   LOCAL_PORT=5679 HTTPS_PORT=5679 ./setup.sh
#
# n8n password policy: >= 8 chars with at least 1 number and 1 capital letter.
#
# Idempotent: safe to re-run; existing .env (encryption key + owner creds) is
# never overwritten. NOTE: the encryption key in .env protects all stored
# workflow credentials — losing it means losing saved credentials.

set -euo pipefail

LOCAL_PORT="${LOCAL_PORT:-5678}"
HTTPS_PORT="${HTTPS_PORT:-$LOCAL_PORT}"
SERVICE_DIR="$(cd "$(dirname "$0")" && pwd)"
ENV_FILE="$SERVICE_DIR/.env"

# shellcheck source=../../lib/common.sh
. "$SERVICE_DIR/../../lib/common.sh"

# ---------------------------------------------------------------- preflight
detect_os
info "Preflight checks ($OS)"
refuse_root
command -v curl >/dev/null || die "curl is required."
resolve_tailscale
require_docker_compose
require_tailscale_up
require_numeric HTTPS_PORT
ok "$OS + curl + Docker (daemon reachable) + Compose v2 + Tailscale (running)"

host="$(tailnet_host)"
[ -n "$host" ] || die "Could not determine tailnet DNS name (is MagicDNS enabled?)"

# ---------------------------------------------------------------- .env
if [ -f "$ENV_FILE" ]; then
  ok "Config already exists, leaving untouched: $ENV_FILE"
else
  info "Generating .env (encryption key + owner credentials)"
  cat > "$ENV_FILE" <<EOF
# Generated by setup.sh. N8N_ENCRYPTION_KEY protects all credentials stored
# in workflows — back this file up. Gitignored; mode 600.
N8N_IMAGE=n8nio/n8n:latest
N8N_VOLUME=$HOME/services/n8n/data
LOCAL_PORT=$LOCAL_PORT
PUBLIC_HOST=$host
PUBLIC_URL=https://$host:$HTTPS_PORT/
TIME_ZONE=$(cat /etc/timezone 2>/dev/null || readlink /etc/localtime 2>/dev/null | sed 's|.*zoneinfo/||' || echo Etc/UTC)
N8N_ENCRYPTION_KEY=$(openssl rand -hex 32)
OWNER_EMAIL=${OWNER_EMAIL:-admin@localhost}
OWNER_PASSWORD=${OWNER_PASSWORD:-A$(openssl rand -hex 8)9}
EOF
  chmod 600 "$ENV_FILE"
  ok "Wrote $ENV_FILE"
fi

mkdir -p "$HOME/services/n8n/data"

# ---------------------------------------------------------------- deploy
info "Starting container (docker compose up -d) — first run pulls the image"
docker compose --project-directory "$SERVICE_DIR" up -d

info "Waiting for n8n on 127.0.0.1:$LOCAL_PORT (first start runs DB migrations)"
wait_http "http://127.0.0.1:$LOCAL_PORT/healthz" 60 3 || die "n8n did not come up. Logs: docker compose --project-directory $SERVICE_DIR logs n8n"
ok "n8n is answering locally"

# ------------------------------------------------------------ seed owner
# /healthz answers during DB migrations; wait for the REST API to be ready.
info "Waiting for the REST API (migrations can take a minute on first boot)"
for i in $(seq 1 40); do
  curl -fsS -o /dev/null "http://127.0.0.1:$LOCAL_PORT/rest/settings" 2>/dev/null && break
  [ "$i" -eq 40 ] && warn "REST API not ready — skipping owner seeding, finish setup in the web UI."
  sleep 3
done

info "Seeding owner account (idempotent)"
owner_email="$(sed -n 's/^OWNER_EMAIL=\(.*\)$/\1/p' "$ENV_FILE")"
owner_pw="$(sed -n 's/^OWNER_PASSWORD=\(.*\)$/\1/p' "$ENV_FILE")"
# browser-id header: n8n 2.x rejects browserless POSTs without it.
resp="$(curl -s -X POST "http://127.0.0.1:$LOCAL_PORT/rest/owner/setup" \
  -H 'Content-Type: application/json' -H 'browser-id: setup-script' \
  -d "{\"email\":\"$owner_email\",\"firstName\":\"Admin\",\"lastName\":\"User\",\"password\":\"$owner_pw\"}" || true)"
if grep -q '"email"' <<<"$resp"; then
  ok "Owner account created: $owner_email"
elif grep -qi 'already' <<<"$resp"; then
  ok "Owner already set up — skipping"
else
  warn "Owner seeding inconclusive — if you can't log in, finish setup in the web UI. Response: ${resp:0:200}"
fi

# ------------------------------------------------------- tailscale serve
info "Publishing via Tailscale Serve (HTTPS :$HTTPS_PORT, tailnet only)"
ts_serve_publish "$HTTPS_PORT" "http://127.0.0.1:$LOCAL_PORT"

# ------------------------------------------------------------ final check
url="https://$host:$HTTPS_PORT"
info "Verifying $url (first request can take ~60s while the TLS cert is minted)"
if curl -fsS -o /dev/null --max-time 90 "$url/healthz"; then
  ok "End-to-end check passed"
else
  echo "    Cert may still be minting — try again in a minute: curl $url/healthz"
fi

echo
printf '\033[1;32mDone.\033[0m n8n is at \033[1m%s\033[0m (tailnet only).\n' "$url"
echo
echo "Login: $owner_email (password in $ENV_FILE)"
echo "Webhook base URL for workflows: $url"
echo "Manage: docker compose --project-directory $SERVICE_DIR ps|logs|restart|down"
echo "Upgrade: docker compose --project-directory $SERVICE_DIR pull && docker compose --project-directory $SERVICE_DIR up -d"
