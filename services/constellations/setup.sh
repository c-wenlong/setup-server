#!/usr/bin/env bash
#
# setup.sh — publish Constellations (the private design-research app) on
# the tailnet and register it with the launcher. Linux + macOS.
#
# The app itself is not installed here. The constellations repo's
# scripts/studio-deploy.sh owns the checkout, the build and
# design-research.service (next start on 127.0.0.1:8845). This script only
# publishes that listener through Tailscale Serve and writes the .env the
# launcher reads.
#
# End state:
#   - https://<host>.<tailnet>.ts.net:HTTPS_PORT proxies to
#     http://127.0.0.1:LOCAL_PORT (the app's own listener, default 8845)
#   - .env records both ports so the tile follows them
#
# Usage:
#   ./setup.sh
#   HTTPS_PORT=8108 LOCAL_PORT=8845 ./setup.sh   # first run only; .env wins
#
# Requirements: Tailscale logged in, and the app already answering on
# LOCAL_PORT. Sudo is needed at most once on Linux (tailscale operator).
#
# Idempotent. An existing .env is never rewritten. Re-running repairs the
# Serve mapping and starts the app if Remove had stopped it.

set -euo pipefail

LOCAL_PORT="${LOCAL_PORT:-8845}"
HTTPS_PORT_EXPLICIT="${HTTPS_PORT:+yes}"
HTTPS_PORT="${HTTPS_PORT:-8108}"

SERVICE_DIR="$(cd "$(dirname "$0")" && pwd)"
ENV_FILE="$SERVICE_DIR/.env"

# shellcheck source=../../lib/common.sh
. "$SERVICE_DIR/../../lib/common.sh"
detect_os

# ---------------------------------------------------------------- preflight
info "Preflight checks ($OS)"
refuse_root "Run as a regular user, not root (sudo is invoked only where needed)."
command -v curl >/dev/null || die "curl is required (health check)."
resolve_tailscale
require_tailscale_up

TS_HOST="$(tailnet_host)"
[ -n "$TS_HOST" ] || die "Could not determine tailnet DNS name (is MagicDNS enabled?)"
ok "$OS + curl + Tailscale (running as $TS_HOST)"

# ---------------------------------------------------------------- .env
if [ -f "$ENV_FILE" ]; then
  ok "Config already exists, leaving untouched: $ENV_FILE"
else
  info "Writing $ENV_FILE"
  cat > "$ENV_FILE" <<EOF
# Generated by setup.sh on first run. Gitignored. Edit and re-run setup.sh.
# No secrets live in this file.

# The app listens on LOCAL_PORT. Tailscale Serve publishes it on HTTPS_PORT.
# The app allows only its configured private origin, so HTTPS_PORT must be
# the port in DESIGN_RESEARCH_PRIVATE_ORIGIN (8108 on this box).
LOCAL_PORT=$LOCAL_PORT
HTTPS_PORT=$HTTPS_PORT
EOF
  ok "Wrote $ENV_FILE"
fi

REQUESTED_PORT="$LOCAL_PORT"
REQUESTED_HTTPS="$HTTPS_PORT"
env_lint "$ENV_FILE"
set -a; . "$ENV_FILE"; set +a
LOCAL_PORT="${LOCAL_PORT:?LOCAL_PORT missing from $ENV_FILE}"
HTTPS_PORT="${HTTPS_PORT:-8108}"
if [ "$LOCAL_PORT" != "$REQUESTED_PORT" ]; then
  warn "LOCAL_PORT=$REQUESTED_PORT ignored: $ENV_FILE says $LOCAL_PORT. Edit .env and re-run to move it."
fi
if [ -n "$HTTPS_PORT_EXPLICIT" ] && [ "$HTTPS_PORT" != "$REQUESTED_HTTPS" ]; then
  warn "HTTPS_PORT=$REQUESTED_HTTPS ignored: $ENV_FILE says $HTTPS_PORT. Edit .env and re-run to move it."
fi
require_numeric LOCAL_PORT HTTPS_PORT
TARGET="http://127.0.0.1:$LOCAL_PORT"

# ---------------------------------------------------------------- start
# Remove disables the unit. Install has to bring it back, or the tile stays
# on Install after a failed health check.
if [ "$OS" = "Linux" ]; then
  systemctl --user enable --now design-research.service
else
  launchctl enable "gui/$(id -u)/com.setup-server.constellations" || true
  launchctl bootstrap "gui/$(id -u)" "$HOME/Library/LaunchAgents/com.setup-server.constellations.plist" || true
fi
ok "Started design-research.service"

# ---------------------------------------------------------------- publish
info "Publishing https://$TS_HOST:$HTTPS_PORT -> $TARGET"
if ts_serve_foreign "$HTTPS_PORT" "$TARGET"; then
  die "HTTPS :$HTTPS_PORT already proxies to a different target. To hand the port to this service: $TAILSCALE serve --https=$HTTPS_PORT off, then re-run."
fi
ts_serve_publish "$HTTPS_PORT" "$TARGET"
# ts_serve_publish returns success when it leaves a foreign mapping alone.
# Confirm the port actually points here before calling it published.
"$TAILSCALE" serve status | awk -v want=":$HTTPS_PORT" -v t="$TARGET" '
  /^https:\/\// {
    inport = 0
    u = $1; sub(/\/$/, "", u)
    p = match(u, /:[0-9]+$/) ? substr(u, RSTART) : ":443"
    inport = (p == want)
    next
  }
  inport && /\|-- / && / proxy / && $NF == t { found = 1 }
  END { exit !found }' \
  || die "HTTPS :$HTTPS_PORT does not proxy to $TARGET. Open would reach something else."
ok "Published"

# ---------------------------------------------------------------- verify
info "Checking $TARGET/"
wait_http "$TARGET/" 10 1 \
  || die "The app did not answer on $TARGET. Check design-research.service, then re-run."
ok "App answers"

echo
ok "Constellations is at https://$TS_HOST:$HTTPS_PORT/"
echo "  Start/stop: systemctl --user start|stop design-research.service"
echo "  The app's own deploy: the constellations repo's scripts/studio-deploy.sh"
