#!/usr/bin/env bash
#
# setup.sh — one-shot deploy of Infisical (self-hosted secrets manager:
# env vars, API keys, certs) behind Tailscale. Linux + macOS.
#
# End state:
#   - infisical + postgres + redis containers on one bridge network;
#     only the app is published, on 127.0.0.1:LOCAL_PORT
#   - reachable tailnet-only at https://<host>.<tailnet>.ts.net:HTTPS_PORT
#   - first super-admin + org seeded via POST /api/v1/admin/bootstrap,
#     which also returns an instance-admin machine-identity token (saved
#     to .env) and — since v0.162.8 — closes public signup on
#     self-hosted instances
#   - boot-persistent via Docker's restart policy (no systemd/launchd)
#
# Usage:
#   ./setup.sh                                    # local 8110, HTTPS 8110
#   LOCAL_PORT=8111 ./setup.sh                    # HTTPS follows LOCAL_PORT
#   LOCAL_PORT=8111 HTTPS_PORT=8222 ./setup.sh
#   INFISICAL_ADMIN_EMAIL=you@x.com ./setup.sh    # first run only; .env wins after
#
# Version: pinned to v0.167.6. Bump INFISICAL_VERSION in .env, then re-run.
#
# Requirements: Linux or macOS, curl, Docker + Compose v2, Tailscale logged in.
#
# Idempotent: safe to re-run; it upgrades the image and repairs the publish.
# An existing .env is never overwritten — with one exception: the
# INFISICAL_ADMIN_TOKEN line appended the one time bootstrap succeeds.

set -euo pipefail

LOCAL_PORT="${LOCAL_PORT:-8110}"
# The HTTPS port follows the local port unless set explicitly (the n8n
# convention), so overriding only LOCAL_PORT cannot split the
# two. Whether it was explicit is remembered for the .env read-back below.
HTTPS_PORT_EXPLICIT="${HTTPS_PORT:+yes}"
HTTPS_PORT="${HTTPS_PORT:-$LOCAL_PORT}"
ADMIN_EMAIL="${INFISICAL_ADMIN_EMAIL:-admin@example.com}"

SERVICE_DIR="$(cd "$(dirname "$0")" && pwd)"
ENV_FILE="$SERVICE_DIR/.env"
STATE="$HOME/services/infisical"
BOOTSTRAP_MARKER="$STATE/.bootstrapped"

# shellcheck source=../../lib/common.sh
. "$SERVICE_DIR/../../lib/common.sh"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# randhex [N] -> N bytes as hex (2N chars). [A-Za-z0-9]-safe, so it
# survives .env, shell quoting and a postgres URI without escaping.
# python3 when present, /dev/urandom otherwise.
randhex() {
  local n="${1:-16}"
  if command -v python3 >/dev/null 2>&1; then
    python3 -c "import secrets; print(secrets.token_hex($n))"
  else
    od -An -tx1 -N"$n" /dev/urandom | tr -d ' \n'
    echo
  fi
}

# AUTH_SECRET wants 32 random bytes base64-encoded (openssl rand -base64 32
# upstream). openssl first, python3 next, /dev/urandom + base64 last.
randb64() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -base64 32
  elif command -v python3 >/dev/null 2>&1; then
    python3 -c 'import base64, secrets; print(base64.b64encode(secrets.token_bytes(32)).decode())'
  else
    head -c 32 /dev/urandom | base64
  fi
}

# ---------------------------------------------------------------- preflight
detect_os
info "Preflight checks ($OS)"
refuse_root
command -v curl >/dev/null || die "curl is required."
resolve_tailscale
require_docker_compose
require_tailscale_up
require_numeric LOCAL_PORT HTTPS_PORT

ok "$OS + curl + Docker (daemon reachable) + Compose v2 + Tailscale (running)"

# The tailnet name is needed *before* the containers start, not after: it
# goes into SITE_URL, and Infisical builds every login redirect, invite
# link and the CORS default from it. Resolve it up front and drift-check
# it on every run.
TS_HOST="$(tailnet_host)"
[ -n "$TS_HOST" ] || die "Could not determine tailnet DNS name (is MagicDNS enabled?)"
ok "Tailnet name: $TS_HOST"

# ---------------------------------------------------------------- .env
if [ -f "$ENV_FILE" ]; then
  ok "Config already exists, leaving untouched: $ENV_FILE"
else
  info "Writing .env (generated admin password + platform keys)"
  tz="Etc/UTC"
  if [ -L /etc/localtime ]; then
    tz="$(readlink /etc/localtime | sed 's#.*/zoneinfo/##')"
  elif [ -f /etc/timezone ]; then
    tz="$(cat /etc/timezone)"
  fi
  enc_key="$(randhex 16)"   # exactly 16 bytes hex, per upstream
  auth_secret="$(randb64)"
  db_pass="$(randhex 16)"
  admin_pass="$(randhex 16)"
  cat > "$ENV_FILE" <<EOF
# Generated by setup.sh. Gitignored; mode 600.
# Docker Compose reads this file from the project directory for interpolation.

# Pinned. Upstream floats \`latest\` (and redis/postgres float a minor line).
# To upgrade: bump, then ./setup.sh.
INFISICAL_VERSION=v0.167.6
POSTGRES_VERSION=16.15-alpine
REDIS_VERSION=7.4-alpine

LOCAL_PORT=$LOCAL_PORT
TZ=$tz

# Marker dir (launcher "installed") and bootstrap marker home. The live
# data is the named volumes infisical-postgres (the vault) and
# infisical-redis (cache + job queue).
INFISICAL_DATA=$STATE

# Public identity — the tailnet HTTPS URL. SITE_URL feeds every login
# redirect, emailed link and the CORS default. If the machine is renamed
# or the HTTPS port moves, edit this line and re-run setup.sh (it warns
# when the value drifts from the live tailnet name).
SITE_URL=https://$TS_HOST:$HTTPS_PORT

# Platform keys. ENCRYPTION_KEY is the root for every secret at rest:
# losing it loses the vault even with a perfect database backup. Never
# rotate either on a live instance — already-encrypted secrets become
# unreadable.
ENCRYPTION_KEY=$enc_key
AUTH_SECRET=$auth_secret

# Postgres sidecar. The connection string is built in docker-compose.yml
# from these three, so there is one password to rotate, not two.
POSTGRES_DB=infisical
POSTGRES_USER=infisical
POSTGRES_PASSWORD=$db_pass

# First super-admin + organisation, seeded once via
# POST /api/v1/admin/bootstrap. Bootstrap also mints an instance-admin
# machine identity; setup.sh saves its token below as
# INFISICAL_ADMIN_TOKEN on the run that creates it, and (since v0.162.8)
# the instance closes public signup itself. Changing the password here
# after bootstrap does not rotate the live one — do that in the UI.
INFISICAL_ADMIN_EMAIL=$ADMIN_EMAIL
INFISICAL_ADMIN_PASSWORD=$admin_pass
INFISICAL_ORG=homeserver
EOF
  chmod 600 "$ENV_FILE"
  ok "Wrote $ENV_FILE"
fi

# Read back: an existing .env is the source of truth for ports, paths and
# credentials, so a re-run can never silently move a live deployment.
REQUESTED_PORT="$LOCAL_PORT"
env_lint "$ENV_FILE"
set -a; . "$ENV_FILE"; set +a
DATA_DIR="${INFISICAL_DATA:?INFISICAL_DATA missing from $ENV_FILE}"
SITE_URL="${SITE_URL:?SITE_URL missing from $ENV_FILE}"
ADMIN_EMAIL="${INFISICAL_ADMIN_EMAIL:?INFISICAL_ADMIN_EMAIL missing from $ENV_FILE}"
ADMIN_PASSWORD="${INFISICAL_ADMIN_PASSWORD:?INFISICAL_ADMIN_PASSWORD missing from $ENV_FILE}"
ORG="${INFISICAL_ORG:-homeserver}"
if [ "$LOCAL_PORT" != "$REQUESTED_PORT" ]; then
  warn "LOCAL_PORT=$REQUESTED_PORT ignored — the existing $ENV_FILE says $LOCAL_PORT. Edit .env and re-run to move the port."
fi
# .env holds no HTTPS_PORT (only the derived SITE_URL), so a default HTTPS
# port keeps following the local port .env settled on; an explicit
# HTTPS_PORT is honoured as given.
[ -n "$HTTPS_PORT_EXPLICIT" ] || HTTPS_PORT="$LOCAL_PORT"

# Drift check, not a rewrite: .env is the user's file. But a SITE_URL that
# no longer matches this machine breaks login redirects and CORS silently,
# so say so loudly.
WANT_URL="https://$TS_HOST:$HTTPS_PORT"
if [ "$SITE_URL" != "$WANT_URL" ]; then
  warn "SITE_URL in .env is $SITE_URL but this box now answers to $WANT_URL."
  warn "  Login redirects, emailed links and CORS will point at the old address. Fix: set SITE_URL=$WANT_URL in $ENV_FILE, then re-run."
fi

mkdir -p "$DATA_DIR"

avail_kb="$(df -Pk "$DATA_DIR" | awk 'NR==2{print $4}')"
if [ "${avail_kb:-0}" -lt 1048576 ]; then
  warn "$(( avail_kb / 1024 )) MB free at $DATA_DIR — the Postgres volume grows with every secret version and audit log."
else
  ok "$(( avail_kb / 1048576 )) GB free at $DATA_DIR"
fi

# ---------------------------------------------------------------- deploy
COMPOSE=(docker compose --project-directory "$SERVICE_DIR")

info "Starting Infisical (docker compose up -d) — first run pulls ~700 MB and runs migrations"
"${COMPOSE[@]}" up -d

info "Waiting for Infisical on 127.0.0.1:$LOCAL_PORT (first boot runs the DB migrations)"
wait_http "http://127.0.0.1:$LOCAL_PORT/api/status" 90 3 || die "Infisical did not come up. Logs: docker compose --project-directory $SERVICE_DIR logs infisical"
ok "Infisical is answering locally"

# ------------------------------------------------- bootstrap (first run)
# POST /api/v1/admin/bootstrap creates the first super-admin, the org, and
# an instance-admin machine identity, and returns that identity's token.
# One call, no web wizard. On self-hosted builds >= v0.162.8 it also
# closes public signup, so the door behind the seeded admin is shut.
#
# Idempotency is two-layered, like forgejo's admin creation: the marker
# means a normal re-run never posts again, and a response saying the
# instance is already bootstrapped still counts as success — a run that
# died after bootstrapping but before writing the marker recovers cleanly.
BOOTSTRAPPED=0
if [ -f "$BOOTSTRAP_MARKER" ]; then
  ok "Instance already bootstrapped ($ADMIN_EMAIL) — skipping"
else
  if command -v python3 >/dev/null 2>&1; then
    info "Seeding the first super-admin via /api/v1/admin/bootstrap"
    payload="$(INF_EMAIL="$ADMIN_EMAIL" INF_PASS="$ADMIN_PASSWORD" INF_ORG="$ORG" python3 -c '
import json, os
print(json.dumps({
  "email": os.environ["INF_EMAIL"],
  "password": os.environ["INF_PASS"],
  "organization": os.environ["INF_ORG"],
}))')"
    # curl already prints 000 on a refused connection AND exits non-zero;
    # a `|| echo 000` fallback would concatenate that into "000000".
    code="$(curl -sS -o "$WORK/bootstrap.json" -w '%{http_code}' --max-time 60 \
      -X POST -H 'Content-Type: application/json' --data-binary "$payload" \
      "http://127.0.0.1:$LOCAL_PORT/api/v1/admin/bootstrap" 2>/dev/null)" || true
    case "$code" in
      [0-9][0-9][0-9]) ;;
      *) code=000 ;;
    esac
    body="$(cat "$WORK/bootstrap.json" 2>/dev/null || true)"
    if [ "$code" = "200" ]; then
      token="$(printf '%s' "$body" | sed -n 's/.*"token": *"\([^"]*\)".*/\1/p' | head -1)"
      mkdir -p "$STATE"
      printf '%s\n' "$ADMIN_EMAIL" > "$BOOTSTRAP_MARKER"
      BOOTSTRAPPED=1
      ok "Super-admin seeded: $ADMIN_EMAIL (org: $ORG)"
      # The machine-identity token is instance-admin on the API — the
      # credential the `infisical` CLI and Terraform want. It only ever
      # appears in the bootstrap response, so it is saved into .env now or
      # never. Appended via the printf builtin so it never sits in an
      # external command's argv; an existing line is never overwritten.
      if [ -n "$token" ] && ! grep -q '^INFISICAL_ADMIN_TOKEN=' "$ENV_FILE"; then
        printf '\n# Instance-admin machine-identity token, minted by bootstrap\n# (API/CLI auth; treat like the admin password).\nINFISICAL_ADMIN_TOKEN=%s\n' "$token" >> "$ENV_FILE"
        ok "Instance-admin token saved to INFISICAL_ADMIN_TOKEN in $ENV_FILE"
      elif ! grep -q '^INFISICAL_ADMIN_TOKEN=' "$ENV_FILE"; then
        warn "Bootstrap succeeded but no machine-identity token was found in the response — mint one later in Server Console -> Access Control, or via a new machine identity."
      fi
    else
      case "$body" in
        *[Bb]ootstrap*|*[Aa]lready*)
          ok "Instance is already bootstrapped — leaving the existing admin alone"
          mkdir -p "$STATE"
          printf '%s\n' "$ADMIN_EMAIL" > "$BOOTSTRAP_MARKER"
          ;;
        *)
          warn "POST /api/v1/admin/bootstrap returned HTTP $code — no admin was seeded. Sign up at the URL below (the first signup becomes the instance admin), then re-run ./setup.sh."
          ;;
      esac
    fi
  else
    warn "python3 is required to seed the admin automatically. Sign up at the URL below (the first signup becomes the instance admin), then re-run ./setup.sh."
  fi
fi

# ------------------------------------------------------- tailscale serve
info "Publishing via Tailscale Serve (HTTPS :$HTTPS_PORT -> 127.0.0.1:$LOCAL_PORT)"
ts_serve_publish "$HTTPS_PORT" "http://127.0.0.1:$LOCAL_PORT"

# ------------------------------------------------------------ final check
url="https://$TS_HOST:$HTTPS_PORT"
info "Verifying $url/api/status (first request can take ~60s while the TLS cert is minted)"
if curl -fsS -o /dev/null --max-time 90 "$url/api/status"; then
  ok "End-to-end HTTPS check passed"
else
  warn "No answer on $url/api/status yet — the cert may still be minting. Retry in a minute: curl $url/api/status"
fi

echo
printf '\033[1;32mDone.\033[0m Infisical is at \033[1m%s\033[0m (tailnet only).\n' "$url"
echo
echo "  Sign in:  $ADMIN_EMAIL"
echo "  Password: INFISICAL_ADMIN_PASSWORD in $ENV_FILE"
if [ "$BOOTSTRAPPED" = "1" ] || [ -f "$BOOTSTRAP_MARKER" ]; then
  echo "  API/CLI:  INFISICAL_ADMIN_TOKEN in .env is an instance-admin machine"
  echo "    identity — e.g. infisical login --method=token --domain=$url"
  echo "  Signups:  closed automatically after bootstrap (self-hosted builds"
  echo "    since v0.162.8). Re-open in Server Console -> Authentication."
else
  printf '\033[1;33m ! \033[0m %s\n' "Bootstrap did not run — the signup page is still open."
  echo "    The first account created at $url becomes the instance"
  echo "    admin. Create it, then re-run ./setup.sh."
fi
echo "  Email:    no SMTP configured — MFA codes, invites and login alerts"
echo "    need SMTP_* in .env plus matching keys in docker-compose.yml."
echo
echo "Backups: nothing backs this box up. The vault is the named volume"
echo "  infisical-postgres plus ENCRYPTION_KEY in .env — a dump without the"
echo "  key restores nothing readable. Keep both:"
echo "    docker compose --project-directory $SERVICE_DIR exec -T db \\"
echo "      pg_dump -U infisical infisical > infisical-\$(date +%F).sql"
echo
echo "Manage:  docker compose --project-directory $SERVICE_DIR ps|logs|restart|down"
echo "Upgrade: bump INFISICAL_VERSION in $ENV_FILE, then ./setup.sh"
exit 0
