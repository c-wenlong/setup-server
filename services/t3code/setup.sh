#!/usr/bin/env bash
#
# setup.sh — one-shot deploy of T3 Code (`t3 serve`) behind Tailscale
# (Linux + macOS).
#
# End state:
#   - the upstream `t3` bundle installed under ~/.local/share/t3code,
#     releases/<version> with `bin` symlinked at the live one
#   - `t3 serve` listening on 127.0.0.1:LOCAL_PORT only, state in
#     ~/services/t3code (--base-dir), no browser, no password — the tailnet
#     is the auth layer
#   - kept alive + started at boot/login:
#       Linux: systemd --user unit + lingering
#       macOS: launchd LaunchAgent (starts at login)
#   - published tailnet-only at https://<host>.<tailnet>.ts.net:HTTPS_PORT
#     via Tailscale Serve: the web UI for steering coding agents on this box
#
# Usage:
#   ./setup.sh                                  # local 8109, HTTPS 8109, latest
#   LOCAL_PORT=8110 ./setup.sh                  # first run only; .env wins after
#   T3_VERSION=0.1.8 ./setup.sh                 # pin this run (or set it in .env)
#
# Requirements: Linux (systemd) or macOS arm64, curl, tar, Tailscale logged in.
# Sudo is needed at most twice on Linux (lingering, tailscale operator), never
# on macOS. Upstream ships no Intel-Mac build, so Darwin/x86_64 is refused.
#
# Idempotent: safe to re-run. T3_VERSION=latest (the default) resolves the
# newest GitHub release on every run and upgrades when it moved; a pinned
# version reinstalls only when the pin changes. An existing .env is never
# rewritten.
#
# The unit's PATH puts ~/.nix-profile/bin and ~/.local/bin first because t3
# orchestrates the agent CLIs on this box (claude, codex, cursor-agent,
# devin, gh) — a user unit starts with a minimal PATH otherwise.

set -euo pipefail

LOCAL_PORT="${LOCAL_PORT:-8109}"
# HTTPS follows LOCAL_PORT unless given, so overriding one can't split them.
HTTPS_PORT_EXPLICIT="${HTTPS_PORT:+yes}"
HTTPS_PORT="${HTTPS_PORT:-$LOCAL_PORT}"
T3_VERSION_EXPLICIT="${T3_VERSION:-}"
T3_VERSION="${T3_VERSION:-latest}"

SERVICE_DIR="$(cd "$(dirname "$0")" && pwd)"
ENV_FILE="$SERVICE_DIR/.env"
INSTALL_DIR="$HOME/.local/share/t3code"
DATA_DIR="$HOME/services/t3code"
REV_FILE="$INSTALL_DIR/installed-ver"
UNIT_NAME="t3code.service"
UNIT="$HOME/.config/systemd/user/$UNIT_NAME"
PLIST_LABEL="com.setup-server.t3code"
PLIST="$HOME/Library/LaunchAgents/$PLIST_LABEL.plist"

# shellcheck source=../../lib/common.sh
. "$SERVICE_DIR/../../lib/common.sh"
detect_os

# ---------------------------------------------------------------- preflight
info "Preflight checks ($OS)"
refuse_root "Run as a regular user, not root (sudo is invoked only where needed)."
command -v curl >/dev/null || die "curl is required (downloads, health checks)."
command -v tar  >/dev/null || die "tar is required (the t3 bundle is a tarball)."
if [ "$OS" = "Linux" ]; then
  command -v systemctl >/dev/null || die "systemd is required on Linux (the service runs as a systemd user unit)."
  command -v loginctl >/dev/null  || die "loginctl is required on Linux (lingering, for boot persistence)."
else
  command -v launchctl >/dev/null || die "launchctl is required on macOS (the service runs as a LaunchAgent)."
fi
ARCH="$(uname -m)"
case "$OS/$ARCH" in
  Linux/x86_64)   TARGET="linux-x64" ;;
  Linux/aarch64|Linux/arm64) TARGET="linux-arm64" ;;
  Darwin/arm64)   TARGET="darwin-arm64" ;;
  Darwin/*)       die "No upstream t3 build for macOS $ARCH (only Apple Silicon). Run this on the Mac's ARM machine or use the web UI from a browser." ;;
  *)              die "Unsupported platform: $OS/$ARCH" ;;
esac

resolve_tailscale
require_tailscale_up

TS_HOST="$(tailnet_host)"
[ -n "$TS_HOST" ] || die "Could not determine tailnet DNS name (is MagicDNS enabled?)"
ok "$OS/$ARCH ($TARGET) + curl + tar + Tailscale (running as $TS_HOST)"

# ---------------------------------------------------------------- .env
if [ -f "$ENV_FILE" ]; then
  ok "Config already exists, leaving untouched: $ENV_FILE"
else
  info "Writing $ENV_FILE"
  cat > "$ENV_FILE" <<EOF
# Generated by setup.sh on first run. Gitignored. Edit and re-run setup.sh;
# No secrets live in this file.

# t3 binds 127.0.0.1:LOCAL_PORT; Tailscale Serve publishes it on
# https://<host>:HTTPS_PORT.
LOCAL_PORT=$LOCAL_PORT
HTTPS_PORT=$HTTPS_PORT

# Which upstream release the service runs: "latest" re-resolves the newest
# GitHub release on every setup.sh run; pin with e.g. T3_VERSION=0.1.8.
T3_VERSION=$T3_VERSION
EOF
  ok "Wrote $ENV_FILE"
fi

# Read back: .env is the source of truth for the ports and the version, so a
# re-run can never silently move a live deployment. Explicit env vars win
# for this run only.
REQUESTED_PORT="$LOCAL_PORT"
REQUESTED_HTTPS="$HTTPS_PORT"
env_lint "$ENV_FILE"
set -a; . "$ENV_FILE"; set +a
LOCAL_PORT="${LOCAL_PORT:?LOCAL_PORT missing from $ENV_FILE}"
HTTPS_PORT="${HTTPS_PORT:-$LOCAL_PORT}"
T3_VERSION="${T3_VERSION_EXPLICIT:-${T3_VERSION:-latest}}"
if [ "$LOCAL_PORT" != "$REQUESTED_PORT" ]; then
  warn "LOCAL_PORT=$REQUESTED_PORT ignored: $ENV_FILE says $LOCAL_PORT. Edit .env and re-run to move it."
fi
if [ -n "$HTTPS_PORT_EXPLICIT" ] && [ "$HTTPS_PORT" != "$REQUESTED_HTTPS" ]; then
  warn "HTTPS_PORT=$REQUESTED_HTTPS ignored: $ENV_FILE says $HTTPS_PORT. Edit .env and re-run to move it."
fi

require_numeric LOCAL_PORT HTTPS_PORT
# A bare `--https=443` replaces whatever owns "/" there (code-server on this box).
[ "$HTTPS_PORT" != "443" ] || die "HTTPS_PORT=443 would replace the :443 / handler (code-server). Pick another port."

# Serve is one mapping per port: publishing over another service's HTTPS port
# would silently take it down. Our own mapping (a re-run) is fine.
SERVE_TARGET="http://127.0.0.1:$LOCAL_PORT"
existing="$("$TAILSCALE" serve status 2>/dev/null | awk -v hdr="https://$TS_HOST:$HTTPS_PORT " '
  index($0, hdr) == 1 { inblk = 1; next }
  /^https?:\/\// { inblk = 0 }
  inblk && $2 == "/" && $3 == "proxy" { print $4; exit }' || true)"
if [ -n "$existing" ] && [ "$existing" != "$SERVE_TARGET" ]; then
  die "HTTPS :$HTTPS_PORT is already published for $existing. Set another HTTPS_PORT in $ENV_FILE (see tailscale serve status)."
fi
PUBLIC_URL="https://$TS_HOST:$HTTPS_PORT"
ok "Ports: 127.0.0.1:$LOCAL_PORT, HTTPS :$HTTPS_PORT ($PUBLIC_URL)"

# ---------------------------------------------------- install / upgrade
# Resolve T3_VERSION to a concrete release version (no leading v): "latest"
# follows the releases/latest redirect; anything else is a pin (v-prefix ok).
info "Resolving t3 $T3_VERSION"
if [ "$T3_VERSION" = "latest" ]; then
  tag="$(curl -fsSL -o /dev/null -w '%{url_effective}' \
    https://github.com/pingdotgg/t3code/releases/latest 2>/dev/null)" \
    || die "Could not resolve the latest t3 release (github.com unreachable?)."
  VER="${tag##*/}"
  VER="${VER#v}"
  case "$VER" in ''|*[!0-9A-Za-z._+-]*) die "Unrecognised latest-release tag: ${tag:-empty}" ;; esac
else
  VER="${T3_VERSION#v}"
fi
ok "t3 $T3_VERSION -> $VER ($TARGET)"

installed="$(cat "$REV_FILE" 2>/dev/null || true)"
if [ "$installed" = "$VER" ] && [ -x "$INSTALL_DIR/bin/t3" ]; then
  ok "t3 $VER already installed in $INSTALL_DIR"
else
  if [ -n "$installed" ]; then
    info "Upgrading t3 $installed -> $VER"
  else
    info "Installing t3 $VER into $INSTALL_DIR"
  fi
  url="https://github.com/pingdotgg/t3code/releases/download/v$VER/t3-$VER-$TARGET.tar.gz"
  tmp="$(mktemp -d)"
  trap 'rm -rf "$tmp"' EXIT
  info "Downloading $url"
  curl -fsSL "$url" -o "$tmp/t3.tar.gz" \
    || { rm -rf "$tmp"; trap - EXIT; die "Download failed: $url (does v$VER ship a $TARGET build?)"; }
  # The tarball's top-level dir is t3-<ver>-<target>; find it rather than
  # assume, so a renamed asset fails loudly here and not at ExecStart.
  srcdir="$(tar -tzf "$tmp/t3.tar.gz" 2>/dev/null | head -1 | cut -d/ -f1 || true)"
  [ -n "$srcdir" ] || { rm -rf "$tmp"; trap - EXIT; die "Downloaded tarball is empty or not a tar.gz."; }
  mkdir -p "$INSTALL_DIR/releases"
  rm -rf "${INSTALL_DIR:?}/releases/$VER" "${INSTALL_DIR:?}/releases/$srcdir"
  tar -xzf "$tmp/t3.tar.gz" -C "$INSTALL_DIR/releases" \
    || { rm -rf "$INSTALL_DIR/releases/$srcdir"; trap - EXIT; die "Could not extract $url."; }
  [ -x "$INSTALL_DIR/releases/$srcdir/t3" ] \
    || { rm -rf "$INSTALL_DIR/releases/$srcdir"; die "Tarball has no runnable t3 binary at $srcdir/t3."; }
  # srcdir is already t3-<ver>-<target>; rename to the plain version so
  # `installed-ver` and the release dir agree.
  [ "$srcdir" = "$VER" ] || mv "$INSTALL_DIR/releases/$srcdir" "$INSTALL_DIR/releases/$VER"
  rm -rf "$tmp"; trap - EXIT

  # `bin` is a symlink to the live release dir; the unit's ExecStart is the
  # stable $INSTALL_DIR/bin/t3, so upgrades never rewrite the unit. The t3
  # binary finds its bundled siblings via /proc/self/exe, which resolves
  # through both symlinks to the real release dir.
  live=""
  if [ -L "$INSTALL_DIR/bin" ]; then
    live="$(basename "$(readlink "$INSTALL_DIR/bin")")"
  fi
  ln -sfn "releases/$VER" "$INSTALL_DIR/bin"
  printf '%s\n' "$VER" > "$REV_FILE"
  # Keep the live release and the one it replaced (for a quick rollback).
  for old in "$INSTALL_DIR"/releases/*; do
    case "$(basename "$old")" in "$VER"|"$live") ;; *) rm -rf "$old" ;; esac
  done
  ok "Installed t3 $VER"
fi

T3_BIN="$INSTALL_DIR/bin/t3"
[ -x "$T3_BIN" ] || die "$T3_BIN is missing — delete $REV_FILE and re-run to reinstall."

# ------------------------------------------------------------ service
# t3 orchestrates the agent CLIs on this box (claude, codex, cursor-agent,
# devin, gh, tmux) and a user unit starts with a minimal PATH, so the unit
# gets the usual user-level install locations explicitly.
SVC_PATH="$INSTALL_DIR/bin:$HOME/.nix-profile/bin:/nix/var/nix/profiles/default/bin:$HOME/.local/bin:$HOME/.npm-global/bin"
if [ "$OS" = "Linux" ]; then
  SVC_PATH="$SVC_PATH:/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
  info "Installing systemd user unit ($UNIT_NAME)"
  mkdir -p "$(dirname "$UNIT")" "$DATA_DIR"
  # Regenerated on every run: this file is generated, never hand-edited.
  cat > "$UNIT" <<EOF
[Unit]
Description=T3 Code server (web UI for coding agents on this box)
After=network.target

[Service]
Type=exec
ExecStart=$T3_BIN serve --host=127.0.0.1 --port=$LOCAL_PORT --base-dir=$DATA_DIR
Environment=PATH=$SVC_PATH
Restart=always
RestartSec=5

[Install]
WantedBy=default.target
EOF
  systemctl --user daemon-reload
  systemctl --user enable "$UNIT_NAME" >/dev/null 2>&1
  systemctl --user restart "$UNIT_NAME"   # restart, not start: pick up a new build or unit
  ok "Unit installed, enabled and (re)started"
else
  SVC_PATH="$SVC_PATH:/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"
  info "Installing launchd LaunchAgent ($PLIST_LABEL)"
  mkdir -p "$(dirname "$PLIST")" "$HOME/Library/Logs" "$DATA_DIR"
  cat > "$PLIST" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>$PLIST_LABEL</string>
  <key>ProgramArguments</key>
  <array>
    <string>$T3_BIN</string><string>serve</string>
    <string>--host=127.0.0.1</string><string>--port=$LOCAL_PORT</string>
    <string>--base-dir=$DATA_DIR</string>
  </array>
  <key>EnvironmentVariables</key>
  <dict>
    <key>PATH</key><string>$SVC_PATH</string>
  </dict>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>StandardOutPath</key><string>$HOME/Library/Logs/t3code.log</string>
  <key>StandardErrorPath</key><string>$HOME/Library/Logs/t3code.log</string>
</dict>
</plist>
EOF
  launchctl bootout "gui/$(id -u)/$PLIST_LABEL" 2>/dev/null || true
  launchctl bootstrap "gui/$(id -u)" "$PLIST"
  ok "LaunchAgent loaded (starts at login; logs: ~/Library/Logs/t3code.log)"
fi

if [ "$OS" = "Linux" ]; then
  LOGCMD="journalctl --user -u $UNIT_NAME -n 50 --no-pager"
else
  LOGCMD="tail -n 50 ~/Library/Logs/t3code.log"
fi

# The web UI is a SPA; "/" answering at all means the server is up.
info "Waiting for the web UI on http://127.0.0.1:$LOCAL_PORT/"
for i in $(seq 1 30); do
  if curl -fsS -o /dev/null --max-time 3 "http://127.0.0.1:$LOCAL_PORT/" 2>/dev/null; then
    ok "t3 is serving locally"
    break
  fi
  [ "$i" -eq 30 ] && die "t3 did not answer on 127.0.0.1:$LOCAL_PORT. Logs: $LOGCMD"
  sleep 1
done

# ------------------------------------------------------------- lingering
# Linux only: makes user services start at boot and survive logout.
if [ "$OS" = "Linux" ]; then
  if [ "$(loginctl show-user "$USER" -p Linger --value 2>/dev/null)" = "yes" ]; then
    ok "Lingering already enabled"
  else
    info "Enabling lingering so t3 starts at boot (needs sudo, one time)"
    sudo loginctl enable-linger "$USER"
    ok "Lingering enabled"
  fi
fi

# ------------------------------------------------------- tailscale serve
ts_serve_publish "$HTTPS_PORT" "$SERVE_TARGET"

# ------------------------------------------------------------ final check
info "Verifying $PUBLIC_URL (the first request on a new port can take ~60s while the cert is minted)"
if curl -fsS -o /dev/null --max-time 90 "$PUBLIC_URL/" 2>/dev/null; then
  ok "End-to-end check passed"
else
  warn "Cert may still be minting. Try again in a minute: curl $PUBLIC_URL/"
fi

echo
printf '\033[1;32mDone.\033[0m T3 Code is at \033[1m%s\033[0m (tailnet only).\n' "$PUBLIC_URL"
echo
echo "It orchestrates the agent CLIs on this box (claude, codex, cursor-agent,"
echo "devin). First visit pairs this browser; other devices run 't3 pair'."
echo "  $T3_BIN pair --base-dir $DATA_DIR   # mint a pairing link for another device"
echo
echo "Manage it with:"
if [ "$OS" = "Linux" ]; then
  echo "  systemctl --user status|restart|stop $UNIT_NAME"
  echo "  journalctl --user -u $UNIT_NAME -f"
else
  echo "  launchctl kickstart -k gui/\$(id -u)/$PLIST_LABEL   # restart"
  echo "  tail -f ~/Library/Logs/t3code.log"
fi
echo "  tailscale serve status        # or: tailscale serve --https=$HTTPS_PORT off"
echo "  $SERVICE_DIR/setup.sh         # re-run to upgrade (T3_VERSION=latest tracks newest)"
echo "  $SERVICE_DIR/tests/run-tests.sh [--live]"
