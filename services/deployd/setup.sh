#!/usr/bin/env bash
#
# setup.sh — install deployd, the git-poller that turns "push to main" into
# "redeploy on this box" for every service that opts in (Linux + macOS).
#
# What it is: the box is tailnet-only, so GitHub webhooks cannot reach it.
# deployd polls instead — one oneshot every POLL_SECONDS (systemd user timer
# on Linux, launchd on macOS) that:
#   1. pulls this setup-server checkout ff-only (deploy config lives here,
#      so the config self-updates; if the pull touched services/deployd/
#      it re-runs this setup.sh — deployd updates itself)
#   2. scans services/*/app.json for a "deploy" block:
#        "deploy": { "repo": "<git url>", "ref": "main",
#                    "cmd": "shell run from the repo root" }
#   3. resolves repo@ref with git ls-remote and runs cmd when the sha moved
#      (state in ~/services/deployd/state/; a failed cmd backs off
#      RETRY_SECONDS before retrying that sha)
#
# A service opts in by adding the block to its own app.json — the config
# travels with the service definition. See SETUP.md for the field reference.
#
# End state:
#   - poller at ~/services/deployd/bin/deployd, state + lock under
#     ~/services/deployd/
#   - Linux: systemd user units deployd.service + deployd.timer
#     (~/.config/systemd/user/), lingering enabled so polls run at boot
#   - macOS: LaunchAgent com.setup-server.deployd (runs at login)
#   - no port, nothing published, no container — outbound git only
#
# Usage:
#   ./setup.sh                          # first run and re-runs
#   SETUP_REPO=~/dev/setup-server ./setup.sh   # override the watched checkout
#   POLL_SECONDS=120 ./setup.sh                # poll every 2 min instead
#
# Requirements: git, python3 (the poller), systemd + loginctl on Linux.
# No Docker, no Tailscale — deployd is outbound-only.
#
# Idempotent: re-running refreshes the poller + units and repairs any missing
# piece; an existing .env is never overwritten.

set -euo pipefail

NAME="deployd"
SERVICE_DIR="$(cd "$(dirname "$0")" && pwd)"
ENV_FILE="$SERVICE_DIR/.env"
SERVICE_HOME="$HOME/services/$NAME"
BIN_DIR="$SERVICE_HOME/bin"
UNIT_DIR="$HOME/.config/systemd/user"
SERVICE_UNIT="$UNIT_DIR/deployd.service"
TIMER_UNIT="$UNIT_DIR/deployd.timer"
PLIST_LABEL="com.setup-server.deployd"
PLIST="$HOME/Library/LaunchAgents/$PLIST_LABEL.plist"

# The checkout the poller pulls + scans. Default: the repo this setup.sh
# sits in (services/deployd/../../), which on the server is ~/dev/setup-server.
DEFAULT_SETUP_REPO="$(cd "$SERVICE_DIR/../.." && pwd)"
SETUP_REPO="${SETUP_REPO:-$DEFAULT_SETUP_REPO}"
POLL_SECONDS="${POLL_SECONDS:-60}"

info()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
ok()    { printf '\033[1;32m ✓ \033[0m %s\n' "$*"; }
warn()  { printf '\033[1;33m ! \033[0m %s\n' "$*"; }
die()   { printf '\033[1;31m ✗ \033[0m %s\n' "$*" >&2; exit 1; }

# ---------------------------------------------------------------- preflight
OS="$(uname -s)"
info "Preflight checks ($OS)"
case "$OS" in Linux|Darwin) ;; *) die "Unsupported OS: $OS (Linux and macOS only)";; esac
[ "$(id -u)" -ne 0 ] || die "Run as a regular user, not root."
command -v git >/dev/null     || die "git is required (polling remote refs)."
command -v python3 >/dev/null || die "python3 is required (the poller is stdlib-only python)."
command -v bash >/dev/null    || die "bash is required (deploy commands run through it)."
if [ "$OS" = "Linux" ]; then
  command -v systemctl >/dev/null || die "systemd is required on Linux (the poller is a systemd user timer)."
  command -v loginctl >/dev/null  || die "loginctl is required on Linux (lingering, for boot persistence)."
fi
[ -d "$SETUP_REPO/services" ] || die "SETUP_REPO=$SETUP_REPO is not a setup-server checkout (no services/ dir)."
case "$POLL_SECONDS" in ''|*[!0-9]*) die "POLL_SECONDS must be numeric (got: $POLL_SECONDS)";; esac
ok "$OS + git + python3 + checkout at $SETUP_REPO"

# ------------------------------------------------------------------- .env
if [ -f "$ENV_FILE" ]; then
  ok "Config already exists, leaving untouched: $ENV_FILE"
else
  info "Writing .env (paths + poll settings; mode 0600)"
  # Deploy commands are services' own setup.sh/deploy.sh scripts, which need
  # the userland tools a systemd/launchd PATH lacks (uv, docker, tailscale,
  # a nix-profile git). Bake the directories they resolve in NOW, as a
  # PATH_PREFIX the poller prepends for itself and every cmd it runs.
  PATH_PREFIX=""
  for tool in git python3 uv curl docker tailscale; do
    dir="$(dirname "$(command -v "$tool" 2>/dev/null || echo /nonexistent)")"
    if [ "$dir" != "/nonexistent" ]; then
      case ":$PATH_PREFIX:" in *":$dir:"*) ;; *) PATH_PREFIX="$PATH_PREFIX:$dir";; esac
    fi
  done
  PATH_PREFIX="${PATH_PREFIX#:}"
  {
    printf '# Generated by setup.sh. Gitignored. Edit + re-run setup.sh to apply.\n'
    printf 'SETUP_REPO=%q\n' "$SETUP_REPO"
    printf 'SERVICE_HOME=%q\n' "$SERVICE_HOME"
    printf 'POLL_SECONDS=%q\n' "$POLL_SECONDS"
    printf 'RETRY_SECONDS=%q\n' "900"
    printf 'DEPLOY_TIMEOUT=%q\n' "1800"
    printf 'PATH_PREFIX=%q\n' "$PATH_PREFIX"
  } > "$ENV_FILE"
  chmod 600 "$ENV_FILE"
  ok "Wrote $ENV_FILE"
fi

# The poller reads .env itself; setup.sh only needs SETUP_REPO/POLL_SECONDS
# back for the units. Source it (values are %q-escaped shell, so they come
# back unescaped — the same format every service's .env uses).
set -a; . "$ENV_FILE"; set +a

mkdir -p "$BIN_DIR" "$SERVICE_HOME/state"

# ----------------------------------------------------------- install poller
# Atomic: write to a temp file and mv, so a tick already running the old
# installed copy keeps its inode (a plain `cp` would truncate it mid-read —
# that matters because the pull-diff self-update can replace this file while
# a poll is running).
info "Installing poller to $BIN_DIR/deployd"
TMP_BIN="$BIN_DIR/.deployd.tmp.$$"
sed "s|^ENV_BAKED = \"__ENV_FILE__\"|ENV_BAKED = \"$ENV_FILE\"|" \
  "$SERVICE_DIR/deployd" > "$TMP_BIN"
chmod 755 "$TMP_BIN"
mv -f "$TMP_BIN" "$BIN_DIR/deployd"
ok "Installed $BIN_DIR/deployd"

# ------------------------------------------------------------------ poller
if [ "$OS" = "Linux" ]; then
  info "Installing systemd user timer (poll every ${POLL_SECONDS}s)"
  mkdir -p "$UNIT_DIR"
  cat > "$SERVICE_UNIT" <<EOF
[Unit]
Description=deployd poll cycle (refresh checkout, deploy services whose remote moved)

[Service]
Type=oneshot
ExecStart=$BIN_DIR/deployd
EOF
  cat > "$TIMER_UNIT" <<EOF
[Unit]
Description=deployd poller (push-to-deploy for a tailnet-only box)

[Timer]
OnBootSec=90
OnUnitActiveSec=${POLL_SECONDS}
AccuracySec=15

[Install]
WantedBy=timers.target
EOF
  systemctl --user daemon-reload
  systemctl --user enable --now deployd.timer >/dev/null 2>&1
  ok "Timer active: deployd.timer"

  if [ "$(loginctl show-user "$USER" -p Linger --value 2>/dev/null)" = "yes" ]; then
    ok "Lingering already enabled"
  else
    info "Enabling lingering (needs sudo, one time) so the poller runs at boot"
    sudo loginctl enable-linger "$USER"
    ok "Lingering enabled"
  fi
else
  info "Installing launchd poller (every ${POLL_SECONDS}s)"
  mkdir -p "$(dirname "$PLIST")" "$HOME/Library/Logs"
  cat > "$PLIST" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>$PLIST_LABEL</string>
  <key>ProgramArguments</key>
  <array><string>$BIN_DIR/deployd</string></array>
  <key>StartInterval</key><integer>$POLL_SECONDS</integer>
  <key>RunAtLoad</key><true/>
  <key>StandardOutPath</key><string>$HOME/Library/Logs/deployd.log</string>
  <key>StandardErrorPath</key><string>$HOME/Library/Logs/deployd.log</string>
</dict>
</plist>
EOF
  launchctl bootout "gui/$(id -u)/$PLIST_LABEL" 2>/dev/null || true
  # teardown.sh disables the label so login does not reload it; undo that.
  launchctl enable "gui/$(id -u)/$PLIST_LABEL" 2>/dev/null || true
  launchctl bootstrap "gui/$(id -u)" "$PLIST"
  ok "LaunchAgent loaded (logs: ~/Library/Logs/deployd.log)"
fi

# ------------------------------------------------------------ first tick
# A first poll now proves the wiring (checkout pull, manifest scan, state
# writes) without waiting a cycle. A deploy that fails here warns, not dies:
# setup itself succeeded.
info "Running the first poll"
if "$BIN_DIR/deployd"; then
  ok "First poll clean"
else
  warn "First poll reported failures — see above and ~/services/deployd/state/*.log"
fi

echo
printf '\033[1;32mDone.\033[0m deployd polls %s every %ss.\n' "$SETUP_REPO" "$POLL_SECONDS"
echo
echo "A service opts in via its app.json deploy block:"
echo '  "deploy": { "repo": "<git url>", "ref": "main",'
echo '              "cmd": "services/<name>/setup.sh" }'
echo
echo "Manage:"
echo "  $BIN_DIR/deployd --status           # entries, deployed shas, failures"
echo "  $BIN_DIR/deployd --force <service>  # deploy one now"
if [ "$OS" = "Linux" ]; then
  echo "  systemctl --user list-timers deployd.timer"
  echo "  journalctl --user -u deployd -n 50   # poll + deploy logs"
else
  echo "  tail -f ~/Library/Logs/deployd.log"
fi
