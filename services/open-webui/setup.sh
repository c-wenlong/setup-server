#!/usr/bin/env bash
#
# setup.sh — one-shot deploy of Open WebUI (chat UI over local ollama)
# behind Tailscale. Linux + macOS.
#
# End state:
#   - Open WebUI container (host network, binds 127.0.0.1:LOCAL_PORT only)
#   - talks to the host's ollama at OLLAMA_BASE_URL
#   - published tailnet-only at https://<host>.<tailnet>.ts.net:HTTPS_PORT
#   - the owner account seeded from WEBUI_ADMIN_* in .env over the API and
#     open signup off — no "first tailnet visitor becomes admin" window
#   - boot-persistent via Docker's restart policy (no systemd/launchd needed)
#
# Usage:
#   ./setup.sh                                  # local 3001, HTTPS 3001
#   LOCAL_PORT=3005 ./setup.sh                  # HTTPS follows LOCAL_PORT
#   LOCAL_PORT=3005 HTTPS_PORT=8443 ./setup.sh
#
# Version: pinned to 0.13.2, not `:main` — the signup-closes-on-first-account
# behaviour this script relies on is a release-line feature, and a floating
# tag makes a re-run's behaviour a lottery.
#
# Requirements: Linux or macOS, curl, Docker + Compose v2, Tailscale logged
# in, and ollama running on the host (https://ollama.com).
#
# Idempotent: safe to re-run; existing .env is never overwritten (new keys
# introduced later are appended, never edited in place).

set -euo pipefail

LOCAL_PORT="${LOCAL_PORT:-3001}"
# HTTPS follows the local port unless set explicitly (the n8n
# convention), so overriding only LOCAL_PORT cannot split the
# two. Until 2026-09-13 this defaulted to a literal 10000, chosen back when
# Tailscale Serve only allowed 443/8443/10000; that limit is long gone.
# This script never executes .env, so there is no read-back to guard.
HTTPS_PORT="${HTTPS_PORT:-$LOCAL_PORT}"
OLLAMA_BASE_URL="${OLLAMA_BASE_URL:-http://127.0.0.1:11434}"
SERVICE_DIR="$(cd "$(dirname "$0")" && pwd)"
ENV_FILE="$SERVICE_DIR/.env"

# shellcheck source=../../lib/common.sh
. "$SERVICE_DIR/../../lib/common.sh"

# 32 hex chars: [A-Za-z0-9]-safe, so it survives .env, shell quoting, a JSON
# body and a login form without escaping.
randhex() {
  if command -v python3 >/dev/null 2>&1; then
    python3 -c 'import secrets; print(secrets.token_hex(16))'
  else
    od -An -tx1 -N16 /dev/urandom | tr -d ' \n'
    echo
  fi
}

# One `KEY=value` line from .env, the way it is written here: unquoted,
# no shell execution. Last match wins, like Compose.
env_get() {
  local file="$1" key="$2"
  [ -f "$file" ] || return 0
  sed -n "s/^${key}=//p" "$file" | tail -1
}

# ---------------------------------------------------------------- preflight
detect_os
info "Preflight checks ($OS)"
refuse_root
command -v curl >/dev/null || die "curl is required."
resolve_tailscale
require_docker_compose
require_tailscale_up
require_numeric HTTPS_PORT

# macOS note: with Docker Desktop, "host" networking + loopback ollama needs
# Docker Desktop >= 4.34 host networking support; verify after deploy.
if curl -fsS -o /dev/null --max-time 3 "$OLLAMA_BASE_URL/api/version" 2>/dev/null; then
  ok "ollama reachable at $OLLAMA_BASE_URL"
else
  warn "ollama not reachable at $OLLAMA_BASE_URL — the UI will start but have no models. Install/start ollama, or set OLLAMA_BASE_URL."
fi
ok "$OS + curl + Docker (daemon reachable) + Compose v2 + Tailscale (running)"

host="$(tailnet_host)"
[ -n "$host" ] || die "Could not determine tailnet DNS name (is MagicDNS enabled?)"

# ---------------------------------------------------------------- .env
if [ -f "$ENV_FILE" ]; then
  chmod 600 "$ENV_FILE" 2>/dev/null || true
  ok "Config already exists, leaving untouched: $ENV_FILE"
else
  info "Writing .env"
  (
    umask 077
    cat > "$ENV_FILE" <<EOF
# Generated by setup.sh. Gitignored; mode 600.

# Pinned exactly. Do not float \`main\` — it moves every day, and this
# deploy relies on release behaviour (first account closes signup).
# Bump the tag, then re-run ./setup.sh to upgrade.
WEBUI_IMAGE=ghcr.io/open-webui/open-webui:0.13.2
WEBUI_VOLUME=$HOME/services/open-webui/data
LOCAL_PORT=$LOCAL_PORT
OLLAMA_BASE_URL=$OLLAMA_BASE_URL

# Passed to the container. Open signup is off from the first boot; the
# first account created is still allowed (and becomes admin), which is
# how the owner below is seeded. To open signups for other tailnet
# users later, flip this in .env and re-run.
ENABLE_SIGNUP=false

# Owner account, created over the API on first deploy. First account is
# the admin — seeding it here is what keeps a random tailnet peer from
# grabbing the role. Change the password in the UI afterwards (Settings
# -> Account); this file is not updated.
WEBUI_ADMIN_EMAIL=admin@$host
WEBUI_ADMIN_PASSWORD=$(randhex)
EOF
  )
  chmod 600 "$ENV_FILE"
  ok "Wrote $ENV_FILE"
fi

mkdir -p "$HOME/services/open-webui/data"

# ---------------------------------------------------------------- deploy
info "Starting container (docker compose up -d) — first run pulls the image"
docker compose --project-directory "$SERVICE_DIR" up -d

info "Waiting for Open WebUI on 127.0.0.1:$LOCAL_PORT"
wait_http "http://127.0.0.1:$LOCAL_PORT/health" 60 3 || die "Open WebUI did not come up. Logs: docker compose --project-directory $SERVICE_DIR logs open-webui"
ok "Open WebUI is answering locally"

# ------------------------------------------------- owner account + signup
# "First account becomes admin" with open signup is a race every tailnet
# peer wins by loading the URL first. ENABLE_SIGNUP=false in the container
# env closes /signup to everyone — the FIRST signup is exempt (that is the
# seeding path), and on the pinned image a completed first signup also
# records enable_signup=false in the app's own config store, so it stays
# closed across restarts and config resets.
#
# /api/config answers unauthenticated and reports `"onboarding": true`
# while no user exists, plus `features.enable_signup` for the live flag.
webui_config() {
  curl -fsS --max-time 15 "http://127.0.0.1:$LOCAL_PORT/api/config" 2>/dev/null || true
}
json_true() { printf '%s' "$1" | grep -q "\"$2\" *: *true"; }

ADMIN_EMAIL="$(env_get "$ENV_FILE" WEBUI_ADMIN_EMAIL)"
ADMIN_PASSWORD="$(env_get "$ENV_FILE" WEBUI_ADMIN_PASSWORD)"

cfg="$(webui_config)"
[ -n "$cfg" ] \
  || die "Could not read http://127.0.0.1:$LOCAL_PORT/api/config after /health succeeded — refusing to publish before confirming the owner account and signup state. Logs: docker compose --project-directory $SERVICE_DIR logs open-webui"
if json_true "$cfg" onboarding; then
  # No users at all. An .env written before WEBUI_ADMIN_* existed (or a
  # wiped data dir) gets the keys appended; a fresh one already has them.
  if [ -z "$ADMIN_EMAIL" ] || [ -z "$ADMIN_PASSWORD" ]; then
    ADMIN_EMAIL="admin@$host"
    ADMIN_PASSWORD="$(randhex)"
    (
      umask 077
      printf '\n# Owner account, appended by a later setup.sh — see a fresh .env\n# for the full comment. First account is the admin.\nWEBUI_ADMIN_EMAIL=%s\nWEBUI_ADMIN_PASSWORD=%s\n' \
        "$ADMIN_EMAIL" "$ADMIN_PASSWORD" >> "$ENV_FILE"
    )
    chmod 600 "$ENV_FILE" 2>/dev/null || true
    info "Appended owner credentials to $ENV_FILE"
  fi
  info "Creating the owner account over the API ($ADMIN_EMAIL)"
  # Pass credentials on stdin (--data-binary @-) so WEBUI_ADMIN_PASSWORD
  # never appears in curl's command-line argv.
  esc_email="${ADMIN_EMAIL//\\/\\\\}"; esc_email="${esc_email//\"/\\\"}"
  esc_pw="${ADMIN_PASSWORD//\\/\\\\}"; esc_pw="${esc_pw//\"/\\\"}"
  code="$(printf '{"name":"Admin","email":"%s","password":"%s"}' "$esc_email" "$esc_pw" \
    | curl -sS -o /dev/null -w '%{http_code}' --max-time 30 -X POST \
        -H 'Content-Type: application/json' \
        --data-binary @- \
        "http://127.0.0.1:$LOCAL_PORT/api/v1/auths/signup" 2>/dev/null || echo 000)"
  [ "$code" = "200" ] \
    || die "Could not create the owner account (HTTP $code): the instance has no users and nobody can sign in. Create the admin account through the UI at http://127.0.0.1:$LOCAL_PORT on this box, then re-run. Logs: docker compose --project-directory $SERVICE_DIR logs open-webui"
  ok "Owner account created: $ADMIN_EMAIL (password: WEBUI_ADMIN_PASSWORD in $ENV_FILE)"
  cfg="$(webui_config)"
fi

# Assert the door is actually closed before publishing. A re-run on an
# install where signups were re-enabled (or a config reset) still warns —
# deliberately re-enabling is the owner's call, not something to undo.
if printf '%s' "$cfg" | grep -q '"enable_signup" *: *false'; then
  ok "Open signup is off"
elif printf '%s' "$cfg" | grep -q '"enable_signup"'; then
  warn "Open WebUI still accepts open signups — any tailnet peer can register an account. Disable it in the UI: admin login -> Admin Panel -> Settings -> 'Enable New Sign Ups'."
else
  warn "Could not confirm the signup setting at http://127.0.0.1:$LOCAL_PORT/api/config — check 'Enable New Sign Ups' is off in the Admin Panel."
fi

# ------------------------------------------------------- tailscale serve
info "Publishing via Tailscale Serve (HTTPS :$HTTPS_PORT, tailnet only)"
ts_serve_publish "$HTTPS_PORT" "http://127.0.0.1:$LOCAL_PORT"

# One-time repair for boxes deployed before 2026-09-13, when this service was
# published on :10000. Serve keeps every mapping it has ever been given, so
# without this a re-run would simply add :$HTTPS_PORT and leave the old port
# published alongside it: two URLs for one service, and the retired one still
# answering. Only withdrawn when it actually points at this service, so a
# :10000 belonging to something else is never touched.
LEGACY_HTTPS_PORT=10000
if [ "$HTTPS_PORT" != "$LEGACY_HTTPS_PORT" ] \
   && "$TAILSCALE" serve status 2>/dev/null \
      | grep -A2 ":$LEGACY_HTTPS_PORT " \
      | grep -q "proxy http://127.0.0.1:$LOCAL_PORT$"; then
  info "Withdrawing the legacy :$LEGACY_HTTPS_PORT mapping (this service moved to :$HTTPS_PORT)"
  if "$TAILSCALE" serve --https="$LEGACY_HTTPS_PORT" off >/dev/null 2>&1; then
    ok "Legacy :$LEGACY_HTTPS_PORT mapping withdrawn"
  else
    warn "Could not withdraw the legacy :$LEGACY_HTTPS_PORT mapping. Remove it by hand: tailscale serve --https=$LEGACY_HTTPS_PORT off"
  fi
fi

# ------------------------------------------------------------ final check
url="https://$host:$HTTPS_PORT"
info "Verifying $url (first request can take ~60s while the TLS cert is minted)"
if curl -fsS -o /dev/null --max-time 90 "$url/health"; then
  ok "End-to-end check passed"
else
  echo "    Cert may still be minting — try again in a minute: curl $url/health"
fi

echo
printf '\033[1;32mDone.\033[0m Open WebUI is at \033[1m%s\033[0m (tailnet only).\n' "$url"
echo
if [ -n "$ADMIN_EMAIL" ]; then
  echo "  Login:    $ADMIN_EMAIL"
  echo "  Password: WEBUI_ADMIN_PASSWORD in $ENV_FILE"
else
  echo "  Login:    the admin account this instance already had"
fi
echo "  Signups are off; invite more users from the Admin Panel if needed."
echo
echo "Manage: docker compose --project-directory $SERVICE_DIR ps|logs|restart|down"
echo "Upgrade: docker compose --project-directory $SERVICE_DIR pull && docker compose --project-directory $SERVICE_DIR up -d"
