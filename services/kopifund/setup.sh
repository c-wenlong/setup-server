#!/usr/bin/env bash
#
# setup.sh — one-shot deploy of Kopifund (the private lagom-studio/kopifund-finance
# repo) behind Tailscale. Linux + macOS.
#
# End state:
#   - a machine-managed clone of kopifund-finance at ~/services/kopifund/repo
#     (hard-reset per deploy — a working clone belongs in ~/dev)
#   - a `kopifund` container built from that clone's own Dockerfile,
#     published on 127.0.0.1:LOCAL_PORT only
#   - the data folder at ~/.kopifund — upstream's own data root — as an
#     unlocked git-crypt clone of the private c-wenlong/kopifund-hub repo,
#     which is how state is versioned and shared with the Mac
#   - a user-level sync timer (systemd --user timer / launchd agent) that
#     snapshots ~/.kopifund to kopifund-hub and merges the other machines'
#     snapshots back, every SYNC_SECONDS
#   - a user-level analyse timer that rebuilds the per-machine stats cache
#     (~/.kopifund/cache, gitignored) every ANALYSE_SECONDS — a pulled
#     ledger is no in-app write, so nothing else refreshes the dashboard
#   - reachable tailnet-only at https://<host>.<tailnet>.ts.net:HTTPS_PORT
#
# Usage:
#   ./setup.sh                      # local 8300, HTTPS 8300
#   LOCAL_PORT=8400 ./setup.sh      # HTTPS follows LOCAL_PORT
#
# Requirements beyond the repo baseline (curl, Tailscale): git with
# non-interactive access to BOTH private repos (gh auth setup-git, or an SSH
# deploy key + REPO_URL/HUB_URL set to ssh form), git-crypt, and Docker.
# On a fresh machine the hub key must be in place BEFORE the data folder is
# provisioned: scp ~/.config/kopifund/gitcrypt.key from a machine that
# already unlocks kopifund-hub (see SETUP.md).
#
# Idempotent: safe to re-run; it fast-forwards the repo clone, rebuilds the
# image, repairs the publish and never rewrites .env or the data folder.

set -euo pipefail

LOCAL_PORT="${LOCAL_PORT:-8300}"
# The HTTPS port follows the local port unless set explicitly (the forgejo
# convention), so overriding only LOCAL_PORT cannot split the two.
HTTPS_PORT_EXPLICIT="${HTTPS_PORT:+yes}"
HTTPS_PORT="${HTTPS_PORT:-$LOCAL_PORT}"
REPO_URL="${KOPIFUND_REPO_URL:-https://github.com/lagom-studio/kopifund-finance.git}"
HUB_URL="${KOPIFUND_HUB_URL:-https://github.com/c-wenlong/kopifund-hub.git}"
REF="${KOPIFUND_REF:-main}"
CONTAINER="kopifund"
LEGACY_CONTAINER="app-kopifund-finance"

SERVICE_DIR="$(cd "$(dirname "$0")" && pwd)"
ENV_FILE="$SERVICE_DIR/.env"
STATE="${SERVICE_HOME:-$HOME/services/kopifund}"
REPO_DIR="$STATE/repo"
KEY_FILE="${GITCRYPT_KEY:-$HOME/.config/kopifund/gitcrypt.key}"
LEGACY_DATA="$HOME/services/apps/kopifund-finance/data"

# shellcheck source=../../lib/common.sh
. "$SERVICE_DIR/../../lib/common.sh"

# ---------------------------------------------------------------- preflight
detect_os
info "Preflight checks ($OS)"
refuse_root
command -v curl >/dev/null || die "curl is required."
command -v git >/dev/null || die "git is required."
command -v git-crypt >/dev/null || {
  [ "$OS" = "Linux" ] && die "git-crypt is required: sudo apt-get install -y git-crypt (0.7+), then re-run."
  die "git-crypt is required: brew install git-crypt, then re-run."
}
resolve_tailscale
require_docker_compose
require_tailscale_up
require_numeric LOCAL_PORT HTTPS_PORT

# An existing .env overrides the defaults above, including the repo URLs —
# source it BEFORE the access check so a saved SSH URL is what ls-remote
# probes, not the https default a first install would have used.
if [ -f "$ENV_FILE" ]; then
  ok "Config already exists, leaving untouched: $ENV_FILE"
  REQUESTED_PORT="$LOCAL_PORT"
  REQUESTED_HTTPS="$HTTPS_PORT"
  env_lint "$ENV_FILE"
  set -a; . "$ENV_FILE"; set +a
fi

# deployd and this script touch the private repos unattended — verify auth now.
for repo in "$REPO_URL" "$HUB_URL"; do
  GIT_TERMINAL_PROMPT=0 git ls-remote --heads "$repo" >/dev/null 2>&1 \
    || die "Cannot read $repo non-interactively. Fix auth first: gh auth login && gh auth setup-git (or use an SSH deploy key and set the *_URL variables to ssh form)."
done

ok "$OS + curl + git + git-crypt + Docker + Compose v2 + Tailscale (running)"

TS_HOST="$(tailnet_host)"
[ -n "$TS_HOST" ] || die "Could not determine tailnet DNS name (is MagicDNS enabled?)"
ok "Tailnet name: $TS_HOST"

# ---------------------------------------------------------------- .env
# An existing .env was already sourced above (the repo access check needs
# its saved URLs). A fresh install writes it now, then takes the same path.
if [ ! -f "$ENV_FILE" ]; then
  info "Writing .env (ports, paths, repo URLs — mode 600)"
  tz="Etc/UTC"
  if [ -L /etc/localtime ]; then
    tz="$(readlink /etc/localtime | sed 's#.*/zoneinfo/##')"
  elif [ "$OS" = "Darwin" ]; then
    tz="$(readlink /etc/localtime 2>/dev/null | sed 's#.*/zoneinfo/##' || true)"
    tz="${tz:-Etc/UTC}"
  fi
  cat > "$ENV_FILE" <<EOF
# Generated by setup.sh. Gitignored; mode 600. Edit + re-run to apply.
# The app source: a private repo, machine-managed clone below.
REPO_URL=$REPO_URL
KOPIFUND_REF=$REF
REPO_DIR=$REPO_DIR

# The data folder's versioned remote. git-crypt encrypts everything on
# push except its own meta files; see c-wenlong/kopifund-hub's README.
HUB_URL=$HUB_URL

LOCAL_PORT=$LOCAL_PORT
HTTPS_PORT=$HTTPS_PORT
TZ=$tz

SERVICE_HOME=$STATE
# The data root upstream itself uses (~/.kopifund or KOPIFUND_DATA). It is a
# git-crypt clone of HUB_URL, kept OUTSIDE ~/services on purpose: the Mac
# syncs the same path and teardown --purge must never touch it.
KOPIFUND_DATA=$HOME/.kopifund

# What the app tells paired phones its tailnet address is (SPEC, "Phone
# link"): a container holds no tailscale to ask, so both come from .env.
KOPIFUND_HOSTS=$TS_HOST
KOPIFUND_TAILNET_URL=https://$TS_HOST:$HTTPS_PORT

# Seconds between sync snapshots of the data folder.
SYNC_SECONDS=300

# Seconds between stats rebuilds into the data folder's cache — the app
# reads cache/results, which is gitignored per machine, so a sync that
# lands a newer ledger never refreshes the pages by itself.
ANALYSE_SECONDS=86400
EOF
  chmod 600 "$ENV_FILE"
  ok "Wrote $ENV_FILE"
  REQUESTED_PORT="$LOCAL_PORT"
  REQUESTED_HTTPS="$HTTPS_PORT"
  env_lint "$ENV_FILE"
  set -a; . "$ENV_FILE"; set +a
fi

# Validation — one path whether .env was just written or loaded above. An
# existing .env is the source of truth for ports, paths and repos, so a
# re-run can never silently move a live deployment.
REPO_URL="${REPO_URL:?REPO_URL missing from $ENV_FILE}"
HUB_URL="${HUB_URL:?HUB_URL missing from $ENV_FILE}"
REF="${KOPIFUND_REF:-main}"
SERVICE_HOME="${SERVICE_HOME:?SERVICE_HOME missing from $ENV_FILE}"
REPO_DIR="${REPO_DIR:-$SERVICE_HOME/repo}"
DATA_DIR="${KOPIFUND_DATA:?KOPIFUND_DATA missing from $ENV_FILE}"
KOPIFUND_HOSTS="${KOPIFUND_HOSTS:?KOPIFUND_HOSTS missing from $ENV_FILE}"
TAILNET_URL="${KOPIFUND_TAILNET_URL:?KOPIFUND_TAILNET_URL missing from $ENV_FILE}"
SYNC_SECONDS="${SYNC_SECONDS:-300}"
ANALYSE_SECONDS="${ANALYSE_SECONDS:-86400}"
STATE="$SERVICE_HOME"
case "$SYNC_SECONDS" in ''|*[!0-9]*) die "SYNC_SECONDS must be numeric (got: $SYNC_SECONDS)";; esac
case "$ANALYSE_SECONDS" in ''|*[!0-9]*) die "ANALYSE_SECONDS must be numeric (got: $ANALYSE_SECONDS)";; esac
if [ "$LOCAL_PORT" != "$REQUESTED_PORT" ]; then
  warn "LOCAL_PORT=$REQUESTED_PORT ignored — the existing $ENV_FILE says $LOCAL_PORT. Edit .env and re-run to move the port."
fi
if [ -n "$HTTPS_PORT_EXPLICIT" ] && [ "$HTTPS_PORT" != "$REQUESTED_HTTPS" ]; then
  warn "HTTPS_PORT=$REQUESTED_HTTPS ignored — the existing $ENV_FILE says $HTTPS_PORT. Edit .env and re-run to move the port."
fi

# Drift check, not a rewrite: .env is the user's file. A tailnet name that
# moved means the phone-link URL it advertises is stale — say so loudly.
WANT_URL="https://$TS_HOST:$HTTPS_PORT"
if [ "$TAILNET_URL" != "$WANT_URL" ]; then
  warn "KOPIFUND_TAILNET_URL in .env is $TAILNET_URL but this box now answers to $WANT_URL."
  warn "  The pair QR a phone scans would carry a dead address. Fix: set KOPIFUND_HOSTS=$TS_HOST and KOPIFUND_TAILNET_URL=$WANT_URL in $ENV_FILE, then re-run."
fi

mkdir -p "$STATE/bin" "$STATE/state"

# A manual ./setup.sh re-installs the service: clear deployd's disabled
# flag (written by teardown.sh) so auto-deploy resumes. deployd itself
# never invokes this while the flag is set, so clearing is always manual.
DEPLOYD_HOME="$HOME/services/deployd"
if [ -f "$SERVICE_DIR/../deployd/.env" ]; then
  d="$(sed -n "s/^SERVICE_HOME=\(.*\)\$/\1/p" "$SERVICE_DIR/../deployd/.env" \
       | tail -1 | sed "s/^'//; s/'\$//; s/^\"//; s/\"\$//")"
  case "$d" in \~/*) d="$HOME/${d#\~/}" ;; \$HOME/*) d="$HOME/${d#\$HOME/}" ;; esac
  [ -n "$d" ] && DEPLOYD_HOME="$d"
fi
rm -f "$DEPLOYD_HOME/state/kopifund.disabled"

# ------------------------------------------------------------- repo clone
# Machine-managed checkout of the app source. Hard-reset per run: nobody
# works here, deployd drives it unattended, and a drifted clone would
# silently pin the deployed version.
info "Updating source clone ($REPO_URL @ $REF) -> $REPO_DIR"
if [ -d "$REPO_DIR/.git" ]; then
  git -C "$REPO_DIR" fetch -q origin || die "git fetch failed in $REPO_DIR"
  if ! git -C "$REPO_DIR" diff --quiet || ! git -C "$REPO_DIR" diff --cached --quiet; then
    warn "$REPO_DIR has uncommitted changes — resetting (this clone is machine-managed)."
  fi
  git -C "$REPO_DIR" checkout -q "$REF" 2>/dev/null || true
  git -C "$REPO_DIR" reset -q --hard "origin/$REF" \
    || die "origin/$REF not found in $REPO_DIR after fetch — wrong KOPIFUND_REF?"
else
  mkdir -p "$(dirname "$REPO_DIR")"
  git clone -q "$REPO_URL" "$REPO_DIR" || die "git clone of $REPO_URL failed"
  git -C "$REPO_DIR" checkout -q "$REF" || die "ref $REF not found in $REPO_URL"
fi
ok "Source at $(git -C "$REPO_DIR" rev-parse --short HEAD)"

[ -f "$REPO_DIR/Dockerfile" ] || die "$REPO_DIR has no Dockerfile — upstream layout changed?"

# ------------------------------------------------------------- data folder
# ~/.kopifund is a git-crypt clone of kopifund-hub: versioning AND the
# sync transport in one. Three states handled: absent (clone + unlock),
# unlocked clone (kept, ff-pulled when clean), locked clone (unlock when
# the key is here). A non-clone ~/.kopifund is never converted in place —
# too easy to bury an existing folder under a checkout.
is_locked_clone() {
  local f
  for f in "$DATA_DIR/config.toml" "$DATA_DIR/profile.json" "$DATA_DIR/kopifund.db"; do
    [ -f "$f" ] || continue
    # git-crypt ciphertext starts with the 9-byte magic \0GITCRYPT.
    [ "$(od -An -c -N9 "$f" | tr -d ' ')" = '\0GITCRYPT' ] && return 0
  done
  return 1
}

unlock_data() {
  [ -f "$KEY_FILE" ] || die "The data clone is sealed and $KEY_FILE is missing.
  Copy the git-crypt key from a machine that unlocks kopifund-hub:
    scp <mac>:~/.config/kopifund/gitcrypt.key $KEY_FILE && chmod 600 $KEY_FILE
  (see c-wenlong/kopifund-hub README, 'Bootstrap a new device')."
  (cd "$DATA_DIR" && git-crypt unlock "$KEY_FILE") \
    || die "git-crypt unlock failed — wrong key file? $KEY_FILE"
  ok "Data folder unlocked (git-crypt)"
}

info "Provisioning data folder: $DATA_DIR"
if [ ! -e "$DATA_DIR" ]; then
  [ -f "$KEY_FILE" ] || die "$DATA_DIR does not exist and the git-crypt key is missing.
  Put the hub key at $KEY_FILE first (mode 600), then re-run:
    scp <mac>:~/.config/kopifund/gitcrypt.key $KEY_FILE"
  git clone -q "$HUB_URL" "$DATA_DIR" || die "git clone of $HUB_URL failed"
  unlock_data
elif [ -d "$DATA_DIR/.git" ]; then
  if is_locked_clone; then
    info "Data clone is sealed — unlocking"
    unlock_data
  else
    ok "Data folder already present and unlocked"
  fi
  case "$(git -C "$DATA_DIR" remote get-url origin 2>/dev/null || true)" in
    *kopifund-hub*) ;;
    *) warn "origin of $DATA_DIR is not kopifund-hub — sync will push to the wrong remote until fixed." ;;
  esac
  # Cheap freshness: fast-forward only when the worktree is clean; anything
  # else is the sync timer's job (it commits first, then merges).
  if git -C "$DATA_DIR" diff --quiet && git -C "$DATA_DIR" diff --cached --quiet; then
    git -C "$DATA_DIR" pull -q --ff-only 2>/dev/null \
      || warn "$DATA_DIR could not fast-forward — left to the sync timer."
  fi
else
  die "$DATA_DIR exists but is not a kopifund-hub clone. Reconcile by hand (SETUP.md, 'Data folder'), then re-run — this script never converts a populated folder in place."
fi

# -------------------------------------- retiring the launcher app's writer
# The launcher's From-GitHub app (app-kopifund-finance) held :LOCAL_PORT
# before this service existed and is the old writer of the legacy data.
# Stop it BEFORE the adoption copy: an in-flight save landing after the
# copy would be stranded in the old folder forever, and a write mid-copy
# could hand the clone a torn database. Stopping it here also frees the
# port for the compose project below. Removing its tile stays a manual
# launcher action (the note at the end explains why order matters).
if docker ps --format '{{.Names}}' 2>/dev/null | grep -qx "$LEGACY_CONTAINER"; then
  info "Stopping the launcher app's container ($LEGACY_CONTAINER) — superseded by this service"
  docker stop "$LEGACY_CONTAINER" >/dev/null
fi

# ------------------------------------------------- adopt launcher app data
# The launcher's app kept its data at
# ~/services/apps/kopifund-finance/data. One-time merge INTO the data
# clone, only while that legacy dir exists — and the two halves of it get
# different treatment:
#
#   FILES merge without clobbering (cp -n): the launcher's folder can
#   hold things the clone lacks (statements that never reached the Mac),
#   but wherever both have a file the clone's copy stays. Its config and
#   device registry come from the newer lineage — the old app's
#   config.toml/devices.json were real downgrades in practice.
#
#   kopifund.db copies over the clone's only when it is measurably
#   richer. The honest test is the ledger itself (the txn row count),
#   not time: a fresh clone stamps every file at checkout, and a live
#   app's db looks newest whenever the app was last open — the launcher
#   app's empty record once won that race against the clone's thousands
#   of transactions. When a side cannot be counted (not a kopifund db,
#   still sealed, no python3), fall back to snapshot age — the clone's
#   last kopifund.db commit vs the legacy file's mtime, never the
#   clone's checkout time.
#
# Marked done so a re-run never re-copies.
mtime_of() { stat -c %Y "$1" 2>/dev/null || stat -f %m "$1" 2>/dev/null || echo 0; }

# The ledger's transaction count, or nothing when the file cannot be read
# as a kopifund record.
txn_count() {
  command -v python3 >/dev/null 2>&1 || return 1
  python3 - "$1" <<'PY' 2>/dev/null
import sqlite3, sys
from urllib.parse import quote
try:
    db = sqlite3.connect("file:%s?mode=ro" % quote(sys.argv[1]), uri=True)
    print(db.execute("SELECT count(*) FROM txn").fetchone()[0])
    db.close()
except Exception:
    sys.exit(1)
PY
}

ADOPT_MARKER="$STATE/state/legacy-adopted"
if [ -d "$LEGACY_DATA" ] && [ ! -f "$ADOPT_MARKER" ]; then
  hub_db="$DATA_DIR/kopifund.db"; leg_db="$LEGACY_DATA/kopifund.db"
  overwrite_db=0; db_why=""
  if [ -f "$hub_db" ] && [ -f "$leg_db" ]; then
    hub_n="$(txn_count "$hub_db" || true)"; leg_n="$(txn_count "$leg_db" || true)"
    if [ -n "$hub_n" ] && [ -n "$leg_n" ]; then
      if [ "$leg_n" -gt "$hub_n" ]; then
        overwrite_db=1; db_why="$leg_n transactions vs the clone's $hub_n"
      fi
    else
      hub_ts="$(git -C "$DATA_DIR" log -1 --format=%ct -- kopifund.db 2>/dev/null || true)"
      hub_ts="${hub_ts:-0}"
      leg_ts="$(mtime_of "$leg_db")"
      if [ "$leg_ts" -gt "$hub_ts" ]; then
        overwrite_db=1; db_why="newer than the clone's last ledger snapshot"
      fi
    fi
  fi
  info "Adopting launcher app data: merging $LEGACY_DATA into $DATA_DIR (files the clone lacks only)"
  had_db=0; had_wal=0; had_shm=0; had_journal=0
  [ -f "$hub_db" ] && had_db=1
  [ -f "$hub_db"-wal ] && had_wal=1
  [ -f "$hub_db"-shm ] && had_shm=1
  [ -f "$hub_db"-journal ] && had_journal=1
  cp -an "$LEGACY_DATA/." "$DATA_DIR/"
  if [ "$overwrite_db" -eq 1 ]; then
    cp -a "$leg_db" "$hub_db"
    # sqlite sidecars travel with their db or not at all — a -wal that
    # belongs to the OTHER file must never replay against this one.
    for ext in -wal -shm -journal; do
      if [ -f "$leg_db$ext" ]; then cp -a "$leg_db$ext" "$hub_db$ext"; else rm -f "$hub_db$ext"; fi
    done
    ok "Adopted the launcher's ledger over the clone's ($db_why)"
  elif [ "$had_db" -eq 1 ]; then
    # The clone's ledger won: gap-fill may have dragged the launcher's
    # sidecars in beside it, and a -wal belonging to the OTHER db must
    # never replay against this one. Only sidecars that were not already
    # there go; the worktree's own hold the app's real unflushed rows.
    [ "$had_wal" -eq 0 ] && rm -f "$hub_db"-wal
    [ "$had_shm" -eq 0 ] && rm -f "$hub_db"-shm
    [ "$had_journal" -eq 0 ] && rm -f "$hub_db"-journal
    [ -f "$leg_db" ] \
      && warn "Kept the clone's ledger — the launcher's is not richer. If that was wrong its copy is still at $leg_db — reconcile by hand, then remove $LEGACY_DATA."
  elif [ -f "$hub_db" ]; then
    # No clone db existed — the ledger itself just gap-filled, and its
    # sidecars (adopted rows still in -wal) must come with it.
    ok "Adopted the launcher's ledger — the clone had none"
  fi
  touch "$ADOPT_MARKER"
  ok "Legacy data merged into $DATA_DIR (lands in the next sync snapshot)"
fi

# ------------------------------------------------- sync+analyse scripts
info "Installing sync + analyse scripts -> $STATE/bin"
sed -e "s|__ENV_FILE__|$ENV_FILE|" \
  "$SERVICE_DIR/sync.sh" > "$STATE/bin/sync.sh"
# analyse.sh gets docker's resolved path too — its timer runs under
# launchd/systemd with a bare PATH, where a docker CLI living somewhere
# else (Docker Desktop on the Mac) would silently never be found.
DOCKER_BIN="$(command -v docker)"
sed -e "s|__ENV_FILE__|$ENV_FILE|" -e "s|__DOCKER__|$DOCKER_BIN|" \
  "$SERVICE_DIR/analyse.sh" > "$STATE/bin/analyse.sh"
chmod +x "$STATE/bin/sync.sh" "$STATE/bin/analyse.sh"
# The clone may carry no identity (deployd boxes, fresh VMs); the timer's
# snapshot commits need one and must not fall back to a guess.
git -C "$DATA_DIR" config user.name >/dev/null 2>&1 \
  || git -C "$DATA_DIR" config user.name "kopifund-sync"
git -C "$DATA_DIR" config user.email >/dev/null 2>&1 \
  || git -C "$DATA_DIR" config user.email "kopifund-sync@$TS_HOST"
ok "Scripts installed"

if [ "$OS" = "Linux" ]; then
  info "Writing systemd user timers (sync every ${SYNC_SECONDS}s, analyse every ${ANALYSE_SECONDS}s)"
  UNIT_DIR="$HOME/.config/systemd/user"
  mkdir -p "$UNIT_DIR"
  cat > "$UNIT_DIR/kopifund-sync.service" <<EOF
# Generated by services/kopifund/setup.sh — regenerated on every re-run.
[Unit]
Description=kopifund data sync (snapshot ~/.kopifund to kopifund-hub)

[Service]
Type=oneshot
ExecStart=$STATE/bin/sync.sh
EOF
  chmod 600 "$UNIT_DIR/kopifund-sync.service"   # names .env-derived paths
  cat > "$UNIT_DIR/kopifund-sync.timer" <<EOF
# Generated by services/kopifund/setup.sh — regenerated on every re-run.
[Unit]
Description=kopifund data sync every ${SYNC_SECONDS}s

[Timer]
OnBootSec=60
OnUnitActiveSec=${SYNC_SECONDS}s
Persistent=true

[Install]
WantedBy=timers.target
EOF
  cat > "$UNIT_DIR/kopifund-analyse.service" <<EOF
# Generated by services/kopifund/setup.sh — regenerated on every re-run.
[Unit]
Description=kopifund stats rebuild (analyse into ~/.kopifund/cache)

[Service]
Type=oneshot
ExecStart=$STATE/bin/analyse.sh
EOF
  chmod 600 "$UNIT_DIR/kopifund-analyse.service"   # names .env-derived paths
  cat > "$UNIT_DIR/kopifund-analyse.timer" <<EOF
# Generated by services/kopifund/setup.sh — regenerated on every re-run.
[Unit]
Description=kopifund stats rebuild every ${ANALYSE_SECONDS}s

[Timer]
OnBootSec=300
OnUnitActiveSec=${ANALYSE_SECONDS}s
Persistent=true

[Install]
WantedBy=timers.target
EOF
  systemctl --user daemon-reload
  systemctl --user enable --now kopifund-sync.timer
  systemctl --user enable --now kopifund-analyse.timer
  # The timer must outlive logouts (the box may sit at a login screen for
  # days): lingering on, at most one sudo on first deploy.
  if ! loginctl show-user "$USER" -p Linger 2>/dev/null | grep -q 'Linger=yes'; then
    info "Enabling lingering for $USER so the sync timer runs logged out (needs sudo, one time)"
    sudo loginctl enable-linger "$USER"
  fi
  ok "Timers enabled: systemctl --user status kopifund-sync.timer / kopifund-analyse.timer"
else
  info "Writing LaunchAgents (sync every ${SYNC_SECONDS}s, analyse every ${ANALYSE_SECONDS}s)"
  mkdir -p "$HOME/Library/LaunchAgents" "$HOME/Library/Logs"
  cat > "$HOME/Library/LaunchAgents/com.kopifund.sync.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by services/kopifund/setup.sh — regenerated on every re-run. -->
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>com.kopifund.sync</string>
  <key>ProgramArguments</key>
  <array>
    <string>$STATE/bin/sync.sh</string>
  </array>
  <key>StartInterval</key><integer>$SYNC_SECONDS</integer>
  <key>RunAtLoad</key><true/>
  <key>StandardOutPath</key><string>$HOME/Library/Logs/kopifund-sync.log</string>
  <key>StandardErrorPath</key><string>$HOME/Library/Logs/kopifund-sync.log</string>
</dict>
</plist>
EOF
  cat > "$HOME/Library/LaunchAgents/com.kopifund.analyse.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by services/kopifund/setup.sh — regenerated on every re-run. -->
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>com.kopifund.analyse</string>
  <key>ProgramArguments</key>
  <array>
    <string>$STATE/bin/analyse.sh</string>
  </array>
  <key>StartInterval</key><integer>$ANALYSE_SECONDS</integer>
  <key>RunAtLoad</key><true/>
  <key>StandardOutPath</key><string>$HOME/Library/Logs/kopifund-analyse.log</string>
  <key>StandardErrorPath</key><string>$HOME/Library/Logs/kopifund-analyse.log</string>
</dict>
</plist>
EOF
  chmod 600 "$HOME/Library/LaunchAgents/com.kopifund.sync.plist" \
            "$HOME/Library/LaunchAgents/com.kopifund.analyse.plist"  # names .env-derived paths
  launchctl bootout "gui/$(id -u)/com.kopifund.sync" 2>/dev/null || true
  launchctl enable "gui/$(id -u)/com.kopifund.sync" 2>/dev/null || true
  launchctl bootstrap "gui/$(id -u)" "$HOME/Library/LaunchAgents/com.kopifund.sync.plist"
  launchctl bootout "gui/$(id -u)/com.kopifund.analyse" 2>/dev/null || true
  launchctl enable "gui/$(id -u)/com.kopifund.analyse" 2>/dev/null || true
  launchctl bootstrap "gui/$(id -u)" "$HOME/Library/LaunchAgents/com.kopifund.analyse.plist"
  ok "LaunchAgents loaded: com.kopifund.sync + com.kopifund.analyse"
fi

# -------------------------------------------- retiring the launcher app
# The old tile lives in the launcher, not here — removing it is a dashboard
# action. Warn while its definition is still on the box, and warn honestly:
# the launcher's Remove unpublishes any Serve port that proxies to the same
# target, which is exactly the :HTTPS_PORT this service now owns, so the
# publish must be re-applied once afterwards or the service goes dark.
if [ -f "$HOME/services/launcher/apps/kopifund-finance.json" ]; then
  warn "The old launcher tile (kopifund-finance) is still installed. Remove it when satisfied — launcher -> kopifund-finance -> Remove keeps its data dir, already adopted above."
  warn "  Its Remove also unpublishes :$HTTPS_PORT (the same proxy target this service owns) — re-run ./setup.sh once afterwards to put the publish back."
fi

# ---------------------------------------------------------------- deploy
COMPOSE=(docker compose --project-directory "$SERVICE_DIR")

info "Building and starting Kopifund (docker compose up -d --build)"
"${COMPOSE[@]}" up -d --build

info "Waiting for Kopifund on 127.0.0.1:$LOCAL_PORT"
wait_http "http://127.0.0.1:$LOCAL_PORT/api/health" 60 3 \
  || die "Kopifund did not come up. Logs: docker compose --project-directory $SERVICE_DIR logs kopifund"
ok "Kopifund is answering locally"

# ------------------------------------------------------- tailscale serve
info "Publishing via Tailscale Serve (HTTPS :$HTTPS_PORT, tailnet only)"
