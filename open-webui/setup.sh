#!/usr/bin/env bash
#
# setup.sh — one-shot deploy of Open WebUI (chat UI over local ollama)
# behind Tailscale. Linux + macOS.
#
# End state:
#   - Open WebUI container (host network, binds 127.0.0.1:LOCAL_PORT only)
#   - talks to the host's ollama at OLLAMA_BASE_URL
#   - published tailnet-only at https://<host>.<tailnet>.ts.net:HTTPS_PORT
#   - boot-persistent via Docker's restart policy (no systemd/launchd needed)
#
# Usage:
#   ./setup.sh                                  # local 3001, HTTPS 3001
#   LOCAL_PORT=3005 ./setup.sh                  # HTTPS follows LOCAL_PORT
#   LOCAL_PORT=3005 HTTPS_PORT=8443 ./setup.sh
#
# Requirements: Linux or macOS, curl, Docker + Compose v2, Tailscale logged
# in, and ollama running on the host (https://ollama.com).
#
# Idempotent: safe to re-run; existing .env is never overwritten.

set -euo pipefail

LOCAL_PORT="${LOCAL_PORT:-3001}"
# HTTPS follows the local port unless set explicitly (the n8n and
# kaichenpedia convention), so overriding only LOCAL_PORT cannot split the
# two. Until 2026-09-13 this defaulted to a literal 10000, chosen back when
# Tailscale Serve only allowed 443/8443/10000; that limit is long gone.
# This script never sources .env, so there is no read-back to guard.
HTTPS_PORT="${HTTPS_PORT:-$LOCAL_PORT}"
OLLAMA_BASE_URL="${OLLAMA_BASE_URL:-http://127.0.0.1:11434}"
SERVICE_DIR="$(cd "$(dirname "$0")" && pwd)"
ENV_FILE="$SERVICE_DIR/.env"

info()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
ok()    { printf '\033[1;32m ✓ \033[0m %s\n' "$*"; }
warn()  { printf '\033[1;33m ! \033[0m %s\n' "$*"; }
die()   { printf '\033[1;31m ✗ \033[0m %s\n' "$*" >&2; exit 1; }

# ---------------------------------------------------------------- preflight
OS="$(uname -s)"
info "Preflight checks ($OS)"
case "$OS" in Linux|Darwin) ;; *) die "Unsupported OS: $OS (Linux and macOS only)";; esac
[ "$(id -u)" -ne 0 ] || die "Run as a regular user, not root."
command -v curl >/dev/null || die "curl is required."
if ! command -v docker >/dev/null; then
  [ "$OS" = "Linux" ] && die "Docker is not installed. On Ubuntu: sudo apt-get install -y docker.io docker-compose-v2"
  die "Docker is not installed. On macOS install Docker Desktop or OrbStack."
fi

if command -v tailscale >/dev/null; then
  TAILSCALE="tailscale"
elif [ "$OS" = "Darwin" ] && [ -x "/Applications/Tailscale.app/Contents/MacOS/Tailscale" ]; then
  TAILSCALE="/Applications/Tailscale.app/Contents/MacOS/Tailscale"
else
  die "Tailscale is not installed: https://tailscale.com/download"
fi

if ! docker ps >/dev/null 2>&1; then
  [ "$OS" = "Linux" ] && die "Cannot talk to the Docker daemon. Fix: sudo usermod -aG docker $USER, then log out/in (or run via: sg docker -c ./setup.sh)"
  die "Cannot talk to the Docker daemon. Is Docker Desktop/OrbStack running?"
fi
docker compose version >/dev/null 2>&1 || die "Docker Compose v2 is required (docker compose)."

state="$("$TAILSCALE" status --json 2>/dev/null | grep -o '"BackendState": *"[^"]*"' | head -1 | cut -d'"' -f4 || true)"
[ "$state" = "Running" ] || die "Tailscale is not up (state: ${state:-unknown}). Run: sudo tailscale up (or open the Tailscale app)"

case "$HTTPS_PORT" in ''|*[!0-9]*) die "HTTPS_PORT must be numeric (got: $HTTPS_PORT)";; esac

# macOS note: with Docker Desktop, "host" networking + loopback ollama needs
# Docker Desktop >= 4.34 host networking support; verify after deploy.
if curl -fsS -o /dev/null --max-time 3 "$OLLAMA_BASE_URL/api/version" 2>/dev/null; then
  ok "ollama reachable at $OLLAMA_BASE_URL"
else
  warn "ollama not reachable at $OLLAMA_BASE_URL — the UI will start but have no models. Install/start ollama, or set OLLAMA_BASE_URL."
fi
ok "$OS + curl + Docker (daemon reachable) + Compose v2 + Tailscale (running)"

host="$("$TAILSCALE" status --json | grep -o '"DNSName": *"[^"]*"' | head -1 | cut -d'"' -f4 | sed 's/\.$//')"
[ -n "$host" ] || die "Could not determine tailnet DNS name (is MagicDNS enabled?)"

# ---------------------------------------------------------------- .env
if [ -f "$ENV_FILE" ]; then
  ok "Config already exists, leaving untouched: $ENV_FILE"
else
  info "Writing .env"
  cat > "$ENV_FILE" <<EOF
# Generated by setup.sh. Gitignored; mode 600.
WEBUI_IMAGE=ghcr.io/open-webui/open-webui:main
WEBUI_VOLUME=$HOME/services/open-webui/data
LOCAL_PORT=$LOCAL_PORT
OLLAMA_BASE_URL=$OLLAMA_BASE_URL
EOF
  chmod 600 "$ENV_FILE"
  ok "Wrote $ENV_FILE"
fi

mkdir -p "$HOME/services/open-webui/data"

# ---------------------------------------------------------------- deploy
info "Starting container (docker compose up -d) — first run pulls the image"
docker compose --project-directory "$SERVICE_DIR" up -d

info "Waiting for Open WebUI on 127.0.0.1:$LOCAL_PORT"
for i in $(seq 1 60); do
  if curl -fsS -o /dev/null "http://127.0.0.1:$LOCAL_PORT/health" 2>/dev/null; then
    ok "Open WebUI is answering locally"
    break
  fi
  [ "$i" -eq 60 ] && die "Open WebUI did not come up. Logs: docker compose --project-directory $SERVICE_DIR logs open-webui"
  sleep 3
done

# ------------------------------------------------------- tailscale serve
info "Publishing via Tailscale Serve (HTTPS :$HTTPS_PORT, tailnet only)"
if ! "$TAILSCALE" serve --bg --https="$HTTPS_PORT" "http://127.0.0.1:$LOCAL_PORT" >/dev/null 2>&1; then
  if [ "$OS" = "Linux" ]; then
    info "Direct serve failed — trying operator grant (needs sudo, one time)"
    sudo tailscale set --operator="$USER"
  fi
  until "$TAILSCALE" serve --bg --https="$HTTPS_PORT" "http://127.0.0.1:$LOCAL_PORT"; do
    echo
    info "If Tailscale printed an approval URL above, open it, approve, then press Enter to retry."
    read -r
  done
fi
ok "Tailscale Serve: HTTPS :$HTTPS_PORT -> http://127.0.0.1:$LOCAL_PORT"

# ------------------------------------------------------------ final check
url="https://$host:$HTTPS_PORT"
info "Verifying $url (first request can take ~60s while the TLS cert is minted)"
if curl -fsS -o /dev/null --max-time 90 "$url/health"; then
  ok "End-to-end check passed"
else
  echo "    Cert may still be minting — try again in a minute: curl $url/health"
fi

echo
printf '\033[1;32mDone.\033[0m Open WebUI is at \033[1m%s\033[0m (tailnet only).\n' "$url"
echo
echo "IMPORTANT: the first account registered becomes the admin — open the URL"
echo "and sign up now. Signups can then be disabled in Admin Panel -> Settings."
echo
echo "Manage: docker compose --project-directory $SERVICE_DIR ps|logs|restart|down"
echo "Upgrade: docker compose --project-directory $SERVICE_DIR pull && docker compose --project-directory $SERVICE_DIR up -d"
