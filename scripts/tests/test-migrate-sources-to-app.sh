check "nginx on 127.0.0.1:8098"             calls_have "--publish 127.0.0.1:8098:80"
check "nginx gets the host gateway"         calls_have "--add-host host.docker.internal:host-gateway"
check "nginx gets no .env"                  calls_lack "--env-file"
