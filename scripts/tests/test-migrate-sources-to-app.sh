check "Serve left alone (already mapped)"   calls_lack "tailscale serve --bg"
check "Serve never reset or turned off"     sh -c "! grep -E 'tailscale serve (reset|.*off)' '$CALLS_LOG'"
check "reports the downtime"                out_has "s of downtime"
