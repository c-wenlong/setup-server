#!/usr/bin/env bash
#
# Mocked tests for scripts/migrate-sources-to-app.sh. Runs the real script
# against a sandbox repo (the script, lib/common.sh and the launcher's real
# server.py + ghapp.py), a temp $HOME, and PATH stubs for docker, git, uv,
# tailscale, systemctl and uname. ghapp.py runs the definition's real build
# line through `sh -c`, so the jobs.db link step is exercised for real; `uv`
# is stubbed in ~/.local/bin, the first directory ghapp puts on a host
# build's PATH. A sitecustomize.py on PYTHONPATH answers ghapp's health
# probe of 127.0.0.1:8098 from stub state, so nothing on this machine
# (including a live site on that port) is ever contacted.
#
#   ./scripts/tests/test-migrate-sources-to-app.sh
#
# Zero changes to the host: everything lives in a temp dir, HOME included.

set -u

TESTS_DIR="$(cd "$(dirname "$0")" && pwd)"
SRC_ROOT="$(cd "$TESTS_DIR/../.." && pwd)"
PASS=0; FAIL=0
ORIG_HOME="$HOME"
ORIG_PATH="$PATH"
ORIG_PYTHONPATH="${PYTHONPATH-}"
SECRET="passphrase-TOPSECRET-123"
SHA="99d2893dc52883b589d5f0ac45336e56079cc07b"
red()   { printf '\033[1;31m%s\033[0m\n' "$*"; }
green() { printf '\033[1;32m%s\033[0m\n' "$*"; }

check() {
  local label="$1"; shift
  if "$@" >/dev/null 2>&1; then
    printf '    \033[1;32m✓\033[0m %s\n' "$label"; PASS=$((PASS + 1))
  else
    printf '    \033[1;31m✗\033[0m %s\n' "$label"; FAIL=$((FAIL + 1))
  fi
}
calls_have()  { grep -qF -- "$1" "$CALLS_LOG"; }
calls_lack()  { ! grep -qF -- "$1" "$CALLS_LOG"; }
calls_count() { grep -cF -- "$1" "$CALLS_LOG"; }
out_has()     { grep -qF -- "$1" "$OUT"; }
out_lacks()   { ! grep -qF -- "$1" "$OUT"; }
json_get()    { python3 -c 'import json,sys; d=json.load(open(sys.argv[1])); print(eval(sys.argv[2], {"d": d}))' "$1" "$2"; }
mode_of()     { stat -c %a "$1" 2>/dev/null || stat -f %Lp "$1"; }
# line number of the first call log line containing $1 (0 when absent)
call_line()   { grep -nF -- "$1" "$CALLS_LOG" | head -1 | cut -d: -f1 | sed 's/^$/0/'; }
before()      { local a b; a="$(call_line "$1")"; b="$(call_line "$2")"; [ "${a:-0}" -gt 0 ] && [ "${b:-0}" -gt 0 ] && [ "$a" -lt "$b" ]; }

# ---------------------------------------------------------------- harness
setup() {
  SB="$(mktemp -d)"
  R="$SB/repo"
  export HOME="$SB/home"
  export CALLS_LOG="$SB/calls.log"
  export STATE_DIR="$SB/state"
  export SECRET SHA
  : > "$CALLS_LOG"
  mkdir -p "$HOME/.local/bin" "$R/scripts" "$R/lib" "$R/app/web" "$SB/bin" "$SB/py" "$STATE_DIR"
  cp "$SRC_ROOT/scripts/migrate-sources-to-app.sh" "$R/scripts/"
  cp "$SRC_ROOT/lib/common.sh" "$R/lib/"
  cp "$SRC_ROOT/app/web/server.py" "$SRC_ROOT/app/web/ghapp.py" \
     "$SRC_ROOT/app/web/services.json" "$R/app/web/"

  # deployd installed, with the old manifest poller's state files.
  D="$HOME/services/deployd/state"
  mkdir -p "$D"
  echo "$SHA" > "$D/sources.sha"
  echo '{"sha": "old", "at": 1, "rc": 1}' > "$D/sources.fail"

  # The fetch clone with the daily scrape's jobs.db.
  FETCH="$SB/dev/sources"
  mkdir -p "$FETCH/data/jobs"
  echo db > "$FETCH/data/jobs/jobs.db"

  # The old deploy's leftovers: its clone home and deploy.sh copy, whose
  # baked-in ENV_FILE points at an old .env outside this repo.
  OLD_ENV="$SB/old-checkout/services/sources/.env"
  mkdir -p "$HOME/services/sources/bin" "$HOME/services/sources/www" "$(dirname "$OLD_ENV")"
  printf '#!/usr/bin/env bash\nENV_FILE="%s"\n' "$OLD_ENV" \
    > "$HOME/services/sources/bin/deploy.sh"
  printf '# Generated by setup.sh\nexport SOURCE_REPO=%s # fetch clone\nLOCAL_PORT=8098\nSITE_PASSPHRASE='"'"'%s'"'"'\n' \
    "$FETCH" "$SECRET" > "$OLD_ENV"

  # The installed deployd binary, whose baked-in .env agrees with the
  # default state dir this checkout resolves.
  mkdir -p "$HOME/services/deployd/bin" "$SB/deployd-checkout/services/deployd"
  printf 'SETUP_REPO=%s\nSERVICE_HOME=%s\n' "$SB/deployd-checkout" "$HOME/services/deployd" \
    > "$SB/deployd-checkout/services/deployd/.env"
  printf '#!/usr/bin/env python3\nENV_BAKED = "%s"  # setup.sh rewrites this\n' \
    "$SB/deployd-checkout/services/deployd/.env" > "$HOME/services/deployd/bin/deployd"
  export SANDBOX_SCRIPT="$R/scripts/migrate-sources-to-app.sh"

  # The trigger's unit, as installed on the box.
  mkdir -p "$HOME/.config/systemd/user"
  printf '[Service]\nExecStart=/usr/bin/python3 %s/apps/pipeline/fetch_trigger_server.py\n' "$FETCH" \
    > "$HOME/.config/systemd/user/sources-trigger.service"

  # The running old container.
  touch "$STATE_DIR/old-exists" "$STATE_DIR/old-running" "$STATE_DIR/network"

  cat > "$SB/bin/docker" <<'STUB'
#!/usr/bin/env bash
echo "docker $*" >> "$CALLS_LOG"
S="$STATE_DIR"
fmt=""; name=""
args=("$@")
for ((i = 1; i < ${#args[@]}; i++)); do
  case "${args[$i]}" in
    --format) fmt="${args[$((i + 1))]}"; i=$((i + 1)) ;;
    --filter) i=$((i + 1)) ;;
    -*) ;;
    *) name="${args[$i]}" ;;
  esac
done
exists()  { case "$1" in sources) [ -f "$S/old-exists" ] ;; app-sources) [ -f "$S/new-exists" ] ;; *) false ;; esac; }
case "$1" in
  info) exit 0 ;;
  inspect)
    exists "$name" || exit 1
    case "$fmt" in
      *State.Running*)
        if [ "$name" = sources ]; then [ -f "$S/old-running" ] && echo true || echo false
        else [ -f "$S/new-stopped" ] && echo false || echo true; fi ;;
      *.Image*) echo "sha256:0123456789abcdef0123456789abcdef" ;;
    esac ;;
  ps)
    for n in sources app-sources; do
      exists "$n" && case "$*" in *"^/$n\$"*) echo "$n" ;; esac
    done; exit 0 ;;
  stop) rm -f "$S/old-running" ;;
  start) [ "$2" = sources ] && touch "$S/old-running" ;;
  rm)
    for n in "${@:2}"; do
      case "$n" in
        sources) rm -f "$S/old-exists" "$S/old-running" ;;
        app-sources) rm -f "$S/new-exists" ;;
      esac
    done ;;
  pull) exit 0 ;;
  run)
    if [ -f "$S/interrupt-run" ]; then pkill -TERM -f "$SANDBOX_SCRIPT"; command -p sleep 1; exit 125; fi
    [ -f "$S/fail-run" ] && { echo "port is already allocated" >&2; exit 125; }
    [ -f "$S/old-running" ] && { echo "port 8098 still held by sources" >&2; exit 125; }
    touch "$S/new-exists"; echo cid ;;
  image) exit 0 ;;
  network)
    case "$2" in
      inspect) [ -f "$S/network" ] ;;
      rm) rm -f "$S/network" ;;
    esac ;;
  logs) echo "container log" ;;
esac
exit 0
STUB

  cat > "$SB/bin/git" <<'STUB'
#!/usr/bin/env bash
echo "git $*" >> "$CALLS_LOG"
if [ "$1" = ls-remote ]; then printf '%s\trefs/heads/main\n' "$SHA"; exit 0; fi
if [ "$1" = clone ]; then dest="${*: -1}"; mkdir -p "$dest/.git"; exit 0; fi
if [ "$1" = -C ] && [ "$3" = checkout ]; then
  [ -f "$STATE_DIR/fail-checkout" ] && exit 1
  mkdir -p "$2/apps/web/build"
fi
exit 0
STUB

  # uv: `uv sync` is a no-op; `uv run ... --out DIR` writes a site there
  # and records what data/jobs/jobs.db is at build time.
  cat > "$HOME/.local/bin/uv" <<'STUB'
#!/usr/bin/env bash
echo "uv $* (cwd $(pwd))" >> "$CALLS_LOG"
[ "$1" = run ] || exit 0
[ -f "$STATE_DIR/fail-build" ] && { echo "build failed" >&2; exit 1; }
if [ -L data/jobs/jobs.db ]; then echo "jobs.db -> $(readlink data/jobs/jobs.db)" >> "$CALLS_LOG"
else echo "jobs.db absent" >> "$CALLS_LOG"; fi
out="${*: -1}"
mkdir -p "$out" && echo "<html>sources</html>" > "$out/index.html"
STUB

  cat > "$SB/bin/tailscale" <<'STUB'
#!/usr/bin/env bash
echo "tailscale $*" >> "$CALLS_LOG"
if [ "$1 $2" = "serve status" ]; then
  echo '{"Web": {"box.ts.net:8098": {"Handlers": {"/": {"Proxy": "http://127.0.0.1:8098"}}}, "box.ts.net:443": {"Handlers": {"/": {"Proxy": "http://127.0.0.1:8098"}}}}}'
fi
exit 0
STUB

  # systemctl: logs every call; a busy sources-manual-* unit shows while
  # $STATE_DIR/manual-busy holds a count above zero (each list-units call
  # counts it down), or forever with manual-busy-forever.
  cat > "$SB/bin/systemctl" <<'STUB'
#!/usr/bin/env bash
echo "systemctl $*" >> "$CALLS_LOG"
case "$*" in
  *list-units*sources-manual-*)
    if [ -f "$STATE_DIR/manual-busy-forever" ]; then echo "sources-manual-redeploy.service loaded active running x"; exit 0; fi
    n="$(cat "$STATE_DIR/manual-busy" 2>/dev/null || echo 0)"
    if [ "$n" -gt 0 ]; then echo $((n - 1)) > "$STATE_DIR/manual-busy"; echo "sources-manual-fetch.service loaded active running x"; fi
    exit 0 ;;
  *restart*) [ -f "$STATE_DIR/fail-restart" ] && exit 1; exit 0 ;;
esac
exit 0
STUB
  printf '#!/usr/bin/env bash\necho "sleep $*" >> "$CALLS_LOG"\n' > "$SB/bin/sleep"
  printf '#!/usr/bin/env bash\ncase "$1" in -s) echo Linux ;; -m) echo x86_64 ;; *) echo Linux ;; esac\n' > "$SB/bin/uname"
  chmod +x "$SB/bin/"* "$HOME/.local/bin/uv"

  # ghapp's health probe: answers only while the new container "runs".
  cat > "$SB/py/sitecustomize.py" <<'PY'
import os
import urllib.error
import urllib.request

_real = urllib.request.urlopen


class _Resp(object):
    status = 200

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        return False


def _urlopen(url, *a, **kw):
    target = url if isinstance(url, str) else url.get_full_url()
    if target.startswith("http://127.0.0.1:"):
        if os.path.exists(os.path.join(os.environ["STATE_DIR"], "new-exists")):
            return _Resp()
        raise urllib.error.URLError("refused")
    return _real(url, *a, **kw)


urllib.request.urlopen = _urlopen
PY
  export PYTHONPATH="$SB/py"
  export PATH="$SB/bin:$ORIG_PATH"
}

teardown() {
  rm -rf "$SB"
  export HOME="$ORIG_HOME"
  export PATH="$ORIG_PATH"
  if [ -n "$ORIG_PYTHONPATH" ]; then export PYTHONPATH="$ORIG_PYTHONPATH"; else unset PYTHONPATH; fi
  unset CALLS_LOG STATE_DIR
}

migrate() { OUT="$SB/out.log"; "$R/scripts/migrate-sources-to-app.sh" "$@" > "$OUT" 2>&1; CODE=$?; }

