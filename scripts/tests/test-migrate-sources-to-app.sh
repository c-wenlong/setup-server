check "config sends no-cache"               sh -c "grep -q 'add_header Cache-Control \"no-cache\";' '$HOME'/services/apps/sources/site-*.nginx.conf"
check "release holds the built site"        sh -c "grep -q sources '$HOME'/services/apps/sources/site-*/index.html"
check "old container removed"               calls_have "docker rm --force sources"
