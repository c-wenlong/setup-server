#!/usr/bin/env python3
"""build-registry.py — generate app/web/services.json from per-service manifests.

    python3 scripts/build-registry.py           # rewrite app/web/services.json
    python3 scripts/build-registry.py --check   # exit 1 if it is out of date

Inputs:

  services/<dir>/app.json   one tile (a JSON object) or several (a list), for
                            the service that folder deploys. `setup` is never
                            written here: it is always services/<dir>/setup.sh.
                            A relative `env` (".env") is relative to the folder.
  app/web/registry.json     the file-level parts: `_comment` (the field
                            reference), `groups`, `control`, `order` (tile
                            order, which is the launcher's tie-break inside a
                            group), and `external` (tiles with no folder in
                            this repo: code that lives elsewhere, or planned).

Output: app/web/services.json, the file the launcher and ntfy-control read at
runtime. It is generated and committed, so a checkout works with no build
step; `--check` (run by `make lint`) keeps it from drifting. Stdlib only, and
Python 3.9 like the launcher.
"""

import json
import os
import sys

ROOT = os.path.realpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
BASE = os.path.join("app", "web", "registry.json")
OUT = os.path.join("app", "web", "services.json")
MANIFEST = "app.json"

GENERATED = [
    "GENERATED by scripts/build-registry.py: do not edit by hand.",
    "Edit services/<dir>/app.json (one service) or app/web/registry.json",
    "(groups, control, order, external tiles), then run the script.",
]


class RegistryError(Exception):
    pass


def _load(path):
    try:
        with open(os.path.join(ROOT, path), encoding="utf-8") as fh:
            return json.load(fh)
    except ValueError as exc:
        raise RegistryError("%s is not valid JSON: %s" % (path, exc))


def _from_manifest(folder, entry):
    """One manifest entry -> one services.json entry, with setup/env filled in."""
    if not isinstance(entry, dict) or not entry.get("key"):
        raise RegistryError("services/%s/%s: every entry needs a \"key\"" % (folder, MANIFEST))
    if "setup" in entry:
        raise RegistryError(
            "services/%s/%s (%s): drop \"setup\", it is always services/%s/setup.sh"
            % (folder, MANIFEST, entry["key"], folder))
    out = {}
    for name, value in entry.items():
        if name == "env" and isinstance(value, str) and not value.startswith(("/", "~")):
            value = "services/%s/%s" % (folder, value)
        if name == "env":
            # setup sits just before env, which is where the hand-written
            # file had it; keeps the generated file diffable against history.
            out["setup"] = "services/%s/setup.sh" % folder
        out[name] = value
    out.setdefault("setup", "services/%s/setup.sh" % folder)
    return out


def build():
    base = _load(BASE)
    for field in ("groups", "control", "order", "external"):
        if field not in base:
            raise RegistryError("%s is missing \"%s\"" % (BASE, field))

    entries = {}

    def add(entry, where):
        key = entry.get("key")
        if not key:
            raise RegistryError("%s: an entry has no \"key\"" % where)
        if key in entries:
            raise RegistryError("duplicate key %r (%s and %s)" % (key, entries[key][1], where))
        entries[key] = (entry, where)

    services_dir = os.path.join(ROOT, "services")
    for folder in sorted(os.listdir(services_dir)):
        path = os.path.join("services", folder, MANIFEST)
        if not os.path.isfile(os.path.join(ROOT, path)):
            continue
        data = _load(path)
        for entry in data if isinstance(data, list) else [data]:
            add(_from_manifest(folder, entry), path)
    for entry in base["external"]:
        add(entry, BASE + " external")

    groups = {g["id"] for g in base["groups"]}
    for key, (entry, where) in entries.items():
        if entry.get("group") not in groups:
            raise RegistryError("%s (%s): group %r is not in %s groups"
                                % (where, key, entry.get("group"), BASE))

    order = base["order"]
    missing = [k for k in entries if k not in order]
    unknown = [k for k in order if k not in entries]
    dupes = sorted({k for k in order if order.count(k) > 1})
    if missing:
        raise RegistryError("add to \"order\" in %s: %s" % (BASE, ", ".join(missing)))
    if unknown:
        raise RegistryError("\"order\" in %s names keys with no entry: %s" % (BASE, ", ".join(unknown)))
    if dupes:
        raise RegistryError("\"order\" in %s repeats: %s" % (BASE, ", ".join(dupes)))

    registry = {
        "_comment": GENERATED + list(base.get("_comment", [])),
        "groups": base["groups"],
        "control": base["control"],
        "services": [entries[k][0] for k in order],
    }
    return json.dumps(registry, indent=2, ensure_ascii=False) + "\n"


def main(argv):
    check = argv[1:] == ["--check"]
    if argv[1:] not in ([], ["--check"]):
        print("usage: %s [--check]" % argv[0], file=sys.stderr)
        return 2
    try:
        text = build()
    except RegistryError as exc:
        print("build-registry: %s" % exc, file=sys.stderr)
        return 1
    out = os.path.join(ROOT, OUT)
    try:
        with open(out, encoding="utf-8") as fh:
            current = fh.read()
    except OSError:
        current = None
    if check:
        if current != text:
            print("build-registry: %s is out of date; run python3 scripts/build-registry.py" % OUT,
                  file=sys.stderr)
            return 1
        print("registry OK: %s matches the manifests" % OUT)
        return 0
    if current != text:
        # Temp file + rename: the launcher re-reads services.json on every
        # request, so it must never see a truncated or half-written file.
        tmp = out + ".tmp"
        with open(tmp, "w", encoding="utf-8") as fh:
            fh.write(text)
        os.replace(tmp, out)
        print("wrote %s" % OUT)
    else:
        print("%s already up to date" % OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
